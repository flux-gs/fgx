#!/usr/bin/env python3
"""Generate the syscall catalog table in docs/userland-abi.md from loader.s.

include/loader.s is the single source of truth for syscall numbers, names, and
their ABI (described in the EQU comments).  This regenerates the table between
the BEGIN/END GENERATED markers in docs/userland-abi.md §4.3 so it can never go
stale: add a SYS_* EQU (with a describing comment) to loader.s and the table
picks it up.  build.sh runs `--check` as a gate, so a drifted table fails the
build.

Usage:
  gen_syscall_table.py            # rewrite the table in docs/userland-abi.md
  gen_syscall_table.py --check    # exit 1 if the table is out of date (gate)
"""
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
LOADER = REPO / "include" / "loader.s"
DOC = REPO / "docs" / "userland-abi.md"

BEGIN = ("<!-- BEGIN GENERATED: syscall-table (regenerated by "
         "tools/gen_syscall_table.py from include/loader.s — do not edit by hand) -->")
END = "<!-- END GENERATED: syscall-table -->"

# A real syscall: SYS_<NAME> EQU <decimal>.  (SYS_NUM_MAX EQU SYS_PROCS is
# symbolic, not a syscall, and is skipped by the \d+ requirement.)
SYS_RE = re.compile(r'^(SYS_[A-Z0-9_]+)\s+G?EQU\s+(\d+)\b(.*)$')
# An indented continuation comment (leading whitespace, then ';').  A column-0
# ';...' separator or a new label does NOT match, so it ends the run.
CONT_RE = re.compile(r'^\s+;\s?(.*)$')
INLINE_COMMENT_RE = re.compile(r';\s?(.*)$')


def parse_syscalls():
    lines = LOADER.read_text().splitlines()
    rows = []
    i = 0
    while i < len(lines):
        m = SYS_RE.match(lines[i])
        if not m:
            i += 1
            continue
        name, num, rest = m.group(1), int(m.group(2)), m.group(3)
        parts = []
        cm = INLINE_COMMENT_RE.search(rest)
        if cm and cm.group(1).strip():
            parts.append(cm.group(1).strip())
        j = i + 1
        while j < len(lines):
            c = CONT_RE.match(lines[j])
            if not c:
                break
            parts.append(c.group(1).strip())
            j += 1
        desc = re.sub(r'\s+', ' ', " ".join(p for p in parts if p)).strip()
        rows.append((num, name, desc))
        i = j
    rows.sort(key=lambda r: r[0])
    return rows


def render(rows):
    def esc(s):
        return s.replace("|", "\\|")
    out = [BEGIN,
           "| # | Name | Description (from `include/loader.s`) |",
           "|---|------|--------------------------------------|"]
    for num, name, desc in rows:
        out.append(f"| {num} | `{name}` | {esc(desc) if desc else '—'} |")
    out.append(END)
    return "\n".join(out)


def _selftest():
    """Prove --check can actually FAIL.

    This gate compares a rendered table against a committed one and passes when
    they match -- so a parse that returns zero syscalls renders an empty table,
    which matches nothing and would report drift... or, worse, a comparison bug
    makes everything match and the gate never fires again.  Test both ends:
    the parse must find syscalls, and a perturbed render must NOT compare equal.
    """
    fails = 0
    rows = parse_syscalls()
    if len(rows) < 20:
        print(f"  SELFTEST FAIL: parsed only {len(rows)} syscalls from loader.s "
              f"-- the gate would be comparing an empty table")
        fails += 1
    a = render(rows)
    if not a.strip():
        print("  SELFTEST FAIL: render() produced nothing")
        fails += 1
    # A single dropped row must change the rendering -- i.e. the comparison the
    # gate performs is actually sensitive to the data.
    if len(rows) > 1 and render(rows[:-1]) == a:
        print("  SELFTEST FAIL: dropping a syscall did not change the render "
              "-- --check could never detect drift")
        fails += 1
    if fails:
        print(f"gen_syscall_table self-test: {fails} FAILURE(S)")
        return 1
    print(f"gen_syscall_table self-test: OK ({len(rows)} syscalls parsed, "
          f"render is drift-sensitive)")
    return 0



def _check_num_max(rows):
    """SYS_NUM_MAX must name the highest SYS_* number, or that syscall is dead.

    Returns 0 if it does, 1 otherwise.  `rows` is (number, name, desc) triples.
    """
    text = (REPO / "include" / "loader.s").read_text()
    m = re.search(r"^SYS_NUM_MAX\s+EQU\s+(\w+)", text, re.M)
    if not m:
        sys.stderr.write("error: include/loader.s defines no SYS_NUM_MAX -- the "
                         "dispatcher range-checks against it, so this check "
                         "cannot be skipped.\n")
        return 1
    named = m.group(1)
    highest_n, highest_name = max(rows, key=lambda r: r[0])[:2]
    if named != highest_name:
        sys.stderr.write(
            f"error: SYS_NUM_MAX names {named}, but the highest syscall is "
            f"{highest_name} ({highest_n}).\n"
            f"  Every number above SYS_NUM_MAX returns ENOSYS from the "
            f"dispatcher, however correct its table entry looks.\n"
            f"  Fix: SYS_NUM_MAX EQU {highest_name}\n")
        return 1
    return 0

def main():
    if "--self-test" in sys.argv:
        return _selftest()

    check = "--check" in sys.argv
    rows = parse_syscalls()
    block = render(rows)
    doc = DOC.read_text()
    bi = doc.find(BEGIN)
    ei = doc.find(END)
    if bi < 0 or ei < 0:
        sys.stderr.write(f"error: BEGIN/END GENERATED markers not found in {DOC}\n")
        return 1
    new_doc = doc[:bi] + block + doc[ei + len(END):]
    if check:
        if new_doc != doc:
            sys.stderr.write(
                "error: docs/userland-abi.md syscall table is OUT OF DATE vs "
                "include/loader.s.\n  Run: python3 tools/gen_syscall_table.py\n")
            return 1
        # THE TABLE BEING IN SYNC IS NOT THE SAME AS THE SYSCALL BEING REACHABLE.
        # The dispatcher range-checks against SYS_NUM_MAX (syscall.s:
        # `CMP #SYS_NUM_MAX+1`), so a number above it returns ENOSYS however
        # correct its table entry looks.  This check reported "in sync"
        # throughout while umask, added at 104 with SYS_NUM_MAX still naming
        # 103, was unreachable -- and libc handed ENOSYS back as the mask,
        # because BSD's umask has no failure return to check.
        rc = _check_num_max(rows)
        if rc:
            return rc
        print(f"syscall table OK: {len(rows)} syscalls, in sync with include/loader.s"
              f"; SYS_NUM_MAX covers the highest ({max(r[0] for r in rows)})")
        return 0
    DOC.write_text(new_doc)
    print(f"wrote {len(rows)} syscalls to {DOC.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
