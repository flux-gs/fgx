#!/usr/bin/env python3
"""gen_fcc_rt -- toolchain/lib/fcc_runtime.s -> src/kernel/far/fcc_rt.s.

fcc lowers a great deal to helper calls -- even `i != 4` becomes `_fcc_ne16` --
so kernel C cannot execute so much as a loop unless the far bank carries fcc's
runtime.  It cannot carry the whole file: the first three routines
(_fcc_sfoflow, _fcc_stkoflow, _fcc_safepoint) reach SYS_EXIT and SYS_YIELD
through SYS_TRAMP, and a kernel cannot make a syscall against itself.  Those
three get kernel replacements in src/kernel/far/fcc_ktrap.s.

EVERYTHING FROM _fcc_mul16 ONWARD IS PURE COMPUTATION -- measured, not assumed:
across that region there is not one JSR/JSL/JMP to a non-_fcc_ symbol and not
one reference to libc, args, console or SYS_*.  So the boundary is a single
point in one file, and this extracts from it.

Copying the arithmetic by hand instead would put two divergent implementations
of signed division in one system, which is the kind of difference that shows up
as a filesystem returning the wrong block number.

Usage:  gen_fcc_rt.py <fcc_runtime.s> <out.s>
        gen_fcc_rt.py --self-test
"""
import os
import re
import sys

# The extraction boundary.  Named, not a line number, so the routine moving
# within the file re-resolves instead of silently taking the wrong region.
FIRST = "_fcc_mul16"

# Routines the kernel must NOT take: they exit or yield through a syscall.
# Named here so that if one is ever moved BELOW the boundary, this fails
# instead of quietly emitting a kernel that syscalls itself.
SYSCALL_ROUTINES = ("_fcc_sfoflow", "_fcc_stkoflow", "_fcc_safepoint")

# What "pure" means, checked on the extracted text rather than trusted.
FORBIDDEN = re.compile(r"\b(SYS_TRAMP|SYS_EXIT|SYS_YIELD|SYS_[A-Z][A-Z0-9_]*)\b")
CALL = re.compile(r"^\s+(?:JSR|JSL|JML|JMP)\s+([A-Za-z_][A-Za-z0-9_]*)")

HEADER = """\
;==============================================================================
; fcc_rt.s - fcc's runtime helpers, for KERNEL C.
;
; GENERATED by tools/gen_fcc_rt.py from toolchain/lib/fcc_runtime.s, starting at
; {first}.  Do NOT hand-edit: a second implementation of signed division
; is the kind of divergence that surfaces as a filesystem returning the wrong
; block number.
;
; The three routines ABOVE the extraction point are omitted deliberately -- they
; exit or yield through SYS_TRAMP, which a kernel cannot do to itself.  Their
; kernel replacements are in src/kernel/far/fcc_ktrap.s.
;
; Everything here is DBR-relative for its scratch, so it runs only with DBR set
; to the far bank -- which is what the _fw_ shim around each C entry point
; establishes.
;==============================================================================

"""


def extract(text, first=FIRST):
    """Return the runtime text from `first`'s comment header to end of file."""
    lines = text.split("\n")
    idx = None
    for i, ln in enumerate(lines):
        if re.match(rf"^{re.escape(first)}\s+MX\b", ln):
            idx = i
            break
    if idx is None:
        raise SystemExit(
            f"gen_fcc_rt: no `{first}` routine in the fcc runtime -- it was "
            f"renamed or reformatted, and the extraction boundary is gone. "
            f"Fix this parser rather than guessing a line number.")
    # Take the banner comment that documents it, too.
    while idx > 0 and lines[idx - 1].startswith(";"):
        idx -= 1
    return "\n".join(lines[idx:])


def impurities(body):
    """Every reason the extracted region is not safe to link into a kernel."""
    bad = []
    for n, ln in enumerate(body.split("\n"), 1):
        if ln.lstrip().startswith(";"):
            continue
        m = FORBIDDEN.search(ln)
        if m:
            bad.append(f"line {n} references {m.group(1)}: {ln.strip()}")
        c = CALL.match(ln)
        if c and not c.group(1).startswith(("_fcc_", "@")):
            bad.append(f"line {n} calls out to {c.group(1)}: {ln.strip()}")
    return bad


def main(argv):
    if "--self-test" in argv:
        return _selftest()
    if len(argv) != 2:
        print(__doc__.rstrip(), file=sys.stderr)
        return 2
    src, out = argv
    whole = open(src, errors="replace").read()
    body = extract(whole)

    # THE BOUNDARY IS CHECKED, NOT TRUSTED.  A syscall routine that drifted
    # below _fcc_mul16 would otherwise be extracted straight into the kernel.
    for name in SYSCALL_ROUTINES:
        if re.search(rf"^{re.escape(name)}\s+MX\b", body, re.MULTILINE):
            raise SystemExit(
                f"gen_fcc_rt: {name} now sits BELOW {FIRST} and would be "
                f"extracted into the kernel, where its syscall cannot work. "
                f"Move it back above the boundary, or give it a kernel "
                f"replacement in src/kernel/far/fcc_ktrap.s and add it to "
                f"SYSCALL_ROUTINES.")
    bad = impurities(body)
    if bad:
        raise SystemExit(
            "gen_fcc_rt: the extracted region is no longer self-contained:\n  "
            + "\n  ".join(bad)
            + "\nA kernel cannot follow these. Move the routine above the "
              "boundary or give it a kernel replacement.")

    text = HEADER.format(first=FIRST) + body
    if not text.endswith("\n"):
        text += "\n"
    try:
        if open(out).read() == text:
            return 0
    except FileNotFoundError:
        pass
    with open(out, "w") as f:
        f.write(text)
    n = len(re.findall(r"^_fcc_[a-z0-9_]+\s+MX\b", body, re.MULTILINE))
    print(f"gen_fcc_rt: wrote {os.path.basename(out)} ({n} helper routines)")
    return 0


def _selftest():
    """Prove the purity check can FAIL.  An extractor that accepts anything
    would happily put a syscall in the kernel."""
    fails = []
    clean = ("_fcc_mul16      MX      %00\n"
             "                JSR     _fcc_helper\n"
             "                RTS\n")
    if impurities(clean):
        fails.append("clean arithmetic was reported as impure")
    if not impurities(clean + "                JSL     SYS_TRAMP\n"):
        fails.append("a SYS_TRAMP call was not caught -- this is the exact "
                     "thing a kernel cannot do")
    if not impurities(clean + "                JSR     _lc_printf\n"):
        fails.append("a call out to libc was not caught")
    # A comment mentioning a syscall is documentation, not a dependency.
    if impurities(clean + "; the userland copy uses SYS_EXIT here\n"):
        fails.append("a comment mentioning SYS_EXIT was treated as a call")
    # The boundary must be found by NAME, and its banner comment taken with it.
    body = extract("; banner\n_fcc_mul16      MX      %00\n                RTS\n")
    if not body.startswith("; banner"):
        fails.append("the routine's banner comment was not extracted with it")
    if "_fcc_stkoflow" in body:
        fails.append("text above the boundary leaked into the extract")
    try:
        extract("nothing here at all\n")
        fails.append("a runtime with no boundary routine extracted anyway")
    except SystemExit:
        pass
    if fails:
        for f in fails:
            print(f"  {f}", file=sys.stderr)
        print(f"gen_fcc_rt self-test: {len(fails)} FAILURE(S)")
        return 1
    print("gen_fcc_rt self-test: OK (finds the boundary by name, keeps its "
          "banner, rejects a syscall or a libc call in the extracted region, "
          "and does not mistake a comment for either)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]) or 0)
