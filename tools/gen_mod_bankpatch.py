#!/usr/bin/env python3
"""gen_mod_bankpatch.py -- the bank-byte patch table for a single-bank image's
&function cells: an FGXM module's MOD_FN_PTR, or a kernel bank's KFAR_FN_PTR.

WHY THIS EXISTS (apple/fgx#173).  fcc's `--module-bank` emits every &function
data cell as `MOD_FN_PTR`: two bytes of in-bank offset, a bank byte, a pad.
The offset needs no linker -- a module is one Merlin invocation -- but the bank
byte cannot be assembled, because a module's bank is chosen by Bank_Alloc at
load time.

It CAN be written at run time, and that is the whole difference from the kernel
far bank.  `PHK` inside `mod_init` yields the module's own bank.  So this tool
scans the built listing for the cells, writes the address of each cell's bank
byte into `<module>/fnptr_patchsites.s`, and `_Mod_StampFnPtrs` (kc_sys.s)
walks that table at init.

MOD_FN_PTR AND KFAR_FN_PTR ARE THE SAME FOUR BYTES, and one run matches only
the one --macro names.  A module is stamped by _Mod_StampFnPtrs from mod_init;
the far and tty kernel banks by Far_BankInit and Tty_BankInit, which PHK their
own bank the same way.  The names differ because a listing scan has no other
way to tell which image's table a cell belongs in.

THE TABLE IS PUT LAST, DELIBERATELY.  It is the only output whose size depends
on the scan, so placing it after every cell it describes keeps those cells'
addresses fixed and makes one regeneration converge.  Put it earlier and the
tool would chase its own tail.

Usage:
  gen_mod_bankpatch.py <listing> <out.s> --bank 07            # write
  gen_mod_bankpatch.py <listing> <out.s> --bank 07 --allow-empty
  gen_mod_bankpatch.py <listing> <out.s> --bank 07 --check    # gate: 1 on drift
  gen_mod_bankpatch.py <listing> <out.s> --bank 08 --macro KFAR_FN_PTR
  gen_mod_bankpatch.py --self-test
"""
import re
import sys

HEADER = "; GENERATED by tools/gen_mod_bankpatch.py from the image listing -- do not edit.\n"

# A Merlin listing row for a macro INVOCATION carries the invocation address and
# the macro name.  The `Macro` column keeps the macro's own DEFINITION (which
# mentions MOD_FN_PTR in a comment and a MAC directive) out of the match.
def site_re(bank, macro="MOD_FN_PTR"):
    return re.compile(
        r"\|\s*Macro\s*\|.*\|\s*%s/([0-9A-F]{4})\s*\|.*\b%s\b" % (bank, macro))


def parse_listing(path, bank, macro="MOD_FN_PTR"):
    """Every such cell's BANK-BYTE address (cell + 2), in listing order."""
    rx = site_re(bank, macro)
    out = []
    with open(path, errors="replace") as f:
        for line in f:
            m = rx.search(line)
            if m:
                out.append((int(m.group(1), 16) + 2) & 0xFFFF)
    return out


def render(sites, bank):
    L = [HEADER,
         ";\n",
         "; One entry per &function cell in this image: the address of the cell's\n",
         "; BANK BYTE.  The image's init writes PHK -- its own runtime bank -- into\n",
         "; each, once, before any C runs.\n",
         ";\n",
         "; Bank ordinal %s.  Addresses are bank-relative, which is what a label in a\n" % bank,
         "; single-bank image already is.\n",
         "\n",
         "_modFnPtrTab    ANOP\n"]
    for a in sites:
        L.append("                DA      $%04X\n" % a)
    L.append("_modFnPtrBytes  EQU     %d      ; %d cell(s), 2 bytes of table each\n"
             % (len(sites) * 2, len(sites)))
    return "".join(L)


def die(msg):
    sys.stderr.write("gen_mod_bankpatch: %s\n" % msg)
    sys.exit(1)


def _selftest():
    """Prove the scanner SEES a cell, IGNORES the macro definition and the
    far-bank spelling, and that --check is drift-sensitive."""
    rx = site_re("07")
    hit = ("  913 | 20   ufs_vnops.data.s   9 | Macro  | 00 |  | 0 "
           "| 07/2BAE  | ufs_vnodeops   MOD_FN_PTR  _Fa;ufs_enotsup")
    assert rx.search(hit), "scanner blind to a real cell"

    # The macro's own definition and comment must NOT match: they are Directive
    # and Comment rows, and they live at 07/0000.
    for miss in (
        "  916 |  4  macros.s  842 | Directive | 00 |  | 0 | 07/0000 | MOD_FN_PTR  MAC",
        "  895 |  4  macros.s  819 | Comment   | 00 |  | 0 | 07/0000 | ; MOD_FN_PTR - a 4-byte",
        # the far-bank spelling shares the layout and must never be stamped
        "  913 | 20  x.data.s  9 | Macro | 00 |  | 0 | 07/2BAE | t  KFAR_FN_PTR  _Fa;f",
        # another bank's cell is another module's business
        "  913 | 20  x.data.s  9 | Macro | 00 |  | 0 | 06/2BAE | t  MOD_FN_PTR  _Fa;f",
    ):
        assert not rx.search(miss), "scanner matched %r" % miss

    # ...and the kernel-bank spelling is found when asked for, and only then.
    krx = site_re("08", "KFAR_FN_PTR")
    assert krx.search("  9 | 36  v.data.s  9 | Macro | 00 |  | 0 "
                      "| 08/1234 | vnops  KFAR_FN_PTR _Fa;vn_read"), \
        "scanner blind to a kernel-bank cell"
    assert not krx.search("  9 | 36  v.data.s  9 | Macro | 00 |  | 0 "
                          "| 08/1234 | t  MOD_FN_PTR _Fa;f"), \
        "a kernel-bank scan matched a module cell"

    # +2 is the bank byte, not the cell.
    assert render([0x2BB0], "07").count("DA      $2BB0") == 1
    assert "_modFnPtrBytes  EQU     2" in render([0x2BB0], "07")
    assert "_modFnPtrBytes  EQU     0" in render([], "07")
    # drift: a different site set must render differently, or --check is vacuous
    assert render([0x2BB0], "07") != render([0x2BB2], "07")

    # AND THE REFUSAL.  A wrong ordinal finds nothing; writing that table would
    # be silent and total, so main() must die rather than render it.  Proven by
    # calling the real path against a listing row at a DIFFERENT ordinal.
    import tempfile, os as _os
    row = ("  913 | 20  x.data.s  9 | Macro | 00 |  | 0 "
           "| 07/2BAE | t  MOD_FN_PTR  _Fa;f\n")
    fd, lst = tempfile.mkstemp()
    _os.write(fd, row.encode()); _os.close(fd)
    out = lst + ".s"
    assert parse_listing(lst, "07"), "self-test listing has no cell at 07"
    assert not parse_listing(lst, "06"), "ordinal filter is not filtering"
    rc = "no die"
    try:
        _argv = sys.argv
        sys.argv = ["x", lst, out, "--bank", "06"]
        main()
    except SystemExit as e:
        rc = e.code
    finally:
        sys.argv = _argv
        for f in (lst, out):
            try: _os.unlink(f)
            except OSError: pass
    assert rc == 1, "an empty table was written instead of refused (%r)" % rc
    print("gen_mod_bankpatch: self-test OK")
    return 0


def main():
    if "--self-test" in sys.argv:
        return _selftest()
    argv = sys.argv[1:]
    check = "--check" in argv
    allow_empty = "--allow-empty" in argv
    argv = [a for a in argv if a not in ("--check", "--allow-empty")]
    bank = "05"
    if "--bank" in argv:
        i = argv.index("--bank")
        bank = argv[i + 1]
        del argv[i:i + 2]
    macro = "MOD_FN_PTR"
    if "--macro" in argv:
        i = argv.index("--macro")
        macro = argv[i + 1]
        del argv[i:i + 2]
    if len(argv) != 2:
        die("usage: gen_mod_bankpatch.py <listing> <out.s> --bank NN [--check]")
    listing, out = argv
    sites = parse_listing(listing, bank, macro)

    # AN EMPTY TABLE IS THE ONE OUTPUT THAT CANNOT BE TRUSTED, so it is refused
    # rather than written.  It is what a WRONG --bank produces: the scan matches
    # on the ordinal, so asking for an ordinal this module does not use finds
    # nothing at all.  Written out, that table then passes --check forever --
    # and every &function cell in the module keeps a bank byte of 0, so every
    # dispatch through one targets bank $00.  The failure is silent and total,
    # and the message the check would print tells you to regenerate with the
    # same wrong bank.
    #
    # gen.py holds the module->ordinal map and each module's .s holds an `ERR
    # MODP_ORG/$10000-$xx` guard; this makes a drift between them LOUD instead
    # of letting one of the two win quietly.
    if not sites and not allow_empty:
        die("no %s cells found in %s at bank ordinal %s.\n"
            "  Either --bank is wrong for this module (check MODP_ORG in\n"
            "  src/modules/<m>/modplace.s), or its C is not compiled\n"
            "  --module-bank (check the `modulec_bank` rule in\n"
            "  tools/ninja/gen.py).  Writing the empty table would leave every\n"
            "  function pointer in the module dispatching to bank $00.\n"
            "  Pass --allow-empty if this module genuinely has no &function."
            % (macro, listing, bank))
    text = render(sites, bank)
    if check:
        try:
            have = open(out).read()
        except IOError:
            die("%s missing -- run without --check to create it" % out)
        if have != text:
            die("%s is STALE.  Regenerate:\n"
                "  python3 tools/gen_mod_bankpatch.py %s %s --bank %s --macro %s"
                % (out, listing, out, bank, macro))
        return 0
    open(out, "w").write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
