#!/usr/bin/env python3
"""gen_fcc_dp -- toolchain/lib/fcc_runtime.s -> src/kernel/far/fcc_dp.s.

Kernel C needs fcc's direct-page register file and nothing else from the fcc
runtime.  The rest of that file exits through SYS_EXIT, a syscall the kernel
cannot make against itself, so the far bank cannot simply PUT it.

The obvious fix -- split the map into its own file and PUT it from both sides
-- does not work: Merlin32 resolves a PUT against the LINK FILE's directory,
not the containing file's, and the twenty-odd userland link files that pull in
fcc_runtime.s each sit at a different depth.  A nested `PUT fcc_dp.s` inside
fcc_runtime.s was tried and every multi-bank binary failed to assemble.

So the map is EXTRACTED instead, the same way src/kernel/far/kernel_exports.s
and src/kernel/w5100_patchsites.s are: one authored copy, a generated second
copy, and a build edge that keeps them equal.  Two hand-maintained copies of a
DP map would be the worst kind of silent divergence -- a slot that moved on one
side only miscompiles into its neighbour with no diagnostic anywhere.

Usage:  gen_fcc_dp.py <fcc_runtime.s> <out.s>
"""
import os
import re
import sys

EQU = re.compile(r"^(_fcc_[A-Za-z0-9_]+)\s+EQU\s+(\$[0-9A-Fa-f]+)\s*(;.*)?$")

HEADER = """\
;==============================================================================
; fcc_dp.s - fcc's direct-page register file, for KERNEL C.
;
; GENERATED by tools/gen_fcc_dp.py from toolchain/lib/fcc_runtime.s.
; Do NOT hand-edit: the generator is the guard, and a hand-edit here is a slot
; map that disagrees with the compiler emitting against it.
;
; EQUs only -- emits no bytes.  Every offset is relative to whatever page D
; holds.  Kernel C runs with D = FGX_DP_KERNELC (include/kernel.s), a page
; laid out like a TASK direct page: the kernel's OWN direct page has the
; console's persistent state across $C0-$EF, exactly where the promoted-local
; register file below wants to be.
;==============================================================================

"""


def extract(text):
    """Return (lines, names) for every _fcc_* DP EQU, in source order."""
    out, names = [], []
    for ln in text.split("\n"):
        m = EQU.match(ln)
        if not m:
            continue
        name, val = m.group(1), m.group(2)
        # A DP slot is a byte offset within one page.  Anything wider is some
        # other kind of constant and must not be mistaken for one -- silently
        # copying it would put a non-slot into the kernel's map.
        if int(val[1:], 16) > 0xFF:
            continue
        out.append(f"{name:<15} EQU     {val}")
        names.append(name)
    return out, names


def main(argv):
    if len(argv) != 2:
        print(__doc__.rstrip(), file=sys.stderr)
        return 2
    src, out = argv
    lines, names = extract(open(src, errors="replace").read())
    # An extractor that matched nothing would write a valid-looking file and
    # let every _fcc_* symbol in the kernel's C resolve to nothing -- or, since
    # Merlin folds unknown symbols to zero in some contexts, to direct page
    # offset 0.  Refuse instead.
    if len(lines) < 20:
        raise SystemExit(
            f"gen_fcc_dp: found only {len(lines)} DP slots in "
            f"{os.path.basename(src)} -- the EQU format changed and the map "
            f"would ship nearly empty. Fix this parser rather than the file.")
    if len(set(names)) != len(names):
        raise SystemExit(
            "gen_fcc_dp: duplicate slot names in the source map -- refusing to "
            "emit a file where one definition silently wins.")
    # ---- the SAVE BAND ------------------------------------------------------
    # The moment kernel C can sleep, the context switch has to save and restore
    # this register file, because it is SHARED across every task that enters C.
    # That save needs a base and a length, and both must come from here: a
    # hand-written pair in the switch code is a second copy of the slot map,
    # and the failure mode when it disagrees is C state silently corrupted
    # across a sleep -- no diagnostic, and it presents in the victim.
    #
    # The band is the LOWEST slot through the end of the page, not a sum of
    # slot widths.  Widths are not recoverable from EQUs (the offsets alone say
    # nothing about extent -- _fcc_sfp is 3 bytes and _fcc_ptr2 is 4), and
    # inferring them from name prefixes is exactly the guess this file exists
    # to prevent.  Taking everything above the lowest slot is a superset that
    # cannot be short, and on the kernel-C page every byte up there is C's
    # anyway.  A guess at the widths already produced a wrong answer once: 102
    # bytes, because _fcc_ptr2 at $FC was taken for 2 bytes rather than 4.
    nslots = len(lines)
    vals = {l.split()[0]: int(l.split("$")[1], 16) for l in lines}
    lo = min(vals.values())
    band = 0x100 - lo
    lines.append("")
    lines.append(";--- the band the context switch must save once kernel C can sleep ---")
    lines.append(f"KC_DP_LO        EQU     ${lo:02X}")
    lines.append(f"KC_DP_BYTES     EQU     ${band:02X}       ; {band} bytes, "
                 f"${lo:02X}-$FF")

    # ---- the integrity marker ------------------------------------------------
    # The syscall dispatcher stamps the running pid into the band and checks it
    # on the way out, which is how the context save proves itself against real
    # switches.  That marker has to live INSIDE the band -- outside it, it would
    # not be saved and restored and would prove nothing -- while sitting
    # somewhere kernel C itself never writes, or the C it exists to protect
    # would overwrite it and the check would fire on innocent code.
    #
    # $E0-$E7 is that place, and it is not a gap by luck.  The authoritative map
    # in fcc_runtime.s assigns it to args.s (ARGS_DP_WORD/ARGS_DP_SPEC) and to
    # libc's SRC/DST scratch -- both USERLAND ONLY.  Kernel C links no libc and
    # takes no argv, so on the kernel-C page those eight bytes are dead, and the
    # extracted slot map below shows the hole plainly: it runs ... $DC $DE $E8.
    #
    # Asserted rather than assumed, because "fcc has no slot there" is exactly
    # the kind of fact that stops being true silently.
    MARK = 0xE0
    clash = [n for n, v in vals.items() if MARK <= v <= MARK + 7]
    if clash:
        raise SystemExit(
            f"gen_fcc_dp: fcc now allocates {', '.join(sorted(clash))} inside "
            f"${MARK:02X}-${MARK + 7:02X}, which the kernel-C integrity marker "
            f"relies on being free. Pick a new marker offset in a region the "
            f"DP map assigns to userland only, and update this guard.")
    lines.append(f"KC_DP_MARK      EQU     ${MARK:02X}       ; free on the "
                 f"kernel-C page: args.s/libc")

    text = HEADER + "\n".join(lines) + "\n"
    # Write only on change: this file is TRACKED and is an input to the
    # far-bank edge, so an unconditional rewrite would dirty the tree and
    # reassemble the far bank on every build.
    try:
        if open(out).read() == text:
            return 0
    except FileNotFoundError:
        pass
    with open(out, "w") as f:
        f.write(text)
    print(f"gen_fcc_dp: wrote {os.path.basename(out)} ({nslots} DP slots, "
          f"save band ${lo:02X}-$FF)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]) or 0)
