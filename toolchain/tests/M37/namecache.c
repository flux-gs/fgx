/* namecache.c -- UFS 1.6a: the name cache, on real hardware.
 *
 * WHAT MAKES A NAME CACHE DANGEROUS is that every failure mode is silent and
 * only one of them is a crash.  A cache that never hits is CORRECT and slow.
 * A cache that hits when it should not returns the WRONG FILE with no error.
 * A cache whose LRU is wrong evicts the entry it just made.  None of those is
 * visible from userland until data is wrong or the machine merely feels bad,
 * so every claim below is checked against the counters and the chains rather
 * than against "did it return something".
 *
 * THE CENTRAL CLAIM IS STALENESS.  A cached entry names a vnode that can be
 * recycled underneath it -- the file is deleted, the vnode goes back to the
 * pool, and the next getnewvnode hands the same slot to a different file.
 * v_id is what catches it, and case 6 is that exact sequence end to end: cache
 * a name, recycle the vnode through the REAL vnode layer, and require the
 * lookup to miss rather than answer with the new occupant.
 *
 * It composes the REAL vfs_subr.c, because the recycling half of that claim
 * belongs to getnewvnode and vgone.  A fake vnode layer would let the fixture
 * assert whatever it liked about capability numbers.
 *
 * Exit 42 = pass; 99 = the panic stub was reached; every other value is
 * 50 + the case number, so no failure can land on the pass code.
 */

