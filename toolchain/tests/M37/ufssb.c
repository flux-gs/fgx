/* ufssb.c -- the UFS superblock decoder, against a REAL 2.11BSD volume.
 *
 * WHY THIS FIXTURE EXISTS.  UFS 1.10a's probe checks the decoder against
 * disk/ufsscratch.fs, which `fgxfs mkfs` creates at build time.  That is a
 * genuine independent implementation and it catches a great deal -- but it
 * cannot pin the 32-bit ENCODING, and the reason is worth stating: every long
 * on a freshly made volume is small or zero.  volblocks 4096, tfree 4028, and
 * a deliberately zeroed timestamp all have a zero high word, so they cannot
 * distinguish "high word first" from any other arrangement that happens to
 * agree on small numbers.
 *
 * THESE BYTES CAME OFF A PDP-11.  tools/testdata/211bsd/super.bin is the
 * superblock of a live 2.11BSD system (kernel #18), captured from the running
 * machine -- the same volume tools/fgxfs.py's foreign-volume arm reads.  It
 * was written by 2.11BSD itself, by an implementation neither this kernel nor
 * fgxfs has ever seen, which is what makes it evidence rather than agreement.
 *
 * TWO KINDS OF WRONG READING, AND IT TAKES TWO KINDS OF FIELD TO CATCH THEM.
 * This was measured by mutating the decoder, not reasoned about -- an earlier
 * draft of this comment claimed the timestamp was the one field every wrong
 * reading gets wrong, and that is false.
 *
 *   A reading that MOVES THE LOW WORD is caught by volblocks (7942 =
 *   0x00001F06) and tfree (4739 = 0x00001283).  Swapping the halves or reading
 *   a straight little-endian long both put 0x1F06 somewhere it does not belong,
 *   and case 7 fires first.  Measured: both mutations exit 7.
 *
 *   A reading that DISCARDS OR CORRUPTS THE HIGH WORD is invisible to those
 *   two, because their high words are zero -- dropping the high word entirely
 *   leaves 7942 and 4739 both correct.  Only fs_time catches it: 0x6A7937C3 is
 *   stored as the bytes 79 6A C3 37 and is the sole field here with BOTH
 *   halves non-zero and different.  Measured: that mutation exits 9, and only 9.
 *
 * So neither assertion is redundant, and a fresh volume made by `fgxfs mkfs`
 * can supply only the first kind -- its timestamp is deliberately zero.
 *
 * Exit 42 = pass; every other code names the property that failed.
 */

#include "../../../src/kernel/vfs/fsparam.h"
#include "../../../src/kernel/vfs/ufs_fs.h"

/* THE DECODER UNDER TEST, AND NOTHING ELSE.
 *
 * This used to #include ufs_vfsops.c -- a whole translation unit, to exercise
 * one decoder -- and paid for it four times: every function added anywhere in
 * that file became a stub here and a 3,000-line golden regeneration.  bwrite at
 * 1.10b, vrele at 1.8a, then iget and ufs_ihashinit at 1.11a, the last two
 * dragging in the in-core inode table by way of a function this fixture never
 * calls.  bwrite's arrival was the sharpest version: !233 added this fixture
 * and !234 added ufs_sbupdate, both gate-green alone and not together, and
 * nothing either branch could have run would have caught it.
 *
 * ufs_sb.c is the answer that note kept asking for.  It holds decode, encode
 * and validate -- everything that knows the PDP-11 byte order and touches no
 * device, buffer, vnode or mount -- so this fixture needs NO STUBS AT ALL.
 * That is the property to protect: a stub reappearing here means something with
 * an outward call landed on the wrong side of the cut. */
#include "../../../src/kernel/vfs/ufs_sb.c"

