int main()
{
    struct ufs_sb sb;

    ufs_sbdecode(real_sb, &sb);

    /* The 16-bit fields overlay this machine directly, so these check the
     * offsets rather than the byte order. */
    if (sb.sb_isize != 126)              return (1);
    if (sb.sb_nfree != 40)               return (2);
    if (sb.sb_ninode != 92)              return (3);
    if (sb.sb_tinode != 1368)            return (4);
    if (sb.sb_step != 7)                 return (5);
    if (sb.sb_cyl != 400)                return (6);

    /* The 32-bit fields.  volblocks and tfree have zero high words -- true of
     * this volume as well as of a fresh one -- so they check the offset and
     * the low half only. */
    if (sb.sb_volblocks != 7942L)         return (7);
    if (sb.sb_tfree != 4739L)             return (8);

    /* AND THE ONE THAT PINS THE ENCODING.  See the head of this file: both
     * halves non-zero and different, so no wrong reading survives it. */
    if (sb.sb_time != 1786329027L)        return (9);

    /* A REAL VOLUME MUST VALIDATE.  The rejection arms are exercised by the
     * on-machine probe against values it corrupts itself; what this adds is
     * the other direction -- that a filesystem 2.11BSD wrote and uses is not
     * refused by our idea of consistency.  A validator that rejects real
     * volumes is worse than one that accepts bad ones: it cannot be noticed
     * until someone tries to mount their disk. */
    if (!ufs_sbvalid(&sb, (daddr_t)0))          return (10);
    if (!ufs_sbvalid(&sb, (daddr_t)7942))       return (11);
    if (ufs_sbvalid(&sb, (daddr_t)100))         return (12);

    return (42);
}
