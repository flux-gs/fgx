#!/usr/bin/env python3
"""gen_commons.py -- K&R A.10.2 tentative-definition coalescing (link pass).

K&R "The C Programming Language" A.10.2 (p.187): the tentative definitions of an
externally-linked object across ALL translation units are considered together --
"if a definition occurs somewhere in the program, then the tentative definitions
become merely declarations, but if no definition appears, then all its tentative
definitions become a definition with initializer 0."  This is the UNIX common
extension the Standard recognizes, and the behaviour 2.11BSD's `ld` gives K&R
sources that declare file-scope globals in a shared header WITHOUT `extern`
(the Bourne shell's defs.h: `jmp_buf INTbuf;`, `INT exitval;`, ...).

fcc emits each such tentative def to a per-TU `<tu>.comm` sidecar (`--commons`),
one record per line:
    TENT <name> <size> <reloc>   -- a tentative def redirected out of .data.s
    DEF  <name>                  -- a real (initialized) def kept in <tu>.data.s
This pass reads every sidecar and emits ONE `commons.data.s`: a name with any
DEF is dropped (its real def in some .data.s wins); every other name gets a
single `<name> DS <maxsize>` (zero-initialized, largest tentative size), with
FGX2_EXPORT when any TU took its address in a pointer initializer, and a
closing FGX2_RELOC_COUNT declaring those rows (macros.s).

A library-provided global (the C source declares `int errno;` K&R-style, but
libc really defines it) is likewise a real definition the tentatives yield to.
Pass the library data sources with `--extern-defs <file>`: their column-0 labels
are added to the defined set, so a matching tentative is dropped rather than
re-defined (which would collide with the library's own label).

Usage:  gen_commons.py [--extern-defs <lib.s>]... <out.data.s> <tu.comm>...
"""
import re
import sys

_LABEL = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)\s")


def main(argv):
    args = argv[1:]
    extern_defs = []
    rest = []
    i = 0
    while i < len(args):
        if args[i] == "--extern-defs":
            if i + 1 >= len(args):
                sys.exit("gen_commons: --extern-defs needs a file")
            extern_defs.append(args[i + 1]); i += 2
        else:
            rest.append(args[i]); i += 1
    if len(rest) < 2:
        sys.exit("usage: gen_commons.py [--extern-defs <lib.s>]... "
                 "<out.data.s> <tu.comm>...")
    out_path = rest[0]
    comm_files = rest[1:]

    defined = set()                       # names with a real (initialized) def
    # Library-defined labels (errno, ...) are real defs the tentatives yield to.
    for lib in extern_defs:
        with open(lib) as f:
            for line in f:
                m = _LABEL.match(line)
                if m:
                    defined.add(m.group(1))
    tent = {}                             # name -> [max_size, any_reloc]
    for cf in comm_files:
        with open(cf) as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith("#"):
                    continue
                parts = line.split()
                if parts[0] == "DEF" and len(parts) == 2:
                    defined.add(parts[1])
                elif parts[0] == "TENT" and len(parts) == 4:
                    name, size, reloc = parts[1], int(parts[2]), int(parts[3])
                    if name in tent:
                        tent[name][0] = max(tent[name][0], size)
                        tent[name][1] = tent[name][1] or bool(reloc)
                    else:
                        tent[name] = [size, bool(reloc)]
                else:
                    sys.exit("gen_commons: malformed record %r in %s" % (line, cf))

    # A real definition anywhere wins: those tentatives become mere declarations.
    names = sorted(n for n in tent if n not in defined)

    with open(out_path, "w") as o:
        o.write("*------------------------------------------------------------\n")
        o.write("*  commons.data.s -- coalesced K&R tentative definitions.\n")
        o.write("*  GENERATED by gen_commons.py (do not edit).  K&R A.10.2 p.187:\n")
        o.write("*  one zero-initialized definition per externally-linked object\n")
        o.write("*  whose only defs across all TUs are tentative.\n")
        o.write("*------------------------------------------------------------\n")
        rows = 0
        for n in names:
            size, reloc = tent[n]
            if reloc:
                o.write("                FGX2_EXPORT %s\n" % n)
                rows += 1
            o.write("%-15s DS      %d\n" % (n, size))
        # fgx_ld's count gate, as fcc ends every generated .s: a link that
        # folds this file into another source sums the declarations.
        o.write("                FGX2_RELOC_COUNT %d\n" % rows)

    dropped = sorted(n for n in tent if n in defined)
    print("gen_commons: %d coalesced, %d dropped (real def wins)%s"
          % (len(names), len(dropped),
             (": " + " ".join(dropped)) if dropped else ""))


if __name__ == "__main__":
    main(sys.argv)
