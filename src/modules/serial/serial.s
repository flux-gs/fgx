                PUT     kernel_exports.s

;------------------------------------------------------------------------------
; FGXM header v2 (40 bytes).
;------------------------------------------------------------------------------
; BSS bytes the loader zero-fills after the text.  ONE symbol, used by
; the header field below AND by the placement ceiling guard at the tail,
; so a module that grows real bss cannot outgrow the bank with a guard
; that measured only its text.
serial_bss         EQU     0

serial_hdr      ASC     'FGXM'                          ; +0  magic
                DFB     <MODP_ORG                        ; +4  load lo
                DFB     >MODP_ORG                        ; +5  load mid
                DFB     ^MODP_ORG                        ; +6  load hi
                DFB     $02                             ; +7  header format version (v2)
                DA      mod_init-$050000                ; +8  entry offset
                DA      serial_end-serial_text          ; +10 text bytes
                DA      serial_bss                         ; +12 bss bytes
                DA      serial_vtdir-serial_text        ; +14 vtdir offset
                ; --- v2 header additions ---
serial_modname  ASC     'serial'                        ; +16 module name
                DS      16-*+serial_modname             ;     NUL-pad to 16 bytes
                DA      $0000                           ; +32 module version (reserved)
                ; +34 kernel build identity (KERN_BUILD_ID comes from the
                ; generated kernel_exports.s).  Mod_Load refuses this module if
                ; the running kernel published a different one -- every kernel
                ; address baked below would point at the wrong byte.
                DA      KERN_BUILD_ID
                DS      4                               ; +36 reserved (deps/flags)

serial_text     EQU     *

;------------------------------------------------------------------------------
; VTDR sentinel + VT_END terminator (no vtables yet; slice 5 adds VT_CHARDEV).
;------------------------------------------------------------------------------
serial_vtdir    ASC     'VTDR'
                DA      $0000                           ; VT_END

;------------------------------------------------------------------------------
; mod_init - MX %00 entry; PHK/PLB sets DBR = our bank.
;
; Slice 3 sequence:
;   1. Program SCC channel B for 9600-8N1, TX+RX enabled, IRQ disabled.
;   2. Emit a polled TX hello banner so a connected dumb terminal sees
;      proof of life.
;   3. Log a one-liner via SYS_KERNLOG so SHR console shows the load.
;
; Slice 4+ adds: SetVector(VRN $0009) ISR install, master IRQ enable,
; ring-buffered RX, and (slice 5) chardev registration as /dev/tty01.
;------------------------------------------------------------------------------
mod_init        MX      %00
                PHK
                PLB                                     ; DBR = our bank

                ; Self-patch ops table bank bytes per prodos.mod's @spL.
                ; CRITICAL: SEP #$30 (not #$20) — must set BOTH M and X to
                ; 8-bit since the LDX #2 below assembles per the MX %11
                ; directive.  An earlier SEP #$20 left X 16-bit at runtime
                ; while the assembler thought X=8, misaligning the
                ; instruction stream — same bug class as
                ; feedback_merlin_imm_in_m8_mode but on the X flag.
                SEP     #$30
                MX      %11
                PHK
                PLA                                     ; A = our bank
                LDX     #2
@mi_spL         STA:    serial_ops,X
                INX
                INX
                INX
                CPX     #18                             ; 6 slots × 3 B
                BCC     @mi_spL
                REP     #$30
                MX      %00

                ; --- Init success counter (module-local; success = >=1 up) ---
                STZ:    _serRegCount

                ; ===== Channel A (printer port / slot 1) -> /dev/tty00 =====
                ; Per-channel INSTALL-FIRST: the SIM install is the AppleTalk
                ; arbitration gate (returns C=0,A=ESIM_ATALK if AppleTalk owns
                ; the port), so we touch the SCC + register the tty only on
                ; success — never reprogram a channel AppleTalk owns.
                ;
                ; Install ABI (src/kernel/sim.s _Sys_SimInstallImpl): A.lo=mask,
                ; X=handler offset, Y.lo=our bank.  CRITICAL: load mask/handler
                ; AFTER the PHK/PLA/TAY dance (PLA clobbers A.lo with the bank).
                PHK
                SEP     #$20
                MX      %10
                PLA                             ; A.lo = our bank
                TAY                             ; Y.lo = our bank
                REP     #$20
                MX      %00
                LDA     #$0038                  ; mask = chan A
                LDX     #serial_isr_A
                JSL     SYS_SIM_INSTALL
                BCS     @mi_A_simOK
                CMP     #ESIM_ATALK
                BNE     @mi_A_simErr
                ; DETECTED, NOT ATTACHED -- and that is worth a line.  The
                ; channel is real and the port is there; AppleTalk owns it, so
                ; the driver leaves it alone.  Saying nothing made the machine
                ; look like it had one SCC channel instead of two.
                LDX     #atalk_A_msg
                JSL     SYS_MODLOG
                BRL     @mi_chanB
@mi_A_simErr    LDX     #simfail_A_msg
                JSL     SYS_MODLOG
                BRL     @mi_chanB
                ; `SIM chan A handler installed' was the driver reporting
                ; its own progress, the way chan B's was.  What the machine
                ; detected is the port, and the banner below says it.
@mi_A_simOK     LDA     #$06                    ; chan A baud param ref (port 1)
                JSR     _serCfgRead             ; read CP cfg -> _cc* + patch banner
                JSR     scc_program_chanA
                JSR     scc_enable_chanA_irqs
                LDA     #tty00_name
                LDX     #serial_ops
                LDY     #{{CDF_FIXED+{DEVNODE_TTY00*4}}*256}+0 ; minor 0 (chan A),
                                                ;   at /dev/tty00's number
                JSL     MOD_REGISTERCHARDEV
                BCS     @mi_A_regOK
                LDX     #regfail_A_msg
                JSL     SYS_MODLOG
                BRL     @mi_chanB
@mi_A_regOK     INC:    _serRegCount
                ; `/dev/tty00 registered' said on its own line what the
                ; banner says at the end of its own -- `(attaching tty00)'.
                LDX     #banner_A_tmpl
                JSL     SYS_MODLOG

@mi_chanB       MX      %00
                ; ===== Channel B (modem port / slot 2) -> /dev/tty01 =====
                PHK
                SEP     #$20
                MX      %10
                PLA                             ; A.lo = our bank
                TAY                             ; Y.lo = our bank
                REP     #$20
                MX      %00
                LDA     #$0007                  ; mask = chan B
                LDX     #serial_isr
                JSL     SYS_SIM_INSTALL
                BCS     @mi_B_simOK
                CMP     #ESIM_ATALK
                BNE     @mi_B_simErr
                LDX     #atalk_B_msg            ; see the chan A note above
                JSL     SYS_MODLOG
                BRL     @mi_done
@mi_B_simErr    LDX     #regfail_sim_msg
                JSL     SYS_MODLOG
                BRL     @mi_done
                ; `SIM chan B handler installed' was the driver reporting its
                ; own progress.  What the machine detected is the LINE, and
                ; that is the banner a few instructions down.
@mi_B_simOK     LDA     #$12                    ; chan B baud param ref (port 2)
                JSR     _serCfgRead             ; read CP cfg -> _cc* + patch banner
                JSR     scc_program_chanB
                JSR     scc_enable_chanB_irqs
                ; NOTE: no boot-time TX banner — the port stays quiet so an
                ; attached modem/tcpser doesn't parse junk.  TX verified via cu.
                LDA     #serial_name
                LDX     #serial_ops
                LDY     #{{CDF_FIXED+{DEVNODE_TTY01*4}}*256}+1 ; minor 1 (chan B),
                                                ;   at /dev/tty01's number
                JSL     MOD_REGISTERCHARDEV
                BCS     @mi_B_regOK
                LDX     #regfail_msg
                JSL     SYS_MODLOG
                BRL     @mi_done
@mi_B_regOK     ; A = the chardev index MOD_REGISTERCHARDEV just handed back.
                ; SAY WHICH TTY THIS LINE IS, or nothing ever will: `tty_devinit'
                ; asks the REGISTRY which tty a device is and records nothing of
                ; its own, so a device the registry does not call a tty gets no
                ; `struct tty' and `tty_byidx' answers NULL for it forever --
                ; which is why `serial_isr' had no index to hand `kc_ttyinput'.
                ; Every other tty line is registered BY THE KERNEL, which sets
                ; this beside the registration (chardev.s:1197-1249); this line
                ; registers itself, so it has to say it itself.  apple/fgx#108 T7.
                PHA
                INC:    _serRegCount
                PLA
                LDY     #SER_TTYIDX_B
                LDX     #KSVC_CDSETTTYIDX
                JSL     SYS_KCALL               ; C=1 + A = the line's byte
                BCC     @mi_B_ttyBad            ;   offset; C=0 + A = EINVAL
                STA     _serTtyOffB             ; OUR bank: mod_init runs under
                                                ;   its own PHK/PLB
                ; THE LINE IS SEEDED BY `tty_devinit', not here -- apple/fgx#247.
                ; `ttychars(tp)' and `t_flags' are upstream's `dzopen' pair
                ; (dz.c:130-140), and they run at BIND time for the reason
                ; `t_oproc' and carrier do: FGX has no getty, so a line not
                ; seeded there is never seeded at all.  Two placements closer to
                ; upstream were tried first and both were reverted -- from this
                ; module's init it broke the boot, and from `serial_open' it
                ; HUNG on every open, because a chardev op runs inside
                ; `_Chardev_Dispatch's shared self-modified trampoline.
                BRA     @mi_B_ttyOK
@mi_B_ttyBad
                LDX     #regfail_ttyidx_msg     ; NOT fatal to the load: the line
                JSL     SYS_MODLOG              ;   still carries bytes raw, and a
                                                ;   silent unbound tty is the
                                                ;   failure that hides
@mi_B_ttyOK     ; `/dev/tty01 registered' said on its own line what the
                ; banner now says at the end of its own: `(attaching tty01)'.
                LDX     #banner_B_tmpl
                JSL     SYS_MODLOG

@mi_done        MX      %00
                ; --- success iff >=1 channel registered (an AppleTalk-owned
                ;     channel is a normal skip, not a module-load failure) ---
                LDA     _serRegCount
                BNE     @mi_ok
                CLC                             ; both failed (non-AppleTalk)
                RTL
@mi_ok          SEC                             ; >=1 channel up -> success
                RTL

;------------------------------------------------------------------------------
; serial_stop - d_stop(dev, rw).  Y = minor, X = rw.  Always C=1.
;
; THE ONE FGX CHARACTER DEVICE WITH OUTPUT ACTUALLY IN FLIGHT.  Every other
; one gets a zero slot, which is what 2.11BSD's own cdevsw does for its console
; (pdp/conf.c, `cn = 0' has nulldev here); only the dz/dh/dhu multiplexers
; carry a body, and this ring is FGX's equivalent of their silo.
;
; DROPPING THE PENDING RING IS EXACTLY WHAT UPSTREAM DOES.  dzstop (pdpuba/dz.c)
; is:
;       if (tp->t_state & TS_BUSY) {
;               dp->p_end = dp->p_mem;
;               if ((tp->t_state & TS_TTSTOP)==0)
;                       tp->t_state |= TS_FLUSH;
;       }
; -- `p_end = p_mem' truncates the block the driver is feeding out, discarding
; what has not gone yet.  Tail = head is the same act on a ring.  What is
; already in the SCC shift register still goes, exactly as the byte in flight
; on a DMA still goes.
;
; THE TS_FLUSH HALF IS NOT CARRIED, and it is FGX's ABI rather than a choice: a
; chardev op receives a MINOR, not a `struct tty *', so it cannot set tty state.
; Nothing is lost -- TS_FLUSH exists to tell the driver's completion interrupt
; that the data was discarded rather than sent, and serial_isr does not consult
; tty state at all: it re-reads the ring, finds tail == head, and takes its own
; @isr_tx_idle path.  Emptying the ring IS the message.
;
; SEI-BRACKETED for the reason serial_write's own critical section is: the
; handler dequeues from the same two cells, and a stop that raced a TxIP could
; leave tail past head and hand the ISR a 64K ring to drain.
;------------------------------------------------------------------------------
serial_stop     MX %00
                ; THE MINOR IS CHECKED, and it was not before.  Both channels
                ; register the SAME `serial_ops' (minor 0 = chan A, 1 = chan B)
                ; and every other op in this table opens by testing Y -- this
                ; one dropped CHAN B's ring whatever line it was called for.
                ; Latent rather than live: chan A has no `struct tty', so
                ; `_Chardev_TtyOff' calls it not-a-tty and no discipline path
                ; dispatches d_stop to it, and every d_stop caller is
                ; discipline driven.  Two instructions now; finding it the day
                ; chan A gets a line would cost rather more.
                CPY     #1
                BNE     @ss_notB
                INC     _sccStopsB              ; the witness apple/fgx#240 never
                                                ;   had -- see include/memmap.s
                PHP
                SEI
                LDX     _sccTxHead
                STX     _sccTxTail              ; drop the pending ring
                PLP
@ss_notB        SEC
                RTL

;------------------------------------------------------------------------------
; serial_ops - CharDev_Ops vtable for /dev/tty01.  Order MUST match
; COPS_* offsets in include/chardev.s.
;
; Dispatch ABI from _Chardev_Dispatch:
;   - DBR is whatever the kernel had (kernel-bank — not our bank).
;   - A = arg byte (zero-extended; meaningful for COPS_Write).
;   - Y = minor byte (zero-extended; we passed 1 at register time).
;
; All ops here use STAL/LDAL for SCC access (24-bit absolute, DBR-
; independent), so no PHB/PHK/PLB needed unless we touch module-bank
; data.
;------------------------------------------------------------------------------
serial_ops      DFB     <serial_open,>serial_open,^serial_open
                DFB     <serial_close,>serial_close,^serial_close
                DFB     <serial_read,>serial_read,^serial_read
                DFB     <serial_write,>serial_write,^serial_write
                DFB     <serial_ioctl,>serial_ioctl,^serial_ioctl
                DFB     <serial_poll,>serial_poll,^serial_poll
                DFB     <_Ser_DRead,>_Ser_DRead,^_Ser_DRead      ; d_read:  the discipline
                DFB     <_Ser_DWrite,>_Ser_DWrite,^_Ser_DWrite   ; d_write: the discipline
                DFB     <serial_stop,>serial_stop,^serial_stop   ; d_stop:  a real TX ring

serial_name     ASC     'tty01',00

;------------------------------------------------------------------------------
; _Ser_DRead / _Ser_DWrite - cdevsw's `d_read'/`d_write' for /dev/tty01.
;
; apple/fgx#108 T7 step 3.  These slots were `0,0,0' DELIBERATELY until now: a
; cdevsw slot on a line whose bytes never met `ttyinput' would point at nothing.
; Step 2 gave the line a discipline, so they point at it.
;
; UPSTREAM'S ARE ONE LINE EACH, and this is the same one `ptsread'/`ptswrite'
; are (tty_pty.c:136, :156) -- the driver hands the whole job to the line:
;
;     dzread(dev, uio, flag)  { ... return ((*linesw[tp->t_line].l_read)(tp, uio, flag)); }
;         -- vendor/2.11BSD/usr/sys/pdpuba/dz.c, dzread/dzwrite
;
; CHAN A GETS NEITHER.  It is AppleTalk's, it has no `struct tty' and no tty
; index, so a bulk op on minor 0 must refuse rather than move bytes against
; line 5.  ENXIO is what an unclaimed minor answers elsewhere in this file.
;------------------------------------------------------------------------------
_Ser_DRead      MX      %00
                CPY     #1                      ; minor 1 = chan B; only chan B
                BNE     @sd_nodev               ;   is a tty line
                LDY     #UIO_READ
                JSR     @sd_args
                BCC     @sd_err
                LDX     #KSVC_TTYREAD
                JSL     SYS_KCALL               ; A = errno, 0 = success
                BRA     @sd_done

_Ser_DWrite     MX      %00
                CPY     #1
                BNE     @sd_nodev
                LDY     #UIO_WRITE
                JSR     @sd_args
                BCC     @sd_err
                LDX     #KSVC_TTYWRITE
                JSL     SYS_KCALL
@sd_done        CMP     #0                      ; an errno either side of the
                BNE     @sd_err                 ;   KSVC; a chardev op answers
                SEC                             ;   in the CARRY
                RTL
@sd_nodev       LDA     #ENXIO
@sd_err         CLC
                RTL

;------------------------------------------------------------------------------
; @sd_args - the two ops' shared argument build, pty.mod's `@sd_args' exactly.
;
; In:  Y = the uio_rw this op is (UIO_READ / UIO_WRITE).
; Out: C=1, A = the uio's offset, Y = (uio bank << 8) | ndelay<<7 | tty index.
;      C=0 + A = EINVAL if the frame does not read as a uio in that direction.
;
; THE OFFSETS ARE COUNTED, NOT ASSUMED.  The op reads 9/11/13,S; this is JSR'd
; from it (+2) and pushes one word (+2), so it reads 13/15/17,S and drops back
; to 11,S for the last one.  include/chardev.s says the frame reaches an op
; through THREE call instructions, not one.
;
; AND THE FRAME IS ASSERTED.  A `d_read' is handed a READ uio by definition, so
; `uio_rw' names the frame -- get the offsets wrong and the pointer handed
; across the KSVC is wild, and `ttread' would move bytes into a stranger's bank.
; The WEAK form of this proves nothing: pty's header records a trial arm given
; the offset deliberately wrong by two that stayed GREEN, because the wild read
; returned zero and zero is UIO_READ.  Y carrying the direction discriminates.
;------------------------------------------------------------------------------
@sd_args        PHY                             ; the expected uio_rw
                LDA     13,S                    ; the uio's offset
                STA     _libcTmp2
                SEP     #$20
                MX      %10
                LDA     15,S                    ; the uio's bank.  8-BIT: the
                STA     _libcTmp2+2             ;   cell is THREE bytes wide
                REP     #$30
                MX      %00
                LDY     #UIO_RW
                LDA     [_libcTmp2],Y
                CMP     1,S
                BEQ     @sda_ok
                PLY
                LDA     #EINVAL
                CLC
                RTS
@sda_ok         LDA     #SER_TTYIDX_B
                AND     #$007F
                STA     1,S                     ; reuse the pushed word
                LDA     17,S                    ; the op's `flag'
                AND     #VFS_IO_NDELAY
                BEQ     @sda_pack
                LDA     1,S
                ORA     #$0080
                STA     1,S
@sda_pack       LDA     15,S                    ; the uio's bank again
                AND     #$00FF
                XBA                             ; -> Y's high byte
                ORA     1,S
                TAY
                PLA                             ; drop the staged word
                LDA     11,S                    ; the uio's offset
                SEC
                RTS

;------------------------------------------------------------------------------
; serial_open - open() on /dev/tty01.  No per-fd state needed for v1
; (the SCC is already programmed; we don't track open count).
;------------------------------------------------------------------------------
serial_open     MX %00
                CPY     #1                      ; minor 1 = chan B only; chan A
                BNE     @so_done                ;   is AppleTalk's and has no line
                INC     _sccOpenB               ; apple/fgx#108 T7: dzrint's
@so_done        SEC                             ;   TS_ISOPEN test, asked of the
                RTL                             ;   state FGX actually keeps

;------------------------------------------------------------------------------
; serial_close - close() on /dev/tty01.  Nothing to release.
;------------------------------------------------------------------------------
serial_close    MX %00
                CPY     #1
                BNE     @sc_done
                LDA     _sccOpenB               ; NEVER BELOW ZERO.  A close the
                BEQ     @sc_done                ;   open never counted would
                DEC     _sccOpenB               ;   otherwise wrap to $FFFF and
@sc_done        SEC                             ;   leave the line permanently
                RTL                             ;   "open" to the interrupt

;------------------------------------------------------------------------------
; serial_read - one-byte non-blocking read from chan B.
;
; If RR0 bit 0 (RX char available) is set, pull byte from $E0C03A and
; return A=byte+C=1.  Otherwise return A=EAGAIN+C=0 (kernel-side
; _Sys_Read CHARDEV branch treats nonzero+C=0 as errno passthrough; the
; userland caller sees EAGAIN and can retry).
;------------------------------------------------------------------------------
serial_read     MX %00
                CPY     #0                      ; minor 0 = chan A, 1 = chan B
                BNE     @sr_chanB
                BRL     serial_read_A
@sr_chanB
                ; --- RETIRED (apple/fgx#108 T7 step 3).  This popped
                ; `_sccRxBuf', which no longer exists for chan B: the receive
                ; interrupt hands each byte to `ttyinput' at arrival, and a read
                ; comes back through `ttread' -- `_Ser_DRead' on the /dev road,
                ; and `_Sys_Read's own detour on the chardev-FCB one, which routes any
                ; line the REGISTRY calls a tty into the discipline.  There is
                ; one input queue on this line now, `t_rawq', and it is BSD's.
                ;
                ; THE ARM STAYS AND IS LOUD, which is this tree's habit for a
                ; retired path -- `_PtyS_Read' says the same thing one module
                ; over.  COPS_Getc has no absent-slot test, so zeroing the slot
                ; would be worse than useless: a caller that somehow reaches it
                ; must get an error it can see, not a dispatch into a zero.
                ;
                ; NOTHING SHOULD REACH IT.  If this errno ever appears, a read
                ; road was found that the two above do not cover -- which is a
                ; defect in the routing and not in this stub.
                LDA     #EIO
                CLC
                RTL

