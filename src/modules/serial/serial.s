; serial_read_A - chan A (tty00) read.  KEEP IN SYNC with serial_read's
; chan-B body (mirror: _sccRx* -> _sccRx*A).
;------------------------------------------------------------------------------
serial_read_A   MX %00
                PHP
                SEI
                SEP     #$30
                MX      %11
                LDX     _sccRxTailA
                CPX     _sccRxHeadA
                BEQ     @sra_empty
                LDA     _sccRxBufA,X
                INX
                STX     _sccRxTailA
                REP     #$30
                MX      %00
                AND     #$00FF
                PLP
                SEC
                RTL
@sra_empty      REP     #$30
                MX      %00
                PLP
                LDA     #EAGAIN
                CLC
                RTL

;------------------------------------------------------------------------------
; serial_write - IRQ-driven TX.  Push A.lo into _sccTxBuf ring; if TX idle,
; prime the SCC by writing the byte directly to data reg (the TxIP that
; fires when hold→shift completes runs serial_isr's dequeue path for
; subsequent bytes).
;
; CRITICAL: in the prime path, load the byte AFTER the "mark in-progress"
; flag store — otherwise A is $01 (the flag value) when we STAL SCC_B_DATA.
;
; SEI-bracketed for full atomicity: the prime-or-not decision must not
; race with handler-side TX dequeue.
;------------------------------------------------------------------------------
serial_write    MX %00
                CPY     #0                      ; minor 0 = chan A, 1 = chan B (A = byte, preserved)
                BNE     @sw_chanB
                BRL     serial_write_A
@sw_chanB       PHP
                SEP     #$30
                MX      %11
                ; --- Ring-full?  Block until handler drains a byte.
                ; Caller's write() expects blocking-write semantics.
                ; Returning EAGAIN would let the per-byte write loop
                ; bail, silently dropping the remainder of
                ; the user's buffer — observed as fragmented/corrupted
                ; output when cat'ing files larger than the 256-byte
                ; ring.  Spin-wait with IRQs enabled so the handler can
                ; dequeue.  Each iteration: PHP/SEI, re-check, PLP if
                ; still full (so handler can fire).
@sw_waitDrain   PHP
                SEI
                LDX     _sccTxHead
                INX
                CPX     _sccTxTail
                BNE     @sw_haveSpace
                ; Still full — let handler fire and re-check.
                PLP
                BRA     @sw_waitDrain
@sw_haveSpace   PLP                             ; drop inner PHP
                SEI                             ; mask for the critical section
                LDX     _sccTxHead
                INX
                DEX                             ; X = head
                STA     _sccTxBuf,X
                INX
                STX     _sccTxHead
                ; Already pumping? Then the in-flight TxIP picks our
                ; byte up later — nothing more to do.
                LDA     _sccTxInProgress
                BNE     @sw_done
                ; Prime: mark in-progress, then dequeue our just-pushed
                ; byte from the ring and write to SCC data reg.
                LDA     #1
                STA     _sccTxInProgress
                LDX     _sccTxTail
                LDA     _sccTxBuf,X
                INX
                STX     _sccTxTail
                STAL    SCC_B_DATA
@sw_done        REP     #$30
                MX      %00
                PLP                             ; restore caller's I
                SEC
                RTL

