                INX
                DEX                             ; X = head
                STA     _sccTxBufA,X
                INX
                STX     _sccTxHeadA
                LDA     _sccTxInProgressA
                BNE     @swa_done
                LDA     #1
                STA     _sccTxInProgressA
                LDX     _sccTxTailA
                LDA     _sccTxBufA,X
                INX
                STX     _sccTxTailA
                STAL    SCC_A_DATA
@swa_done       REP     #$30
                MX      %00
