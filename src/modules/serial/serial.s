; SCC chan B addresses (modem port; slot 2).  Bank $E0 always: bank $00
; I/O is RAMWRT-shadowed.
SCC_B_CMD       EQU     $E0C038
SCC_B_DATA      EQU     $E0C03A

; SCC chan A addresses (printer port; slot 1).  RR3 (both-channels IRQ
; status) is always read via chan A's command port.
SCC_A_CMD       EQU     $E0C039
SCC_A_DATA      EQU     $E0C03B

; RR0 status bits.
RR0_RX_AVAIL    EQU     $01                 ; bit 0: Rx character available
RR0_TX_EMPTY    EQU     $04                 ; bit 2: Tx buffer empty

; RR3 bits (read via chan A only — RR3 in chan B is always 0).
RR3_B_RX        EQU     $04                 ; bit 2: chan B Rx pending
RR3_B_TX        EQU     $02                 ; bit 1: chan B Tx pending
RR3_A_RX        EQU     $20                 ; bit 5: chan A Rx pending
RR3_A_TX        EQU     $10                 ; bit 4: chan A Tx pending


; The tty line this driver IS.  tty[5], APPENDED -- include/kernel.s:1166 lists
; the map and says why appending is the only safe direction.  Chan A gets none:
; it is AppleTalk's and never fires.
SER_TTYIDX_B            EQU     5

