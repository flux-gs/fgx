;==============================================================================
; serial.s - FGX serial driver: the IIgs SCC, both channels.
;
; Channel A (printer port) is /dev/tty00 and channel B (modem port) is
; /dev/tty01, each 9600-8N1, interrupt-driven through the SIM (SYS_SIM_INSTALL)
; with ring-buffered receive and transmit.  A channel AppleTalk owns is left
; alone.
;
; Hardware mapping (IIgs Hardware Reference + Tech Note #18):
;   Modem port  (slot 2)  = SCC channel B  cmd $E0C038  data $E0C03A
;   Printer port (slot 1) = SCC channel A  cmd $E0C039  data $E0C03B
;
; SCC programming sequence per Apple IIgs Tech Note #18
; ("Do-It-Yourself SCC Access"); deliberately omits the WR9=$C0 force
; hardware reset (the Note warns against it and ROM already did one at
; system startup).  All two-step register accesses are wrapped in
; PHP/SEI/PLP per Hint #2.
;
; Bank-agnostic, OFFSET-SPECIFIC.  The BANK is still whatever the loader
; puts this module in -- every absolute reference is DBR-relative once
; mod_init runs PHK/PLB.  The OFFSET WITHIN that bank is NOT free: modules
; now SHARE one bank, so this image is ORG'd at MODP_ORG (generated by
; tools/gen_modplace.py from the measured sizes of the modules placed before
; it) and MUST be loaded there.  The FGXM header's load_addr carries that
; offset to Mod_Load.
; The loader patches the JT call's PC bank.
;==============================================================================

                MX      %11
                ; WHERE THIS MODULE LIVES.  Modules stack into ONE shared
                ; bank -- a 64 KB bank per 2 KB driver was costing four
                ; banks for 17 KB of code.  MODP_ORG is this module's
                ; offset in that bank, derived at build time from the
                ; MEASURED sizes of the modules placed before it; the
                ; loader reads it back out of the FGXM header below.
                ; Module code is ORG-dependent, so this must be exact.
                PUT     modplace.s
                ORG     MODP_ORG

