; here "so the module is self-contained" -- and a copied SLOT OFFSET that drifts
; does not fail to assemble, it dispatches the wrong op.

; Kernel-bank statics touched by serial_isr ($02 = assembly ORG only; the
; kernel bank is MM-assigned at runtime).  serial_isr runs with
; DBR=kernel-bank (set by SIM dispatcher's PHK/PLB), so these are accessed as
