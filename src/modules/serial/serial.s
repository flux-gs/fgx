                RTS

;------------------------------------------------------------------------------
; scc_program_chanA — program SCC chan A (printer port / slot 1) for 9600-8N1,
; RX+TX enabled, interrupts off.  KEEP IN SYNC with scc_program_chanB (verbatim
; mirror: SCC_B_CMD -> SCC_A_CMD).  gno sccf.asm programs both SCC channels with
; one identical register table, so the chan-B Tech-Note-#18 sequence + TC=$0A
; baud constant apply unchanged to chan A.
;------------------------------------------------------------------------------
; Programs baud (WR12/WR13) + framing (WR3/WR4/WR5) from the control-panel
; values decoded by _serCfgRead into _ccTC/_ccWR3/_ccWR4/_ccWR5.  Clock routing
; (WR11/WR14) is fixed: chan A HOSTS the 3.6864 MHz crystal, so WR11=$D0 (bit7
; enables the oscillator that feeds both channels' BRG — gno pr.equates Reg11).
scc_program_chanA MX %00
                PHP
                SEP     #$30                            ; M=8 X=8 for byte bashing
                MX      %11
                SEI                                     ; block chan B IRQ races

                LDAL    SCC_A_CMD                       ; sync state machine to reg 0

                ; WR4 = parity + stop bits + x16 clock (from control panel)
                LDA     #$04
                STAL    SCC_A_CMD
                LDA     _ccWR4
                STAL    SCC_A_CMD

                ; WR3 = data bits, RX DISABLED during baud config
                LDA     #$03
                STAL    SCC_A_CMD
                LDA     _ccWR3
                AND     #$FE                            ; clear RX-enable bit
                STAL    SCC_A_CMD

                ; WR5 = data bits, TX DISABLED during baud config
                LDA     #$05
                STAL    SCC_A_CMD
                LDA     _ccWR5
                AND     #$F7                            ; clear TX-enable bit
                STAL    SCC_A_CMD

                ; WR11 = $D0  (XTAL osc ON; rx/tx clk = BRG out) — see header
                LDA     #$0B
                STAL    SCC_A_CMD
                LDA     #$D0
                STAL    SCC_A_CMD

                ; WR12/WR13 = BRG time constant (baud, from control panel)
                LDA     #$0C
                STAL    SCC_A_CMD
                LDA     _ccTC                           ; TC lo
                STAL    SCC_A_CMD
                LDA     #$0D
                STAL    SCC_A_CMD
                LDA     _ccTC+1                         ; TC hi
                STAL    SCC_A_CMD

                ; WR14 = $00 (BRG src = /RTxC, off) then $01 (enable BRG)
                LDA     #$0E
                STAL    SCC_A_CMD
                LDA     #$00
                STAL    SCC_A_CMD
                LDA     #$0E
                STAL    SCC_A_CMD
                LDA     #$01
                STAL    SCC_A_CMD

                ; WR3 = data bits, RX ENABLED
                LDA     #$03
                STAL    SCC_A_CMD
                LDA     _ccWR3
                STAL    SCC_A_CMD

                ; WR5 = data bits, TX ENABLED
                LDA     #$05
                STAL    SCC_A_CMD
                LDA     _ccWR5
                STAL    SCC_A_CMD

                ; WR15 = $00  (no external/status interrupts)
                LDA     #$0F
                STAL    SCC_A_CMD
                LDA     #$00
                STAL    SCC_A_CMD

                PLP
                RTS

;------------------------------------------------------------------------------
; scc_enable_chanA_irqs - chan A WR1 (per-channel IRQ source) + WR0 reset bits.
; KEEP IN SYNC with scc_enable_chanB_irqs (verbatim mirror: SCC_B_CMD ->
; SCC_A_CMD).  Does NOT touch WR9 — SIM owns the shared master enable on first
; install (see _Sys_SimInstallImpl).
;------------------------------------------------------------------------------
scc_enable_chanA_irqs MX %00
                PHP
                SEI
                SEP     #$30
                MX      %11

                LDAL    SCC_A_CMD               ; sync state machine to reg 0

                ; WR1 = $12
                LDA     #$01
                STAL    SCC_A_CMD
                LDA     #$12
                STAL    SCC_A_CMD

                ; WR0 = $30 (error reset)
                LDA     #$00
                STAL    SCC_A_CMD
                LDA     #$30
                STAL    SCC_A_CMD

                ; WR0 = $38 (Reset Highest IUS)
                LDA     #$00
                STAL    SCC_A_CMD
                LDA     #$38
                STAL    SCC_A_CMD

                PLP
                RTS

;==============================================================================
; Control-panel serial-parameter honoring.  Reads the IIgs control-panel
; baud/data-stop/parity from Battery RAM via ReadBParam (Misc Tool $0C03) and
; decodes them into _cc* (SCC register values + display chars) so each port runs
; AS CONFIGURED instead of a hardcoded 9600-8N1.  Decode matches serinfo.s
; (FGX's own BRAM-reader): baud code table; data=5+(raw>>1), stop=1+(raw&1);
; parity 0=Even 1=Odd 2=None.  Param refs (Toolbox Ref Table 14-3): port 1
; (chan A) baud=$06 ds=$07 parity=$08; port 2 (chan B) baud=$12 ds=$13 par=$14.
;==============================================================================

;------------------------------------------------------------------------------
; _serReadBP - read one Battery-RAM parameter.  In: A.lo = param ref (MX %00).
; Out: A = value (low byte; hi=0).  Clobbers X.  DBR preserved by the toolbox.
;------------------------------------------------------------------------------
_serReadBP      MX %00
                PEA     $0000                   ; result space
                PHA                             ; param ref number (A)
                LDX     #$0C03                  ; Misc.ReadBParam
                JSL     $E10000
                PLA                             ; A = result word
                AND     #$00FF
                RTS

;------------------------------------------------------------------------------
; _serCfgRead - read+decode a port's CP serial params, patch its banner.
; In: A = baud param ref ($06 chan A / $12 chan B).  Sets _ccTC/_ccWR3/_ccWR4/
; _ccWR5 (for scc_program) + display chars, and patches banner_{A,B}_tmpl.
;------------------------------------------------------------------------------
_serCfgRead     MX %00
                STA     _ccRef                  ; save baud ref base
                ; --- baud code (clamp invalid -> 13 = 9600) ---
                JSR     _serReadBP              ; A = baud code (ref = baud)
                CMP     #16
                BCC     @cf_bhi
                LDA     #13
@cf_bhi         CMP     #1
                BCS     @cf_blo
                LDA     #13
@cf_blo         STA     _ccBaudCode
                ASL     A                       ; *2 (word index)
                TAX
                LDA     _serBaudTC,X            ; 16-bit BRG time constant
                STA     _ccTC
                ; --- data/stop (ref+1) ---
                LDA     _ccRef
                INC     A
                JSR     _serReadBP
                STA     _ccDS
                ; --- parity (ref+2) ---
                LDA     _ccRef
                CLC
                ADC     #2
                JSR     _serReadBP
                STA     _ccPar
                JSR     _serDeriveWR            ; _ccWR3/4/5 + _ccDchar/Pchar/Schar
                LDA     _ccRef
                CMP     #$06
                BNE     @cf_pb
                JSR     _serPatchA
                RTS
@cf_pb          JSR     _serPatchB
                RTS

;------------------------------------------------------------------------------
; _serDeriveWR - from _ccDS (data/stop raw) + _ccPar, compute _ccWR3/_ccWR4/
; _ccWR5 and the display chars _ccDchar/_ccPchar/_ccSchar (high-ASCII).
;------------------------------------------------------------------------------
_serDeriveWR    MX %00
                PHP
                SEP     #$30
                MX      %11
                ; db_idx = (ds>>1) & 3   (0=5,1=6,2=7,3=8 data bits)
                LDA     _ccDS
                LSR     A
                AND     #$03
                TAX
                LDA     _serWR3tbl,X
                STA     _ccWR3
                LDA     _serWR5tbl,X
                STA     _ccWR5
                ; data display char = '0' + 5 + (ds>>1)
                TXA
                CLC
                ADC     #5
                CLC
                ADC     #'0'
                ORA     #$80
                STA     _ccDchar
                ; stop: ds&1 -> WR4 stop field + display digit
                LDA     _ccDS
                AND     #$01
                BEQ     @dw_1stop
                LDA     #$0C                    ; 2 stop bits
                STA     _ccTmp
                LDA     #'2'+$80
                STA     _ccSchar
                BRA     @dw_par
@dw_1stop       LDA     #$04                    ; 1 stop bit
                STA     _ccTmp
                LDA     #'1'+$80
                STA     _ccSchar
@dw_par         ; parity raw: 0=Odd($01,'O') 1=Even($03,'E') else None($00,'N').
                ; (Empirically 0=Odd/1=Even — the IIgs CP encoding; serinfo's
                ; original 0=Even/1=Odd was backwards.)
                LDA     _ccPar
                BEQ     @dw_po                  ; raw 0 = ODD
                CMP     #1
                BEQ     @dw_pe                  ; raw 1 = EVEN
                LDA     #$00
                STA     _ccPbits
                LDA     #'N'+$80
                STA     _ccPchar
                BRA     @dw_wr4
@dw_pe          LDA     #$03
                STA     _ccPbits
                LDA     #'E'+$80
                STA     _ccPchar
                BRA     @dw_wr4
@dw_po          LDA     #$01
                STA     _ccPbits
                LDA     #'O'+$80
                STA     _ccPchar
@dw_wr4         LDA     #$40                    ; x16 clock
                ORA     _ccTmp                  ; | stop field
                ORA     _ccPbits                ; | parity bits
                STA     _ccWR4
                PLP
                RTS

;------------------------------------------------------------------------------
; _serPatchA / _serPatchB - patch the 5-char baud field + data/parity/stop
; chars into the channel banner template from the decoded _cc* values.
;------------------------------------------------------------------------------
_serPatchA      MX %00
                PHP
                SEP     #$30
                MX      %11
                LDA     _ccBaudCode             ; *5 -> X (baud-string offset)
                STA     _ccTmp
                ASL     A
                ASL     A
                CLC
                ADC     _ccTmp
                TAX
                LDY     #0
@pa_l           LDA     _serBaud5,X
                STA     banA_baud,Y
                INX
                INY
                CPY     #5
                BCC     @pa_l
                LDA     _ccDchar
                STA     banA_d
                LDA     _ccPchar
                STA     banA_p
                LDA     _ccSchar
                STA     banA_s
                PLP
                RTS

_serPatchB      MX %00
                PHP
                SEP     #$30
                MX      %11
                LDA     _ccBaudCode
                STA     _ccTmp
                ASL     A
                ASL     A
                CLC
                ADC     _ccTmp
                TAX
                LDY     #0
@pb_l           LDA     _serBaud5,X
                STA     banB_baud,Y
                INX
                INY
                CPY     #5
                BCC     @pb_l
                LDA     _ccDchar
                STA     banB_d
                LDA     _ccPchar
                STA     banB_p
                LDA     _ccSchar
                STA     banB_s
                PLP
                RTS

