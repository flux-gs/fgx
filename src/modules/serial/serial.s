;------------------------------------------------------------------------------
; serial_poll - return current readability/writability mask.
;
; RR0 bit 0 (RX char available) maps directly to POLLIN ($01), and
; RR0 bit 2 (Tx buffer empty) maps directly to POLLOUT ($04) — same
; bit positions, so a single AND #$05 extracts both.
;------------------------------------------------------------------------------
serial_poll     MX %00
                CPY     #0                      ; minor 0 = chan A, 1 = chan B
                BNE     @sp_chanB
                BRL     serial_poll_A
@sp_chanB
                ; --- POLLIN = RX ring non-empty; POLLOUT = TX ring not full.
                ; Bit positions match POSIX: POLLIN=$01, POLLOUT=$04. ---
                PHP
                SEI
                SEP     #$30
                MX      %11
                LDA     #$00                    ; A.lo = result bitmask
                ; POLLIN IS THE DISCIPLINE'S ANSWER NOW, not the ring's.  This
                ; arm read `_sccRxHead'/`_sccRxTail' -- and T7 step 3 stops
                ; feeding that ring, so it would read empty forever and POLLIN
                ; would NEVER be set, while the bytes sat in `t_rawq' and a
                ; read(2) would have returned them at once.  A select-driven
                ; reader on the serial line would simply have gone deaf.
                ;
                ; FOURTH SIGHTING OF THIS EXACT SHAPE, and the first one caught
                ; BEFORE the increment underneath it landed rather than after:
                ; `_Ttyv_Poll' (virtual consoles), then BOTH pty arms at T6
                ; increment 4a, in opposite directions.  EVERY INCREMENT THAT
                ; STOPS FEEDING A QUEUE MUST ASK WHAT STILL READS IT -- the
                ; survey that asked it here found this arm and `serial_read',
                ; and `serial_ioctl' answers ENOTTY to everything, so those two
                ; were all of them.
                ;
                ; POLLOUT BELOW IS NOT MOVED.  The TX ring is real and still
                ; this driver's own: `serial_write' fills it and the transmit
                ; interrupt drains it, so its fullness IS the writability of
                ; this device.  Only the INPUT side became the discipline's.
                PHA                             ; the mask so far (8-bit)
                REP     #$30
                MX      %00
                PHB                             ; _serTtyOffB is MODULE-bank and
                PHK                             ;   a dispatched op runs on the
                PLB                             ;   KERNEL's DBR
                LDA     _serTtyOffB             ; the line's byte offset, from
                PLB                             ;   KSVC_CDSETTTYIDX at register
                LDY     #TTYIO_FREAD
                LDX     #KSVC_TTYSELECT
                JSL     SYS_KCALL               ; A = 1 ready / 0 not
                CMP     #1
                SEP     #$30
                MX      %11
                BNE     @sp_pollinDone
                PLA
                ORA     #$01                    ; POLLIN
                PHA
@sp_pollinDone  PLA
@sp_noIn        LDX     _sccTxHead
                INX
                CPX     _sccTxTail
                BEQ     @sp_done                ; TX ring full → no POLLOUT
                ORA     #$04                    ; POLLOUT
@sp_done        PHA                             ; stash 8-bit result
                REP     #$30
                MX      %00
                PLA
                AND     #$00FF
                PLP
                SEC
                RTL

;------------------------------------------------------------------------------
; serial_poll_A - chan A (tty00) poll.  KEEP IN SYNC with serial_poll's
; chan-B body (mirror: _sccRx*/_sccTx* -> ...A).
;------------------------------------------------------------------------------
serial_poll_A   MX %00
                PHP
                SEI
                SEP     #$30
                MX      %11
                LDA     #$00                    ; A.lo = result bitmask
                LDX     _sccRxHeadA
                CPX     _sccRxTailA
                BEQ     @spa_noIn
                ORA     #$01                    ; POLLIN
@spa_noIn       LDX     _sccTxHeadA
                INX
                CPX     _sccTxTailA
                BEQ     @spa_done               ; TX ring full → no POLLOUT
                ORA     #$04                    ; POLLOUT
@spa_done       PHA                             ; stash 8-bit result
                REP     #$30
                MX      %00
                PLA
                AND     #$00FF
                PLP
                SEC
                RTL

;------------------------------------------------------------------------------
; serial_isr - SIM handler for SCC chan B.  Lifted from
; src/standalone/simtest/simtest.s simtest_isr at tag
; sim-c05f-live-irq-display.
;
; ABI (per SIM dispatcher contract — spec §2.2):
;   In:   A   = RR3 contents (8-bit).
;         MX  = %11 (M=X=1).
;         DBR = kernel-bank (dispatcher's PHK/PLB before JSL; $02 = assembly ORG).
;         DP  = $0000 (dispatcher's TCD #0).
;         IRQs masked (firmware IRQ frame still on stack).
;   Out:  CLC + RTL = handled (dispatcher → _simExitHandled).
;         SEC + RTL = not ours (dispatcher → _simExitSccChn).
;
; No PHB needed: rings (_sccRxBuf/_sccTxBuf) live in the kernel bank, SCC
; access uses STAL/LDAL.  Module-bank statics are NOT accessed from
; this handler.  Future enhancements that need module-bank state must
; PHB/PHK/PLB around the access and restore DBR before RTL.
;
; Sources drained per IRQ entry:
;   - RX (RR3 bit 2): loop drain RR1+RR_DATA into _sccRxBuf ring,
;     error-reset on framing/parity, per-byte Reset Highest IUS.
;   - TX (RR3 bit 1): dequeue _sccTxBuf if non-empty, else issue
;     WR0=$28 (Reset Tx IP) and clear _sccTxInProgress.
;
; CRITICAL: do NOT issue WR0=$28 after a real TX dequeue — it kills
; the next TxIP that fires when the byte's hold→shift transition
; happens.  Only issue $28 on the idle path.  See simtest line 2361.
;------------------------------------------------------------------------------
serial_isr      ENT
                MX      %11
                ; Stash entry-time RR3 in our kernel-bank static so we can
                ; check each chan B source bit independently after the
                ; RX drain may have cleared others via Reset Highest IUS.
                STA     _isrEntryRR3

                ; --- RX path ---
                BIT     #$04                    ; chan B Rx IP?
                BEQ     @isr_skip_rx

@isr_rx_loop    LDA     #$01                    ; select RR1
                STAL    SCC_B_CMD
                LDAL    SCC_B_CMD               ; A = RR1 (status)
                PHA                             ; save for error check below
                LDAL    SCC_B_DATA              ; A = received byte; clears RR0 bit 0

                ; --- THE RING IS GONE (apple/fgx#108 T7 step 3).  It held
                ; arrived-but-unread bytes because nothing else did; `t_rawq'
                ; holds them now, with `ttyinput's own TTYHOG overflow handling
                ; instead of this loop's silent discard-when-full.  256 bytes
                ; of the kernel bank back, and one input queue on the line
                ; rather than two.
                ;
                ; `_sccRxCountB' REPLACES IT AS THE DENOMINATOR, and that is not
                ; bookkeeping: `t7noopen' asserts that a byte arriving on a line
                ; nobody holds is DISCARDED, and "the queue is empty" is equally
                ; what you read when the peer never sent anything.  The count is
                ; how that test tells a guard that held from a run that proved
                ; nothing.  Two bytes for a positive control that cannot be
                ; argued with.
                INC     _sccRxCountB

                ; --- THE FLIP (apple/fgx#108 T7): the byte also meets the LINE
                ; DISCIPLINE, at arrival, which is what dzrint does:
                ;     (*linesw[tp->t_line].l_rint)(c, tp);
                ;         -- vendor/2.11BSD/usr/sys/pdpuba/dz.c:259
                ; Guarded by the open count, which is dzrint's TS_ISOPEN test
                ; (dz.c:229) asked of state FGX maintains -- see _sccOpenB in
                ; include/memmap.s for why the bit itself cannot be used.
                ;
                ; THE RING IS STILL FED ABOVE, for one increment only: serial_read
                ; is still this line's only reader until T7 step 3 wires d_read
                ; to ttread, and stopping the ring here would break every reader
                ; between two commits.  Both queues hold the byte meanwhile; only
                ; the ring is drained, and t_rawq stops at TTYHOG (255).
                ; A.lo = the byte and MX is %11 here, so each push below is
                ; ONE byte: 1,S = P, 2,S = X, 3,S = the character.
                PHA
                PHX
                PHP
                REP     #$30
                MX      %00
                LDA     _sccOpenB
                BEQ     @isr_rx_noline          ; nobody holds it -- discard, as
                SEP     #$20                    ;   dzrint does at dz.c:229
                MX      %10
                LDA     3,S                     ; the character, read 8-BIT
                REP     #$30
                MX      %00
                AND     #$00FF                  ; ...the high half is stale B
                ORA     #{SER_TTYIDX_B*256}     ; Y = (idx << 8) | c
                TAY
                LDX     #KSVC_TTYIRQINPUT       ; the BANK-0 GATEWAY, not an
                JSL     SYS_KCALL               ;   exported address: see
                                                ;   include/modules.s.  Clobbers
                                                ;   X, which the loop re-reads
@isr_rx_noline  PLP                             ;   from _sccRxHead anyway
                MX      %11
                PLX
                PLA

@isr_check_err  PLA                             ; restore RR1
                AND     #$60                    ; framing / parity error bits
                BEQ     @isr_no_err
                LDA     #$00
                STAL    SCC_B_CMD               ; select WR0
                LDA     #$30
                STAL    SCC_B_CMD               ; error reset
@isr_no_err     LDA     #$00
                STAL    SCC_B_CMD               ; select WR0
                LDA     #$38
                STAL    SCC_B_CMD               ; Reset Highest IUS (per byte)

                LDAL    SCC_B_CMD               ; RR0
                AND     #$01                    ; Rx Char Available?
                BNE     @isr_rx_loop            ; more data — drain it

@isr_skip_rx
                ; --- TX path: IRQ-driven dequeue.  Mirrors gno sccf.asm
                ;     t_Tx_Int (line 104) + turnOffTxInt (line 142). ---
                LDA     _isrEntryRR3
                BIT     #$02                    ; chan B Tx IP?
                BEQ     @isr_skip_tx

                ; --- Anything in the TX ring? ---
                LDA     _sccTxTail
                CMP     _sccTxHead
                BEQ     @isr_tx_idle            ; empty → ACK + mark idle

                ; --- Dequeue one byte + write to SCC data register ---
                LDX     _sccTxTail
                LDA     _sccTxBuf,X
                INX
                STX     _sccTxTail
                STAL    SCC_B_DATA              ; transmit; hold→shift later re-arms TxIP
                ; CRITICAL: do NOT issue WR0=$28 (Reset Tx Int Pending) here.
                ; gno sccf.asm doTxChar uses ONLY $38 (Reset Highest IUS, the
                ; final reset below).  $28 here would clear the fresh TxIP set
                ; when this byte's hold→shift completes — the IRQ we need to
                ; dequeue the next byte.  $28 kills the chain after one byte.
                BRA     @isr_skip_tx

@isr_tx_idle    ; --- TX ring empty: ACK TxIP and clear in-progress flag.
                ;     Without WR0=$28 here, the chip would re-fire TxIP
                ;     continuously since buffer stays empty. ---
                LDA     #$00
                STAL    SCC_B_CMD
                LDA     #$28
                STAL    SCC_B_CMD               ; Reset Tx Interrupt Pending
                STZ     _sccTxInProgress

@isr_skip_tx
                ; --- Ext/Status (RR3 bit 0) is not enabled in WR15;
                ;     if it ever fires we'll see _simStatTotal climb but
                ;     no chan-claimed bit set, and the final Reset
                ;     Highest IUS below will clear it. ---

                ; --- Final Reset Highest IUS (covers TX/Ext paths) ---
                LDA     #$00
                STAL    SCC_B_CMD
                LDA     #$38
                STAL    SCC_B_CMD

                CLC                             ; handled
                RTL

;------------------------------------------------------------------------------
; serial_isr_A - SIM handler for SCC chan A (printer port).  KEEP IN SYNC with
; serial_isr (verbatim mirror: SCC_B_* -> SCC_A_*, ring syms -> ...A, RR3 RX
; bit $04 -> $20 / TX bit $02 -> $10, @isr_* -> @isrA_*).  Shares _isrEntryRR3
; with serial_isr — safe: the dispatcher runs one handler per IRQ (a CLC return
; ends the walk), so the two never overlap.  Same ABI (A=RR3 in; CLC+RTL).
;------------------------------------------------------------------------------
serial_isr_A    ENT
                MX      %11
                STA     _isrEntryRR3

                ; --- RX path ---
                BIT     #$20                    ; chan A Rx IP?
                BEQ     @isrA_skip_rx

@isrA_rx_loop   LDA     #$01                    ; select RR1
                STAL    SCC_A_CMD
                LDAL    SCC_A_CMD               ; A = RR1 (status)
                PHA                             ; save for error check below
                LDAL    SCC_A_DATA              ; A = received byte; clears RR0 bit 0

                ; --- Ring full? (head+1 == tail) ---
                LDX     _sccRxHeadA
                INX
                CPX     _sccRxTailA
                BEQ     @isrA_check_err         ; ring full -> discard byte (in A)

                ; --- Not full: store + advance head ---
                DEX                             ; X = head
                STA     _sccRxBufA,X
                INX
                STX     _sccRxHeadA

@isrA_check_err PLA                             ; restore RR1
                AND     #$60                    ; framing / parity error bits
                BEQ     @isrA_no_err
                LDA     #$00
                STAL    SCC_A_CMD               ; select WR0
                LDA     #$30
                STAL    SCC_A_CMD               ; error reset
@isrA_no_err    LDA     #$00
                STAL    SCC_A_CMD               ; select WR0
                LDA     #$38
                STAL    SCC_A_CMD               ; Reset Highest IUS (per byte)

                LDAL    SCC_A_CMD               ; RR0
                AND     #$01                    ; Rx Char Available?
                BNE     @isrA_rx_loop           ; more data — drain it

@isrA_skip_rx
                ; --- TX path: IRQ-driven dequeue. ---
                LDA     _isrEntryRR3
                BIT     #$10                    ; chan A Tx IP?
                BEQ     @isrA_skip_tx

                ; --- Anything in the TX ring? ---
                LDA     _sccTxTailA
                CMP     _sccTxHeadA
                BEQ     @isrA_tx_idle           ; empty → ACK + mark idle

                ; --- Dequeue one byte + write to SCC data register ---
                LDX     _sccTxTailA
                LDA     _sccTxBufA,X
                INX
                STX     _sccTxTailA
                STAL    SCC_A_DATA              ; transmit; hold→shift later re-arms TxIP
                ; CRITICAL: no WR0=$28 after a real dequeue (see serial_isr).
                BRA     @isrA_skip_tx

@isrA_tx_idle   ; --- TX ring empty: ACK TxIP and clear in-progress flag. ---
                LDA     #$00
                STAL    SCC_A_CMD
                LDA     #$28
                STAL    SCC_A_CMD               ; Reset Tx Interrupt Pending
                STZ     _sccTxInProgressA

@isrA_skip_tx
                ; --- Final Reset Highest IUS (covers TX/Ext paths) ---
                LDA     #$00
                STAL    SCC_A_CMD
                LDA     #$38
                STAL    SCC_A_CMD

                CLC                             ; handled
                RTL

;------------------------------------------------------------------------------
; scc_program_chanB — program SCC chan B for 9600-8N1, RX+TX enabled,
; interrupts off.  Per Tech Note #18 sequence; PHP/SEI/PLP wraps the
; multi-step register accesses so a same-time chan A IRQ can't tear
; them.
;
; Baud time-constant math (PCLK = 3.6864 MHz, x16 clock):
;   TC = PCLK / (2 * N * baud) - 2
;   For x16 clock + 9600 baud:
;     TC = 3686400 / (2 * 16 * 9600) - 2 = 12 - 2 = 10 = $0A
;   (Earlier comment had the wrong formula — divided by 16*baud instead
;    of 2*16*baud — and wrote $16, which is actually 4800 baud and
;    produced garbled output on the modem terminal at boot.)
;------------------------------------------------------------------------------
scc_program_chanB MX %00
                PHP
                SEP     #$30                            ; M=8 X=8 for byte bashing
                MX      %11
                SEI                                     ; block chan A IRQ races

                LDAL    SCC_B_CMD                       ; sync state machine to reg 0

                ; WR4 = parity + stop bits + x16 clock (from control panel)
                LDA     #$04
                STAL    SCC_B_CMD
                LDA     _ccWR4
                STAL    SCC_B_CMD

                ; WR3 = data bits, RX DISABLED during baud config
                LDA     #$03
                STAL    SCC_B_CMD
                LDA     _ccWR3
                AND     #$FE                            ; clear RX-enable bit
                STAL    SCC_B_CMD

                ; WR5 = data bits, TX DISABLED during baud config
                LDA     #$05
                STAL    SCC_B_CMD
                LDA     _ccWR5
                AND     #$F7                            ; clear TX-enable bit
                STAL    SCC_B_CMD

                ; WR11 = $50  (chan B borrows chan A's xtal; rx/tx clk = BRG out)
                LDA     #$0B
                STAL    SCC_B_CMD
                LDA     #$50
                STAL    SCC_B_CMD

                ; WR12/WR13 = BRG time constant (baud, from control panel)
                LDA     #$0C
                STAL    SCC_B_CMD
                LDA     _ccTC                           ; TC lo
                STAL    SCC_B_CMD
                LDA     #$0D
                STAL    SCC_B_CMD
                LDA     _ccTC+1                         ; TC hi
                STAL    SCC_B_CMD

                ; WR14 = $00 (BRG src = /RTxC, off) then $01 (enable BRG)
                LDA     #$0E
                STAL    SCC_B_CMD
                LDA     #$00
                STAL    SCC_B_CMD
                LDA     #$0E
                STAL    SCC_B_CMD
                LDA     #$01
                STAL    SCC_B_CMD

                ; WR3 = data bits, RX ENABLED
                LDA     #$03
                STAL    SCC_B_CMD
                LDA     _ccWR3
                STAL    SCC_B_CMD

                ; WR5 = data bits, TX ENABLED
                LDA     #$05
                STAL    SCC_B_CMD
                LDA     _ccWR5
                STAL    SCC_B_CMD

                ; WR15 = $00  (no external/status interrupts)
                LDA     #$0F
                STAL    SCC_B_CMD
                LDA     #$00
                STAL    SCC_B_CMD

                PLP
                RTS

