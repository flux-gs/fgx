;==============================================================================
; prodos.s - the assembly root of prodos.mod: the ProDOS filesystem type,
; compiled from C, in a loadable FGXM module.  ProDOS FST P2.
;
; A MOUNTABLE TYPE, NOT A ROOT.  It is loaded by /etc/rc's modload after the
; UFS root is up, and mount(2) reaches it through vfssw[MOUNT_PRODOS], which
; prodos_init fills.  Nothing at boot needs it.
;
; ITS OWN BANK, ORDINAL 5 ($0A0000), for size: its slot in the shared bank
; after pty was 47,872 bytes and create and mkdir outgrew it
; (tools/gen_modplace.py OWN_BANK).
;
; THE READ HALF.  Rename and truncate took prodos.mod past a whole bank, so the
; write half -- prodos_write.c -- is prodosw.mod, in ordinal 6.  This module
; mounts, reads and owns the vnode vector; prodosw.mod reaches the node layer
; through VT_PDCORE below and hands its entry points to the vector with
; pd_setwriteops.  Without prodosw.mod a volume mounts read-only.
;
; THE SEAM IS ufs.mod's: the C needs vfs.mod's buffer cache, vnode pool and
; namei, reached through vfs_import.s, generated by tools/gen_mod_imports.py.
;
; MODBANK-C-OK: every global, literal and runtime scratch this module's C
; touches is read DBR-relatively, which is correct here for ufs.mod's reason --
; the C is only ever entered through MOD_KC_ENTER, or through a vfs_import.s
; shim or a vnode-op dispatch that establishes the same thing.  The waiver is
; at MODULE level because both the accesses and the declarations live in fcc
; OUTPUT.
;==============================================================================

                MX      %11
                PUT     modplace.s
                ORG     MODP_ORG

                PUT     ../../../include/config.s       ; CFG_* build gates
                PUT     ../../../include/macros.s       ; FGX2_MODE/EXPORT/RELOC
                PUT     ../../../include/kernel.s       ; FGX_DP_KERNELC
                PUT     ../../../include/dpmap.s        ; DUM $00: the block
                PUT     ../../../include/modules.s      ; SYS_KCALL, KSVC_*,
                                                        ;   VT_VFSCORE, VFSCORE_*
                PUT     ../../../include/kernelc.s      ; MOD_KC_ENTER/LEAVE
                PUT     ../../../include/fs.s           ; DEV_* record layout
                PUT     ../../../include/vfs_equ.s      ; GENERATED from the C

;------------------------------------------------------------------------------
; FGXM header (40 bytes).  See include/fgxm.s.
;------------------------------------------------------------------------------
pd_bss          EQU     0
pd_hdr          ASC     'FGXM'                          ; +0  magic
                DFB     <MODP_ORG                       ; +4  load lo
                DFB     >MODP_ORG                       ; +5  load mid
                DFB     ^MODP_ORG                       ; +6  load hi
                DFB     $02                             ; +7  header format v2
                DA      mod_init-$0A0000                ; +8  entry, bank-rel
                DA      pd_end-pd_text                  ; +10 text bytes
                DA      pd_bss                          ; +12 bss bytes
                DA      pd_vtdir-pd_text                ; +14 vtdir offset
pd_name         ASC     'prodos'                        ; +16 module name
                DS      16-*+pd_name                    ;     NUL-pad to 16
                DA      $0000                           ; +32 module version
                DA      $0000
                DS      4                               ; +36 reserved

pd_text         EQU     *

; mount(2) finds this module through vfssw[], which prodos_init fills.  The
; VTDR is for prodosw.mod, the write half: VT_PDCORE, in PDCORE_* order, plain
; 16-bit addresses whose bank the loader returns with the table (VT_UFSCORE's
; form, src/modules/ufs/ufs.s).
pd_vtdir        ASC     'VTDR'
                DA      VT_PDCORE
                DA      pdcore_ops-pd_text      ; text-relative; the loader makes
                                                ;   it bank-relative (modload.s)
                DA      VT_END

pdcore_ops      DA      pdget                   ; PDCORE_Pdget
                DA      pd_fork                 ; PDCORE_Fork
                DA      pd_entsync              ; PDCORE_Entsync
                DA      pd_twin                 ; PDCORE_Twin
                DA      pd_rekey                ; PDCORE_Rekey
                DA      pd_bmap                 ; PDCORE_Bmap
                DA      pd_unlock               ; PDCORE_Unlock
                DA      pd_setwriteops          ; PDCORE_Setwriteops
                ERR     *-pdcore_ops-{PDCORE_COUNT*2}

; The C-to-kernel seam, then the module-to-module seam.  BEFORE mod_init, for
; ufs.s's reason: they define macros Merlin needs defined before use.
                PUT     ../common/kc_sys.s
                PUT     vfs_import.s

;------------------------------------------------------------------------------
; mod_init - stamp the &function cells, resolve vfs.mod, then run prodos_init.
; ufs.s's mod_init, line for line: a module whose import table is empty must
; run no C, because the first call through it goes to bank 0.
;------------------------------------------------------------------------------
mod_init        MX      %00
                PHP
                REP     #$30
                MX      %00
                PHB
                PHK
                PLB                     ; DBR = ours, for everything below

                JSR     _Mod_StampFnPtrs
                JSR     _Pd_ResolveVfs
                BCC     @mi_novfs       ; no vfs.mod: run NO C at all

                MOD_KC_ENTER
                PHK
                PEA     @mi_initret-1
                JMP     prodos_init
                ; THE LABEL GETS ITS OWN LINE, for ufs.s's reason:
                ; tools/check_kc_dbr.py matches MOD_KC_LEAVE only at the start
                ; of a line.
@mi_initret     ANOP
                MOD_KC_LEAVE

@mi_out         PLB
                PLP
                SEC
                RTL

@mi_novfs       LDA     #@mi_msgNoVfs
                LDX     #KSVC_LOGSTRNE
                JSL     SYS_KCALL
                LDX     #KSVC_LOGEOL
                JSL     SYS_KCALL
                BRA     @mi_out

@mi_msgNoVfs    ASC     'prodos: vfs.mod not loaded',$00

;------------------------------------------------------------------------------
; _Pd_ResolveVfs - copy vfs.mod's VT_VFSCORE table into _pdVImp.  ufs.s's
; _Ufs_ResolveVfs exactly.  C=1 on success.
;------------------------------------------------------------------------------
_Pd_ResolveVfs  MX      %00
                LDA     #VT_VFSCORE
                LDX     #KSVC_FINDVTABLE
                JSL     SYS_KCALL
                BCS     @rv_have
                RTS                             ; C=0 already
@rv_have        TAY                             ; park the table address
                TXA
                AND     #$00FF
                STA     |_pdVfsBank     ; MODBANK-OK: DBR = ours (mod_init set it)
                TYX                             ; X = table address
                REP     #$30
                MX      %00
                LDY     #0
@rv_L           SEP     #$20
                MX      %10
                LDA     |_pdVfsBank     ; MODBANK-OK: DBR is ours here
                PHA
                PLB                             ; DBR = vfs.mod
                REP     #$20
                MX      %00
                LDA     |$0000,X                ; the entry, from vfs.mod
                PHK
                PLB                             ; DBR ours again -- A survives
                STA     |_pdVImp,Y      ; MODBANK-OK: DBR = ours
                INX
                INX
                INY
                INY
                CPY     #VFSCORE_COUNT*2
                BNE     @rv_L
                SEC
                RTS

;------------------------------------------------------------------------------
; The fcc runtime and the C.
;------------------------------------------------------------------------------
                PUT     ../../kernel/libc/alloc_state.s
                PUT     ../../kernel/far/fcc_dp.s       ; fcc register file (EQU)
                PUT     ../../kernel/far/fcc_rt.s       ; pure-computation half
                PUT     ../../kernel/far/fcc_ktrap.s    ; stack/soft-frame traps
                PUT     ../../../toolchain/lib/fcc_runtime_data.s
                ; The calendar arithmetic ufs.mod's clock uses, for directory
                ; stamps: the same compiled file, which holds no state.
                PUT     ../../kernel/vfs/kern_epoch.s
                PUT     ../../kernel/vfs/kern_epoch.data.s
                PUT     ../../kernel/vfs/prodos_node.s
                PUT     ../../kernel/vfs/prodos_node.data.s
                PUT     ../../kernel/vfs/prodos_vfsops.s
                PUT     ../../kernel/vfs/prodos_vfsops.data.s
                PUT     ../../kernel/vfs/prodos_vnops.s
                PUT     ../../kernel/vfs/prodos_vnops.data.s
                ; LAST: the only output whose size depends on a scan of this
                ; module's own listing, so nothing after it can move a cell.
                PUT     fnptr_patchsites.s

pd_end          EQU     *
                ERR     pd_hdr-MODP_ORG
                ERR     pd_end-MODP_ORG+pd_bss/MODP_LIMIT
; ...and the ordinal: the header's entry field is bank-relative against a
; LITERAL $0A0000.
                ERR     MODP_ORG/$10000-$0A
