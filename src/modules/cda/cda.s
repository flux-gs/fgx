cda_border      DS      1               ; $C034 low nibble when the menu opened
cda_textcol     DS      1               ; $C022 when the menu opened
cda_nib         DS      1               ; scratch
cda_fpt         DS      CDA_FPT_MAX*4   ; the table given to SetTSPtr
cda_isopen      DS      2               ; /dev/cda is open
cda_state       DS      2               ; 0 idle, 1 a block is reserved
cda_id          DS      2               ; the reserved block's user ID
cda_h           DS      4               ; its handle
cda_addr        DS      4               ; its address
cda_size        DS      2               ; its size
cda_off         DS      2               ; CDAIOCLOAD's arguments
cda_len         DS      2
cda_dev         DS      2               ; the chardev index registration gave
cda_faddr       DS      4               ; the reserved pathname-and-fork block
cda_fsize       DS      2               ;   and its size; 0 when there is none
cda_laddr       DS      4               ; the block CDAIOCLOAD writes, and its size
cda_lsize       DS      2
