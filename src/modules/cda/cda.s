;------------------------------------------------------------------------------
; /dev/cda ioctls.  MUST match src/userland/loadcda/loadcda.c.  Each argument is
; a structure in the caller's data bank:
;   CDAIOCRESERVE  +0 size (long, in; high word 0)  +4 address (long, out)
;   CDAIOCLOAD     +0 offset  +2 length  +4 buffer (low 16 bits, data bank)
;                  +6 which block: 0 the CDA, 1 its pathname and fork
;   CDAIOCINSTALL  no argument
;   CDAIOCFORK     +0 size (long, in; high word 0): reserve the second block,
;                  a class 1 GS/OS string of the pathname, then the fork
;------------------------------------------------------------------------------
CDAIOCRESERVE   EQU     $6301           ; 'c'<<8|1
CDAIOCLOAD      EQU     $6302
CDAIOCINSTALL   EQU     $6303
CDAIOCFORK      EQU     $6304

EPERM           EQU     1               ; include/errno.s
ENOMEM          EQU     12
EBUSY           EQU     16
EINVAL          EQU     22
ENOTTY          EQU     25
ENOSPC          EQU     28

