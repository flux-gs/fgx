cda_tn          DS      2               ;   return addresses and data bank
cda_tr          DS      6
cda_tb          DS      1

;------------------------------------------------------------------------------
; CharDev_Ops for /dev/cda, in include/chardev.s's COPS_* order.  The third byte
; of a slot is not used for dispatch (src/kernel/chardev.s, the bank captured at
; registration is), and a slot is absent only when all three bytes are zero.
;------------------------------------------------------------------------------
cda_ops         DFB     <cda_open,>cda_open,0
                DFB     <cda_close,>cda_close,0
                DFB     0,0,0                   ; getc
                DFB     0,0,0                   ; putc
                DFB     <cda_ioctl,>cda_ioctl,0
                DFB     0,0,0                   ; poll
                DFB     0,0,0                   ; d_read
                DFB     0,0,0                   ; d_write
                DFB     0,0,0                   ; d_stop
cda_name        ASC     'cda',$00

;------------------------------------------------------------------------------
; mod_init -- install the Desk Manager patches.  MX %00 in; C=1 ok, C=0 failed.
;------------------------------------------------------------------------------
mod_init        MX      %00
                PHK
                PLB                             ; DBR = our bank
                SEP     #$20
                MX      %10
                PHK
                PLA
                REP     #$20
                MX      %00
                AND     #$00FF
                STA:    cda_bank

                ; --- cda_old = GetTSPtr($0000, DESK_TS) ---
                PEA     $0000                   ; result space (long)
                PEA     $0000
                PEA     $0000                   ; system tool set
                PEA     DESK_TS
                LDX     #_GetTSPtr
                JSL     TOOL_DISPATCH
                PLA
                STA:    cda_old
                PLA
                STA:    cda_old+2
                BCC     @mi_got
                LDX     #getfail_msg
                JMP     @mi_fail
@mi_got         LDA:    cda_old
                STA     _libcTmp2
                LDA:    cda_old+2
                STA     _libcTmp2+2

                ; --- the count: the table's first longword, bounds-checked ---
                LDY     #0
                LDA     [_libcTmp2],Y
                CMP     #FPT_RESTALL/4+1        ; must reach RestAll
                BCC     @mi_szj
                CMP     #CDA_FPT_MAX+1
                BCS     @mi_szj
                STA:    cda_fpt
                LDY     #2
                LDA     [_libcTmp2],Y
                BEQ     @mi_szok
@mi_szj         BRL     @mi_size
@mi_szok        STA:    cda_fpt+2

                ; --- the originals, as jump targets (a table entry is the
                ;     routine's address less one) ---
                LDY     #FPT_SAVEALL
                LDA     [_libcTmp2],Y
                CLC
                ADC     #1
                STA:    cda_sa_jml+1
                LDY     #FPT_SAVEALL+2
                LDA     [_libcTmp2],Y
                ADC     #0
                SEP     #$20
                MX      %10
                STA:    cda_sa_jml+3
                REP     #$20
                MX      %00
                LDY     #FPT_RESTALL
                LDA     [_libcTmp2],Y
                CLC
                ADC     #1
                STA:    cda_ra_jml+1
                LDY     #FPT_RESTALL+2
                LDA     [_libcTmp2],Y
                ADC     #0
                SEP     #$20
                MX      %10
                STA:    cda_ra_jml+3
                REP     #$20
                MX      %00

                ; --- our entries, each this module's bank and address less one ---
                LDA     #cda_bootinit-1
                STA:    cda_fpt+FPT_BOOTINIT
                LDA:    cda_bank
                STA:    cda_fpt+FPT_BOOTINIT+2
                LDA     #cda_saveall-1
                STA:    cda_fpt+FPT_SAVEALL
                LDA:    cda_bank
                STA:    cda_fpt+FPT_SAVEALL+2
                LDA     #cda_restall-1
                STA:    cda_fpt+FPT_RESTALL
                LDA:    cda_bank
                STA:    cda_fpt+FPT_RESTALL+2

                ; --- /dev/cda.  Registered after every check that can refuse
                ;     this module and before anything it cannot take back: a
                ;     registration cannot be withdrawn, so a mod_init that
                ;     failed after it would leave the device pointing into a
                ;     module that was never kept. ---
                LDA     #cda_name
                LDX     #cda_ops
                LDY     #{{CDF_FIXED+{DEVNODE_CDA*4}}*256}+0 ; minor 0, at /dev/cda's number
                JSL     MOD_REGISTERCHARDEV
                BCS     @mi_reg
                LDX     #regfail_msg
                JMP     @mi_fail
@mi_reg         STA:    cda_dev

                ; --- SetTSPtr(DESK_PATCH, DESK_TS, cda_fpt) ---
                PEA     DESK_PATCH
                PEA     DESK_TS
                LDA:    cda_bank
                PHA                             ; fptPtr high word
                PEA     cda_fpt                 ; fptPtr low word
                LDX     #_SetTSPtr
                JSL     TOOL_DISPATCH
                BCC     @mi_ok
                ; The device is registered and stays usable, so the module
                ; stays: only the colours go unrestored.
                LDX     #setfail_msg
                JSL     SYS_MODLOG
                BRA     @mi_stubs
@mi_size        LDX     #sizefail_msg
@mi_fail        JSL     SYS_MODLOG
                CLC
                RTL
@mi_ok          LDX     #ok_msg
                JSL     SYS_MODLOG

                ; --- the GS/OS entry: JML cda_gsos, the operand before the
                ;     opcode ---
@mi_stubs       LDA     #cda_gsos
                STAL    GSOS_ENTRY+1
                SEP     #$20
                MX      %10
                LDA:    cda_bank
                STAL    GSOS_ENTRY+3
                LDA     #$5C
                STAL    GSOS_ENTRY
                REP     #$20
                MX      %00

                ; --- the Loader table: housekeeping answers no error,
                ;     LGetPathname2 is served, the rest go to their stubs ---
                LDA     #LDR_COUNT
                STA:    cda_ldrfpt
                LDA     #cda_bootinit-1
                LDX     #$01*4
@mi_hk          STA:    cda_ldrfpt,X
                INX
                INX
                INX
                INX
                CPX     #$07*4
                BCC     @mi_hk
                LDA     #cda_nistubs-1
@mi_ni          STA:    cda_ldrfpt,X
                CLC
                ADC     #4
                INX
                INX
                INX
                INX
                CPX     #LDR_GETPATH2*4
                BCC     @mi_ni
                LDA     #cda_lgp2-1
                STA:    cda_ldrfpt,X
                LDX     #$01*4+2
@mi_bank        LDA:    cda_bank
                STA:    cda_ldrfpt,X
                INX
                INX
                INX
                INX
                CPX     #LDR_COUNT*4
                BCC     @mi_bank

                ; --- SetTSPtr($0000, LOADER_TS, cda_ldrfpt) ---
                PEA     $0000
                PEA     LOADER_TS
                LDA:    cda_bank
                PHA
                PEA     cda_ldrfpt
                LDX     #_SetTSPtr
                JSL     TOOL_DISPATCH
                BCC     @mi_ldr
                LDX     #ldrfail_msg
                JSL     SYS_MODLOG
                BRA     @mi_dev
@mi_ldr         LDA     #1
                STA:    cda_gsok
                LDX     #stub_msg
                JSL     SYS_MODLOG
@mi_dev         LDA     #dev_msg
                LDX     #KSVC_LOGSTRNE
                JSL     SYS_KCALL               ; "cda: /dev/cda is device "
                PHK
                PLB
                LDA:    cda_dev
                LDX     #KSVC_LOGDEC16
                JSL     SYS_KCALL
                LDX     #KSVC_LOGEOL
                JSL     SYS_KCALL
                SEC
                RTL

;------------------------------------------------------------------------------
; cda_bootinit -- the table's BootInit: no error (TN #101).
;------------------------------------------------------------------------------
cda_bootinit    MX      %00
                LDA     #0
                CLC
                RTL

;------------------------------------------------------------------------------
; cda_saveall -- SaveAll's head patch: record the border and text colours the
; menu is about to replace, then run SaveAll.
;------------------------------------------------------------------------------
cda_saveall     MX      %00
                PHP
                REP     #$30
                PHA
                PHB
                PHK
                PLB
                STZ:    cda_isopn               ; no fork is open across visits
                SEP     #$20
                MX      %10
                LDAL    CLOCKCTL
                AND     #$0F
                STA:    cda_border
                LDAL    TBCOLOR
                STA:    cda_textcol
                LDA:    cda_gsok
                BEQ     @sa_run
                LDAL    OS_KIND
                STA:    cda_oskind
                LDA     #1
                STAL    OS_KIND
@sa_run         REP     #$20
                MX      %00
                PLB
                PLA
                PLP
cda_sa_jml      JML     $000000                 ; operand: SaveAll, set by mod_init

;------------------------------------------------------------------------------
; cda_restall -- RestAll's head patch: put back what cda_saveall recorded, then
; run RestAll.  Only $C034's low nibble is the border; its high nibble drives
; the clock chip and is left as it is.
;------------------------------------------------------------------------------
cda_restall     MX      %00
                PHP
                REP     #$30
                PHA
                PHB
                PHK
                PLB
                SEP     #$20
                MX      %10
                LDAL    CLOCKCTL
                AND     #$F0
                STA:    cda_nib
                LDA:    cda_border
                ORA:    cda_nib
                STAL    CLOCKCTL
                LDA:    cda_textcol
                STAL    TBCOLOR
                LDA:    cda_gsok
                BEQ     @ra_con
                LDA:    cda_oskind
                STAL    OS_KIND
@ra_con         LDAL    KFGX_ANCHOR             ; ask the kernel to repaint the
                STA:    @ra_req+3               ;   console at its next safe point
                LDA     #1
@ra_req         STAL    _kConRestoreReq         ; bank byte: the live kernel's
                REP     #$20
                MX      %00
                PLB
                PLA
                PLP
cda_ra_jml      JML     $000000                 ; operand: RestAll, set by mod_init

;------------------------------------------------------------------------------
; cda_open -- the super-user only, one opener at a time.  DBR = kernel bank on
; entry, as for every op; C=1 ok, C=0 + A = errno.
;------------------------------------------------------------------------------
cda_open        MX      %00
                LDX     #KSVC_CURUID
                JSL     SYS_KCALL               ; A = effective uid
                PHB
                PHK
                PLB
                CMP     #0
                BNE     @op_perm
                LDA:    cda_isopen
                BNE     @op_busy
                LDA     #1
                STA:    cda_isopen
                PLB
                SEC
                RTL
@op_perm        LDA     #EPERM
                BRA     @op_err
@op_busy        LDA     #EBUSY
@op_err         PLB
                CLC
                RTL

;------------------------------------------------------------------------------
; cda_close -- a block reserved and never installed is given back.
;------------------------------------------------------------------------------
cda_close       MX      %00
                PHB
                PHK
                PLB
                LDA:    cda_state
                BEQ     @cl_idle
                JSR     cda_discard
@cl_idle        STZ:    cda_isopen
                PLB
                SEC
                RTL

; cda_discard -- dispose of the reserved blocks and their ID.  DBR = our bank.
cda_discard     MX      %00
                LDA:    cda_id
                PHA
                LDX     #_DisposeAll
                JSL     TOOL_DISPATCH
                LDA:    cda_id
                PHA
                LDX     #_DeleteID
                JSL     TOOL_DISPATCH
                STZ:    cda_state
                STZ:    cda_fsize
                RTS

;------------------------------------------------------------------------------
; cda_ioctl -- read the syscall layer's copy of the command and argument while
; DBR is still the kernel's, then dispatch.  Each handler returns A = errno,
; 0 for success.
;------------------------------------------------------------------------------
cda_ioctl       MX      %00
                LDA     _Sys_IoctlArgLo
                STA     _libcTmp2
                LDA     _Sys_IoctlArgBank
                AND     #$00FF
                STA     _libcTmp2+2
                LDA     _Sys_IoctlCmd
                PHB
                PHK
                PLB
                CMP     #CDAIOCRESERVE
                BNE     @io_1
                JSR     cda_reserve
                BRA     @io_ret
@io_1           CMP     #CDAIOCLOAD
                BNE     @io_2
                JSR     cda_load
                BRA     @io_ret
@io_2           CMP     #CDAIOCINSTALL
                BNE     @io_3
                JSR     cda_install
                BRA     @io_ret
@io_3           CMP     #CDAIOCFORK
                BNE     @io_4
                JSR     cda_fork
                BRA     @io_ret
@io_4           LDA     #ENOTTY
@io_ret         PLB
                CMP     #0
                BNE     @io_err
                SEC
                RTL
@io_err         CLC
                RTL

; cda_reserve -- CDAIOCRESERVE.  _libcTmp2 = the argument.
cda_reserve     MX      %00
                LDA:    cda_state
                BEQ     @rs_idle
                LDA     #EBUSY
                RTS
@rs_idle        LDY     #2
                LDA     [_libcTmp2],Y
                BNE     @rs_inval               ; one bank at most
