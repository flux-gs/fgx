cda_bss         EQU     0

cda_hdr         ASC     'FGXM'                          ; +0  magic
                DFB     <MODP_ORG                        ; +4  load lo
                DFB     >MODP_ORG                        ; +5  load mid
                DFB     ^MODP_ORG                        ; +6  load hi
                DFB     $02                             ; +7  header format version (v2)
                DA      mod_init-$050000                ; +8  entry offset
                DA      cda_end-cda_text                ; +10 text bytes
                DA      cda_bss                         ; +12 bss bytes
                DA      cda_vtdir-cda_text              ; +14 vtdir offset
cda_modname     ASC     'cda'                           ; +16 module name
                DS      16-*+cda_modname                ;     NUL-pad to 16 bytes
                DA      $0000                           ; +32 module version (reserved)
                DA      KERN_BUILD_ID                   ; +34 kernel build identity
                DS      4                               ; +36 reserved

cda_text        EQU     *

cda_vtdir       ASC     'VTDR'
                DA      $0000                           ; VT_END

;------------------------------------------------------------------------------
