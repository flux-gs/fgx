;==============================================================================
; cda.s - FGXM module: classic desk accessory support.
;
; The ROM's Desk Manager runs the Ctrl-OA-Esc menu over FGX without help, and
; Quit returns to a working shell.  What it does not give back is the screen
; border and the text colours: it switches to the Control Panel's settings for
; the menu and leaves them there (measured: $C034's low nibble 2 -> 5, $C022
; $F2 -> $F4), while it restores NEWVIDEO and the shadow register itself.
;
; THE HOOK IS GNO/ME's (examples/gno/kern/gno/patch.c:42-43,
; kern/drivers/conpatch.asm): SaveAll ($0B05) runs as the menu opens and
; RestAll ($0C05) as it closes, both through the Desk Manager's function
; pointer table (measured: one call each per menu visit).  SaveAll's patch
; records the colours; RestAll's puts them back.  Both are head patches that
; leave A, X and Y as they found them and jump to the original, as Technical
; Note #101 asks.
;
; THE TABLE IS INSTALLED, NOT WRITTEN.  GNO writes into the table GetTSPtr
; returns, which under GS/OS is a RAM patch table.  On a bare ROM 03 the Tool
; Locator's pointer table and the Desk Manager's function table are both in
; ROM (measured: $FE/0139 and $FE/C57B).  So this module builds a function
; pointer table of the same size -- its count copied from the ROM's, zero
; except the entries it patches -- and gives it to SetTSPtr, which copies the
; Tool Locator's table to RAM and fills the zero entries from the old one.
; TN #101: BootInit must be patched to return no error, the pointers are one
; less than the routines, and on ROM 3 tool set 5 is patched with
; userOrSystem $0001 -- $0000 is ignored.
;
; /DEV/CDA IS HOW loadcda(8) INSTALLS A CDA, in the order BSD's modload(8)
; drives /dev/lkm (examples/netbsd-0-9/sys/kern/kern_lkm.c: LMRESERV, LMLOADBUF,
; LMREADY): CDAIOCRESERVE takes a desk accessory user ID (type $5000, GS/OS's
; DA_id_type) and a locked, fixed block under it that stays in one bank, and
; returns the block's address so loadcda can relocate the CDA for it;
; CDAIOCLOAD copies a chunk of the relocated image in; CDAIOCINSTALL gives the
; block to the Desk Manager's InstallCDA ($0F05), whose handle it then is.  A
; close before CDAIOCINSTALL disposes of the block and its ID.  Only the super-
; user may open the device, and only one process at a time.
;
; A DESK ACCESSORY MAY READ ITS OWN RESOURCE FORK, as DocVue does on first use:
; the System Loader's LGetPathname2 ($2211) for its pathname, then GS/OS Open
; (resource fork), SetMark, Read and Close.  Those calls come from inside the
; menu, with every FGX task stopped, so nothing here reaches a disk.  loadcda
; hands over a second block with the CDA -- its absolute pathname as a class 1
; GS/OS string, then its resource fork -- and after CDAIOCINSTALL that block is
; registered under the CDA's user ID, which is the ID its MMStartUp returns
; (measured: $5001 for the first).  Two stubs serve it:
;   - the GS/OS inline entry $E1/00A8 (a BRK on a bare ROM) becomes a JML to
;     cda_gsos, which takes a call the way GS.OS/DeskAccessories/GSOS.CDA.src's
;     inline trap does: call number and parameter block pointer after the
;     JSL, return address moved past them, error in A with carry set;
;   - tool set $11, the Loader, which is not in ROM, gets a table through
;     SetTSPtr whose LGetPathname2 answers for a registered ID and file 1.
;     Every other Loader function drops its inputs and returns $0002, as
;     GS.OS/Loader/Functions.a's Load_NI does, with the input sizes of
;     GS.OS/Loader/Loader.Equates and Init.Load.a.
; os_kind ($E1/00BC) reads 1 (GS/OS) only between SaveAll and RestAll, and only
; when both stubs are in, so no code outside a desk accessory is told GS/OS is
; there.
;
; A DESK ACCESSORY MAY LEAVE SUPER HI-RES AS IT DREW IT: DocVue leaves SCB 0 and
; palette 0 zero and its own pixels in the frame buffer (measured), and the menu
; runs inside an interrupt, where the console engine may be mid-write.  So
; RestAll only sets the kernel's _kConRestoreReq, and _Con_DrainRestore
; repaints the console at the next safe point.
;
; The ioctl ops read the syscall layer's _Sys_Ioctl* statics, so this module is
; build-locked to its kernel through kernel_exports.s.
;==============================================================================

