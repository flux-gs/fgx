;==============================================================================
; isofs.s - the assembly root of isofs.mod: the ISO 9660 filesystem type,
; compiled from C, in a loadable FGXM module.
;
; A MOUNTABLE TYPE, NOT A ROOT.  mount_isofs(8) loads it with modload when
; mount(2) answers ENODEV, and mount(2) reaches it through vfssw[MOUNT_ISOFS],
; which isofs_init fills.  Nothing at boot needs it.
;
; ITS OWN BANK, ORDINAL 7 ($0C0000), for the reason prodos.mod has one: the
; shared bank has no room for a filesystem (tools/gen_modplace.py OWN_BANK).
;
; THE SEAM IS prodos.mod's: the C needs vfs.mod's buffer cache, vnode pool and
; namei, reached through vfs_import.s, generated by tools/gen_mod_imports.py.
; isofs.mod exports nothing, so its vtable directory is empty.
;
; MODBANK-C-OK: every global, literal and runtime scratch this module's C
; touches is read DBR-relatively, which is correct here for ufs.mod's reason --
; the C is only ever entered through MOD_KC_ENTER, or through a vfs_import.s
; shim or a vnode-op dispatch that establishes the same thing.  The waiver is
; at MODULE level because both the accesses and the declarations live in fcc
; OUTPUT.
;==============================================================================

                MX      %11
                PUT     modplace.s
                ORG     MODP_ORG

                PUT     ../../../include/config.s       ; CFG_* build gates
                PUT     ../../../include/macros.s       ; FGX2_MODE/EXPORT/RELOC
                PUT     ../../../include/kernel.s       ; FGX_DP_KERNELC
                PUT     ../../../include/dpmap.s        ; DUM $00: the block
                PUT     ../../../include/modules.s      ; SYS_KCALL, KSVC_*,
                                                        ;   VT_VFSCORE, VFSCORE_*
                PUT     ../../../include/kernelc.s      ; MOD_KC_ENTER/LEAVE
                PUT     ../../../include/fs.s           ; DEV_* record layout
                PUT     ../../../include/vfs_equ.s      ; GENERATED from the C

;------------------------------------------------------------------------------
; FGXM header (40 bytes).  See include/fgxm.s.
;------------------------------------------------------------------------------
is_bss          EQU     0
is_hdr          ASC     'FGXM'                          ; +0  magic
                DFB     <MODP_ORG                       ; +4  load lo
                DFB     >MODP_ORG                       ; +5  load mid
                DFB     ^MODP_ORG                       ; +6  load hi
                DFB     $02                             ; +7  header format v2
                DA      mod_init-$0C0000                ; +8  entry, bank-rel
                DA      is_end-is_text                  ; +10 text bytes
                DA      is_bss                          ; +12 bss bytes
                DA      is_vtdir-is_text                ; +14 vtdir offset
is_name         ASC     'isofs'                         ; +16 module name
                DS      16-*+is_name                    ;     NUL-pad to 16
                DA      $0000                           ; +32 module version
                DA      $0000
                DS      4                               ; +36 reserved

is_text         EQU     *

; mount(2) finds this module through vfssw[], which isofs_init fills; it
; exports no table of its own.
is_vtdir        ASC     'VTDR'
                DA      VT_END

; The C-to-kernel seam, then the module-to-module seam.  BEFORE mod_init, for
; ufs.s's reason: they define macros Merlin needs defined before use.
                PUT     ../common/kc_sys.s
                PUT     vfs_import.s

;------------------------------------------------------------------------------
; mod_init - stamp the &function cells, resolve vfs.mod, then run isofs_init.
; prodos.s's mod_init, line for line: a module whose import table is empty must
; run no C, because the first call through it goes to bank 0.
;------------------------------------------------------------------------------
mod_init        MX      %00
                PHP
                REP     #$30
                MX      %00
                PHB
                PHK
                PLB                     ; DBR = ours, for everything below

                JSR     _Mod_StampFnPtrs
                JSR     _Is_ResolveVfs
                BCC     @mi_novfs       ; no vfs.mod: run NO C at all

                MOD_KC_ENTER
                PHK
                PEA     @mi_initret-1
                JMP     isofs_init
                ; THE LABEL GETS ITS OWN LINE, for ufs.s's reason:
                ; tools/check_kc_dbr.py matches MOD_KC_LEAVE only at the start
                ; of a line.
@mi_initret     ANOP
                MOD_KC_LEAVE

@mi_out         PLB
                PLP
                SEC
                RTL

@mi_novfs       LDA     #@mi_msgNoVfs
                LDX     #KSVC_LOGSTRNE
                JSL     SYS_KCALL
                LDX     #KSVC_LOGEOL
                JSL     SYS_KCALL
                BRA     @mi_out

@mi_msgNoVfs    ASC     'isofs: vfs.mod not loaded',$00

;------------------------------------------------------------------------------
; _Is_ResolveVfs - copy vfs.mod's VT_VFSCORE table into _isVImp.  prodos.s's
; _Pd_ResolveVfs exactly.  C=1 on success.
;------------------------------------------------------------------------------
_Is_ResolveVfs  MX      %00
                LDA     #VT_VFSCORE
                LDX     #KSVC_FINDVTABLE
                JSL     SYS_KCALL
                BCS     @rv_have
                RTS                             ; C=0 already
@rv_have        TAY                             ; park the table address
                TXA
                AND     #$00FF
                STA     |_isVfsBank     ; MODBANK-OK: DBR = ours (mod_init set it)
                TYX                             ; X = table address
                REP     #$30
                MX      %00
                LDY     #0
@rv_L           SEP     #$20
                MX      %10
                LDA     |_isVfsBank     ; MODBANK-OK: DBR is ours here
                PHA
                PLB                             ; DBR = vfs.mod
                REP     #$20
                MX      %00
                LDA     |$0000,X                ; the entry, from vfs.mod
                PHK
                PLB                             ; DBR ours again -- A survives
                STA     |_isVImp,Y      ; MODBANK-OK: DBR = ours
                INX
                INX
                INY
                INY
                CPY     #VFSCORE_COUNT*2
                BNE     @rv_L
                SEC
                RTS

;------------------------------------------------------------------------------
; The fcc runtime and the C.
;------------------------------------------------------------------------------
                PUT     ../../kernel/libc/alloc_state.s
                PUT     ../../kernel/far/fcc_dp.s       ; fcc register file (EQU)
                PUT     ../../kernel/far/fcc_rt.s       ; pure-computation half
                PUT     ../../kernel/far/fcc_ktrap.s    ; stack/soft-frame traps
                PUT     ../../../toolchain/lib/fcc_runtime_data.s
                ; The calendar arithmetic ufs.mod's clock uses, for the
                ; recording dates: the same compiled file, which holds no
                ; state.
                PUT     ../../kernel/vfs/kern_epoch.s
                PUT     ../../kernel/vfs/kern_epoch.data.s
                PUT     ../../kernel/vfs/isofs_node.s
                PUT     ../../kernel/vfs/isofs_node.data.s
                PUT     ../../kernel/vfs/isofs_vfsops.s
                PUT     ../../kernel/vfs/isofs_vfsops.data.s
                PUT     ../../kernel/vfs/isofs_vnops.s
                PUT     ../../kernel/vfs/isofs_vnops.data.s
                PUT     ../../kernel/vfs/isofs_rrip.s
                PUT     ../../kernel/vfs/isofs_rrip.data.s
                ; LAST: the only output whose size depends on a scan of this
                ; module's own listing, so nothing after it can move a cell.
                PUT     fnptr_patchsites.s

is_end          EQU     *
                ERR     is_hdr-MODP_ORG
                ERR     is_end-MODP_ORG+is_bss/MODP_LIMIT
; ...and the ordinal: the header's entry field is bank-relative against a
; LITERAL $0C0000.
                ERR     MODP_ORG/$10000-$0C
