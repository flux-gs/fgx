; Placement guards (tools/gen_modplace.py writes MODP_* into modplace.s).
; Merlin's ERR fires on a NON-ZERO expression.  The first pins the
; header at the offset the loader will place it at -- if these
; disagree, every absolute reference in this module is wrong by the
; difference.  The second is the bank-end ceiling, in the same
; integer-division idiom the kernel uses for its own (main.s's
; `ERR *-1/FGX_DATA`).  Merlin has no parentheses and no operator
; precedence -- strictly left to right -- so the subtraction lands
; before the divide without them.
                ERR     bpf_hdr-MODP_ORG
                ERR     bpf_end-MODP_ORG+bpf_bss/MODP_LIMIT

