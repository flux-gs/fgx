;==============================================================================
; bpf.s - FGXM module: /dev/bpf0 IRQ-driven MACRAW packet capture.
;
; Lifted out of the kernel (P0.4 kernel-bank reclaim).  Was src/kernel/bpf.s
; (chardev wrapper) + the W5100 MACRAW capture driver in src/kernel/uthernet.s
; (_Net_CaptureStart / _Net_CaptureStop / _Net_DrainFrame).  Both now live
; here, loaded on demand from /etc/modload.conf so /dev/bpf0 + netdump cost the
; kernel binary nothing.
;
; Split of concerns with the kernel:
;   - The capture BLOCK (heap, M_KERN) is allocated at boot by the kernel's
;     _Bpf_AllocBlk and reached through the kernel DP soft-globals _bpfBase /
;     _bpfSnapPtr / _bpfPhysTmp (declared in include/dpmap.s).
;
;     THAT SPLIT IS A WORKAROUND WHOSE REASON HAS EXPIRED.  It reads here as a
;     design choice; it was not.  Until 2026-08-11 there was no Kmalloc in the
;     module gateway at all -- the slots once named SYS_KMALLOC/SYS_KFREE were
;     never wired and had been reused, so a module-side Kmalloc halted the
;     kernel, and the allocation had to be done kernel-side.  SYS_KCALL's
;     KSVC_KMALLOC/KSVC_KFREE (include/modules.s) close that hole, so
;     _Bpf_AllocBlk can move in here and give the core bank its bytes back.
;     What still has to move with it is the DP soft-globals: the kernel reads
;     _bpfBase too, so both ends change together.
;   - Socket-0 / W5100 bus state (_u2Imr / _u2Locked) stays a kernel static,
;     imported via the auto-generated kernel_exports.s manifest.
;
; Each op is MX %00 in/out, reached by JSL from _Chardev_Dispatch (so they
; RTL), with DBR=kernel-bank ($02 = assembly ORG) and the KERNEL direct page
; active (D=$BF00) -- exactly the context the in-kernel version ran in, so the
; DP-indirect-long accesses ([_bpfBase],Y, [_libcTmp2],Y, [_fcbPtr],Y) and the
; DBR-relative reads of the _Sys_Rd* statics are byte-identical to the old
; kernel code.  The op code
; runs from THIS module's bank (PB = our bank, set by the JSL), so its
; JSRs into the capture driver / W5 primitives are same-bank.
;
; Record layout (produced by _Net_DrainFrame in BPF_SnapBuf):
;   [0..1] caplen  (LE)  - frame bytes actually captured (<= BPF_SNAPLEN)
;   [2..3] datalen (LE)  - true on-the-wire frame length
;   [4..]  frame         - caplen bytes of the Ethernet frame
; Saturation sentinel: caplen=0 + datalen=BPF_Sat -> netdump "[saturated N]".
;
; Bank-agnostic, OFFSET-SPECIFIC.  The BANK is still whatever the loader
; puts this module in -- every absolute reference is DBR-relative once
; mod_init runs PHK/PLB.  The OFFSET WITHIN that bank is NOT free: modules
; now SHARE one bank, so this image is ORG'd at MODP_ORG (generated by
; tools/gen_modplace.py from the measured sizes of the modules placed before
; it) and MUST be loaded there.  The FGXM header's load_addr carries that
; offset to Mod_Load.
; The loader patches the JT-call PC bank + (via mod_init) the ops-table
; bank bytes.
;==============================================================================

                MX      %11
                ; WHERE THIS MODULE LIVES.  Modules stack into ONE shared
                ; bank -- a 64 KB bank per 2 KB driver was costing four
                ; banks for 17 KB of code.  MODP_ORG is this module's
                ; offset in that bank, derived at build time from the
                ; MEASURED sizes of the modules placed before it; the
                ; loader reads it back out of the FGXM header below.
                ; Module code is ORG-dependent, so this must be exact.
