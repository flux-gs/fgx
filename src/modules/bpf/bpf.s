;------------------------------------------------------------------------------
; bpf_open - open("/dev/bpf0"): start MACRAW capture, mark the fd record-mode.
;   In:  _fcbPtr -> caller's FCB (live; set by Fs_Open before _Chardev_Open).
;   Out: C=1 ok; C=0 + A=EBUSY if a capture is already active (single opener).
;------------------------------------------------------------------------------
bpf_open        MX      %00
                ; --- single-opener guard: refuse if already capturing ---
                SEP     #$20
                MX      %10
                LDY     #BPF_CapState
                LDA     [_bpfBase],Y            ; 0=idle, 1=capturing
                BEQ     @bo_free
                REP     #$20
                MX      %00
                LDA     #EBUSY
                CLC
                RTL
@bo_free        MX      %10
                REP     #$20
                MX      %00
                JSR     _Net_CaptureStart       ; socket 0 -> MACRAW, arm RECV IRQ;
                                                ; sets _bpfCapState=1
                ; RECORD MODE IS DECLARED AT REGISTRATION, not here -- see
                ; mod_init's CDF_RECORD.  This used to OR FCB_FL_RECORD into
                ; [_fcbPtr], an FCB this routine's signature never mentions and
                ; the wrong one on the /dev route (apple/fgx#198).
                SEC
                RTL

;------------------------------------------------------------------------------
; bpf_close - close("/dev/bpf0"): stop capture (IMR=0, socket 0 CLOSE).
;------------------------------------------------------------------------------
bpf_close       MX      %00
                JSR     _Net_CaptureStop        ; sets _bpfCapState=0
                SEC
                RTL

;------------------------------------------------------------------------------
; bpf_read - fill the caller buffer with ONE packet record.
;   Reads _Sys_RdBufOff (offset), _Sys_CallerBank (bank), _Sys_RdMax (cap).
;   Out: C=1 + A=bytes copied (one whole record), or C=0 + A=EAGAIN if no
;        frame is waiting.  Copies via [_libcTmp2],Y honoring the caller bank.
;------------------------------------------------------------------------------
bpf_read        MX      %00
                ; zero-length request: copy nothing, drain nothing.
                LDA     _Sys_RdMax
                BNE     @br_room
                LDA     #$0000
                SEC
                RTL
@br_room        MX      %00
                ; Pending saturation report?  If BPF_Sat advanced since we last
                ; surfaced it, return a SENTINEL record (caplen=0, datalen=satcount)
                ; BEFORE the next frame; netdump shows it as "[saturated N]".
                ; caplen=0 never occurs for a real frame, so it's unambiguous.
                LDY     #BPF_Sat
                LDA     [_bpfBase],Y
                LDY     #BPF_SatRept
                CMP     [_bpfBase],Y
                BEQ     @br_drain
                STA     [_bpfBase],Y            ; A = BPF_Sat -> mark reported (Y=BPF_SatRept)
                LDY     #$0000                  ; record [0..1] = caplen = 0 (sentinel)
                LDA     #$0000
                STA     [_bpfSnapPtr],Y
                LDY     #BPF_Sat
                LDA     [_bpfBase],Y
                LDY     #$0002                  ; record [2..3] = saturation count
                STA     [_bpfSnapPtr],Y
                LDA     #$0004                  ; record length = 4 (header only)
                BRA     @br_have
@br_drain       JSR     _Net_DrainFrame         ; C=1 + A=4+caplen, or C=0 (none)
                BCS     @br_have
                LDA     #EAGAIN
                CLC
                RTL
@br_have        MX      %00
                ; A = record length (4 + caplen); cap to the caller buffer size.
                CMP     _Sys_RdMax
                BCC     @br_lenOK
                LDA     _Sys_RdMax
@br_lenOK       MX      %00
                TAX                             ; X = bytes to copy (count-down)
                ; dest long-ptr [_libcTmp2] = _Sys_CallerBank : _Sys_RdBufOff
                LDA     _Sys_RdBufOff
                STA     _libcTmp2
                SEP     #$20
                MX      %10
                LDA     _Sys_CallerBank
                STA     _libcTmp2+2
                REP     #$20
                MX      %00
                LDY     #$0000                  ; Y = src/dst index (count-up)
@br_cp          MX      %00
                CPX     #$0000
                BEQ     @br_cpDone
                SEP     #$20
                MX      %10
                LDA     [_bpfSnapPtr],Y         ; record byte (heap capture block)
                STA     [_libcTmp2],Y           ; -> caller bank:off + Y
                REP     #$20
                MX      %00
                INY
                DEX
                BRA     @br_cp
@br_cpDone      MX      %00
                TYA                             ; A = bytes copied (= capped len)
                SEC
                RTL

;------------------------------------------------------------------------------
; bpf_write - capture is read-only.
;------------------------------------------------------------------------------
bpf_write       MX      %00
                LDA     #ENOTSUP
                CLC
                RTL

;------------------------------------------------------------------------------
; bpf_ioctl - no ioctls (saturation surfaced in-band via the caplen=0 record).
;------------------------------------------------------------------------------
bpf_ioctl       MX      %00
                LDA     #ENOTTY
                CLC
                RTL

;------------------------------------------------------------------------------
; bpf_poll - POLLIN if a frame is waiting in the W5100 RX (Sn_RX_RSR > 0).
;   Peeks RSR under U2_LOCK without draining.  NB U2_UNLOCK clobbers A, so
;   branch on the RSR value BEFORE unlocking.
;------------------------------------------------------------------------------
bpf_poll        MX      %00
                U2_LOCK
                LDA     #W5_S0_RXRSR
                JSR     _W5_Rd16                ; A = RSR; Z set if zero
                BEQ     @bp_noin
                U2_UNLOCK
                LDA     #POLLIN
                SEC
                RTL
@bp_noin        MX      %00
                U2_UNLOCK
                LDA     #$0000
                SEC
                RTL

