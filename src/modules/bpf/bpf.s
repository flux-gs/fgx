;------------------------------------------------------------------------------
; _W5_SetAR16 - set the W5100 indirect AR to the 16-bit address in A.  A kept.
;------------------------------------------------------------------------------
_W5_SetAR16     MX      %00
                PHP
                SEP     #$20
                MX      %10
                XBA                     ; A.lo = addr hi
                STAL    U2_ARH
                XBA                     ; A.lo = addr lo
                STAL    U2_ARL
                PLP
                RTS

;------------------------------------------------------------------------------
; _W5_Rd16 - A = W5100 addr -> A = 16-bit big-endian value at addr.  Z set on
; the result (BNE = nonzero).  MX %00 in/out.
;------------------------------------------------------------------------------
_W5_Rd16        MX      %00
                JSR     _W5_SetAR16
                SEP     #$20
                MX      %10
                LDAL    U2_DAT          ; hi byte (AR auto-inc)
                XBA                     ; B = hi
                LDAL    U2_DAT          ; lo byte (A = lo, B = hi)
                REP     #$20
                MX      %00
                CMP     #$0000          ; Z = (value==0); A preserved
                RTS

;------------------------------------------------------------------------------
; _Net_CaptureStart - socket 0 -> MACRAW+MAC-filter, OPEN, arm RECV IRQ.
;------------------------------------------------------------------------------
_Net_CaptureStart MX    %00
                PHP
                REP     #$30
                MX      %00
                SEP     #$20            ; detected slot -> card (idempotent)
                MX      %10
                LDAL    SLTROMSEL
                ORA     |_u2SltBit
                STAL    SLTROMSEL
                REP     #$20
                MX      %00
                LDA     #W5_S0_MR       ; Sn_MR = $44 (MACRAW + MAC filter)
                JSR     _W5_SetAR16
                SEP     #$20
                MX      %10
                LDA     #W5_MR_MACRAW
                STAL    U2_DAT
                REP     #$20
                MX      %00
                LDA     #W5_S0_CR       ; Sn_CR = OPEN
                JSR     _W5_SetAR16
                SEP     #$20
                MX      %10
                LDA     #$01
                STAL    U2_DAT
                REP     #$20
                MX      %00
                LDX     #$0000          ; bounded wait Sn_SR == MACRAW
@cs_w           LDA     #W5_S0_SR
                JSR     _W5_SetAR16
                SEP     #$20
                MX      %10
                LDAL    U2_DAT
                CMP     #W5_SR_MACRAW
                BNE     @cs_next
                REP     #$20
                MX      %00
                BRA     @cs_arm
@cs_next        REP     #$20
                MX      %00
                DEX
                BNE     @cs_w
@cs_arm         LDA     #$0016          ; IMR = $01 (socket-0 RECV), shadow $01
                JSR     _W5_SetAR16
                SEP     #$20
                MX      %10
                LDA     #$01
                STA    _u2Imr
                STAL    U2_DAT
                LDA     #$00            ; reset saturation count + report watermark
                LDY     #BPF_Sat
                STA     [_bpfBase],Y
                INY
                STA     [_bpfBase],Y
                LDY     #BPF_SatRept
                STA     [_bpfBase],Y
                INY
                STA     [_bpfBase],Y
                LDA     #$01            ; mark capturing
                LDY     #BPF_CapState
                STA     [_bpfBase],Y
                REP     #$20
                MX      %00
                PLP
                RTS

;------------------------------------------------------------------------------
; _Net_CaptureStop - IMR=0, socket 0 CLOSE, capture idle.
;------------------------------------------------------------------------------
_Net_CaptureStop MX    %00
                PHP
                REP     #$30
                MX      %00
                LDA     #$0016          ; IMR = 0
                JSR     _W5_SetAR16
                SEP     #$20
                MX      %10
                LDA     #$00
                STA    _u2Imr
                STAL    U2_DAT
                REP     #$20
                MX      %00
                LDA     #W5_S0_CR       ; Sn_CR = CLOSE
                JSR     _W5_SetAR16
                SEP     #$20
                MX      %10
                LDA     #$10
                STAL    U2_DAT
                LDA     #$00            ; capture idle
                LDY     #BPF_CapState
                STA     [_bpfBase],Y
                REP     #$20
                MX      %00
                PLP
                RTS

;------------------------------------------------------------------------------
; _Net_DrainFrame - drain one MACRAW frame into the capture block (BPF_SnapBuf).
;   Out: C=1 + A = record length (4 + caplen) if a frame was captured;
;        C=0 if no frame available.  MX %00 in/out.  U2_LOCK-wrapped so the
;        heartbeat-triggered generic-walk ISR can't move the AR mid-drain.
;   Record: [0..1]=caplen (LE), [2..3]=datalen (LE), [4..]=frame (caplen bytes).
;------------------------------------------------------------------------------
_Net_DrainFrame MX      %00
                PHP
                REP     #$30
                MX      %00
                U2_LOCK
                LDA     #W5_S0_RXRSR    ; received size (16-bit BE)
                JSR     _W5_Rd16
                BNE     @df_have
                U2_UNLOCK
                PLP
                CLC
                RTS
@df_have        ; A = RSR.  Honest saturation signal: if the 2 KB RX ring is within
                ; a min frame ($07C0) of full, the W5100 is dropping (no HW drop
                ; register) -> bump BPF_Sat (a measured full-buffer count, NOT a
                ; per-frame drop count).  A=RSR is dead after; the drain reloads it.
                CMP     #$07C0
                BCC     @df_notSat
                LDY     #BPF_Sat
                LDA     [_bpfBase],Y
                INC
                STA     [_bpfBase],Y
@df_notSat      LDA     #W5_S0_RXRD     ; RX read pointer -> BPF_Rxrd
                JSR     _W5_Rd16
                LDY     #BPF_Rxrd
                STA     [_bpfBase],Y
                AND     #W5_RXMASK      ; phys = RXRD & ring-mask (A still = RXRD)
                CMP     #$07FF
                BEQ     @df_pfxWrap
                ORA     #W5_RXBASE      ; normal: 2-byte prefix at RXBASE+phys
                JSR     _W5_Rd16        ; A = framelen (AR now at payload start)
                BRA     @df_pfxDone
@df_pfxWrap     LDA     #$67FF          ; straddle: byte0 @ $67FF, byte1 @ $6000
                JSR     _W5_SetAR16
                SEP     #$20
                MX      %10
                LDAL    U2_DAT
                XBA                     ; B = hi
                REP     #$20
                MX      %00
                LDA     #W5_RXBASE
                JSR     _W5_SetAR16
                SEP     #$20
                MX      %10
                LDAL    U2_DAT          ; A=lo, B=hi (AR now $6001)
                REP     #$20
                MX      %00             ; A = framelen
@df_pfxDone     LDY     #BPF_FrameLen   ; A = framelen
                STA     [_bpfBase],Y
                SEC                     ; datalen = framelen - 2
                SBC     #$0002
                LDY     #$0002          ; record [2..3] = datalen (_bpfSnapPtr-relative)
                STA     [_bpfSnapPtr],Y
                CMP     #BPF_SNAPLEN    ; caplen = min(datalen, snaplen)
                BCC     @df_cl
                LDA     #BPF_SNAPLEN
@df_cl          LDY     #BPF_CapLen
                STA     [_bpfBase],Y
                LDY     #$0000          ; record [0..1] = caplen
                STA     [_bpfSnapPtr],Y
                LDY     #BPF_Rxrd       ; cur_phys = (RXRD + 2) & ring-mask
                LDA     [_bpfBase],Y
                CLC
                ADC     #$0002
                AND     #W5_RXMASK
                STA     _bpfPhysTmp
                LDY     #BPF_CapLen     ; X = caplen (count down)
                LDA     [_bpfBase],Y
                TAX
                LDY     #$0004          ; Y = record offset of the frame (BPF_SnapBuf+4)
@df_cp          CPX     #$0000
                BEQ     @df_cpDone
                SEP     #$20
                MX      %10
                LDAL    U2_DAT
                STA     [_bpfSnapPtr],Y ; -> BPF_SnapBuf + Y
                REP     #$20
                MX      %00
                INY
                DEX
                LDA     _bpfPhysTmp     ; advance ring pos; wrap at $0800
                CLC
                ADC     #$0001
                CMP     #$0800
                BCC     @df_noWrap
                LDA     #$0000
                STA     _bpfPhysTmp
                LDA     #W5_RXBASE      ; re-point AR to ring start
                JSR     _W5_SetAR16
                BRA     @df_cp
@df_noWrap      STA     _bpfPhysTmp
                BRA     @df_cp
@df_cpDone      LDY     #BPF_Rxrd       ; RX_RD += framelen; write back (16-bit BE @ $0428)
                LDA     [_bpfBase],Y
                CLC
                LDY     #BPF_FrameLen
                ADC     [_bpfBase],Y
                PHA
                LDA     #W5_S0_RXRD
                JSR     _W5_SetAR16
                PLA
                SEP     #$20
                MX      %10
                XBA                     ; A.lo = rxrd hi
                STAL    U2_DAT
                XBA                     ; A.lo = rxrd lo
                STAL    U2_DAT
                REP     #$20
                MX      %00
                LDA     #W5_S0_CR       ; Sn_CR = RECV (commit)
                JSR     _W5_SetAR16
                SEP     #$20
                MX      %10
                LDA     #W5_CR_RECV
                STAL    U2_DAT
                REP     #$20
                MX      %00
                U2_UNLOCK
                LDY     #BPF_CapLen     ; return record length = 4 + caplen
                LDA     [_bpfBase],Y
                CLC
                ADC     #$0004
                PLP
                SEC
                RTS

