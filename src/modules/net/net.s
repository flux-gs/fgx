                LDY     #6
                LDA     [_libcTmp2],Y
                STA     _sockOptLen
                LDY     #8                      ; the VALUE, read while the arg
                LDA     [_libcTmp2],Y           ;   block pointer is still staged:
                PHA                             ;   its bank at +8, its offset at
                LDY     #4                      ;   +4 -- a local's address is in
                LDA     [_libcTmp2],Y           ;   the stack bank, not the
                STA     _libcTmp2               ;   block's
                PLA
                SEP     #$20
                MX      %10
                STA     _libcTmp2+2
                REP     #$20
                MX      %00
                LDY     #0
                LDA     [_libcTmp2],Y
                STA     _sockOptVal
                TXA
                JSL     SYS_NETKC_SOCKFDTODESC
                BCS     @so_haveDesc
                MX      %00
                CLC
                RTL                             ; A = EBADF
@so_haveDesc    STY     _sockTmpOff
                LDA     _sockOptLevel
                CMP     #SOL_SOCKET
                BNE     @so_noproto
                LDA     _sockOptLen             ; sizeof(int) is 2 here
                CMP     #2
                BCC     @so_einval
                ; --- upstream's switch, arm for arm ---
                LDA     _sockOptName
                CMP     #SO_DEBUG
                BEQ     @so_known
                CMP     #SO_REUSEADDR
                BEQ     @so_known
                CMP     #SO_KEEPALIVE
                BEQ     @so_known
                CMP     #SO_DONTROUTE
                BEQ     @so_known
                CMP     #SO_BROADCAST
                BEQ     @so_known
                CMP     #SO_USELOOPBACK
                BEQ     @so_known
                CMP     #SO_OOBINLINE
                BNE     @so_noproto
                ; SO_BROADCAST and SO_REUSEADDR have consumers -- the sendto
                ; guard and the UDP bind (_Udp_PortShare) -- and are kept in
                ; SOCK_Flags at their own option values.  The other five are
                ; accepted and not stored; see the option block in
                ; include/socket.s for why a word of bits nothing reads is not
                ; an improvement here.
@so_known       LDA     _sockOptName
                CMP     #SO_BROADCAST
                BEQ     @so_store
                CMP     #SO_REUSEADDR
                BNE     @so_ok
@so_store       LDA     _sockTmpOff
                CLC
                ADC     #SOCK_Flags
                TAY
                SEP     #$20
                MX      %10
                LDA     _sockOptName            ; the bit is the option's value
                EOR     #$FF
                AND     [_sockTablePtr],Y       ; cleared...
                LDX     _sockOptVal
                BEQ     @so_storeBc
                ORA     _sockOptName            ; ...and set again if asked
@so_storeBc     STA     [_sockTablePtr],Y
                REP     #$20
                MX      %00
@so_ok          LDA     #0
                SEC
                RTL
@so_noproto     LDA     #ENOPROTOOPT
                CLC
                RTL
@so_einval      LDA     #EINVAL
                CLC
                RTL

