; _sockTmpHw (via _Sock_FdToDesc) then dispatches here.  Sends a FIN (CR_DISCON)
; on a TCP socket, leaving it in FIN_WAIT so recv() still drains; UDP/ICMP/no-hw
; are a no-op success.  Does NOT free the socket (close() does).  -> RTL.
;------------------------------------------------------------------------------
net_op_shutdown MX      %00
                JSR     _Net_Xport_Shutdown
                RTL

;------------------------------------------------------------------------------
; net_op_sockteardown - SYS close of a socket fd.  Fs_Close (FCB_FL_SOCKET)
; dispatches here with _fcbPtr = the socket FCB.  Lifted from socket.s
; _Sock_Teardown; _Net_Xport_Close + _W5_SockFree are now same-bank.  -> RTL.
;------------------------------------------------------------------------------
net_op_sockteardown MX  %00
                PHP
                REP     #$30
                MX      %00
                LDY     #FCB_SockIdx
                SEP     #$20
                MX      %10
                LDA     [_fcbPtr],Y             ; descriptor offset
                REP     #$20
                MX      %00
                AND     #$00FF
                TAY
                STY     _sockTmpOff
                INY                             ; -> SOCK_HwIdx
                SEP     #$20
                MX      %10
                LDA     [_sockTablePtr],Y       ; hw idx
                REP     #$20
                MX      %00
                AND     #$00FF
                STA     _sockTmpHw
                ; A SENTINEL OWNS NO HARDWARE.  This tested only
                ; SOCK_HW_NONE ($FF), so a LOOPBACK descriptor -- SOCK_HW_LOOP,
                ; $FE, written over SOCK_HwIdx by _Loop_BindTry and
                ; _Loop_WireConnector -- fell through to both calls below.
                ; _W5_SockFree then indexed 254 bytes past its 4-byte mask table
                ; and corrupted the allocator bitmap; _Net_Xport_Close was
                ; poking W5100 registers for a socket that does not exist.  A
                ; loopback socket is serviced by the pipe rings and torn down by
                ; _Loop_CloseTry, so neither call belongs on this path.
                ;
                ; Range test rather than two compares: every sentinel is
                ; >= W5_NSOCK by construction, so a third one added later
                ; cannot reintroduce this.
                ;
                ; Found while investigating apple/fgx#93 and NOT a fix for
                ; it -- that failure is unchanged with this in place, so
                ; the bitmap corruption it shows comes from elsewhere.
                CMP     #W5_NSOCK               ; detached listener / loopback /
                BCS     @st_sentinel            ;   AF_UNIX -> no hardware to free
                JSR     _Sock_HwShared          ; a UDP port another descriptor
                BCS     @st_freeDesc            ;   still holds stays open for it
                JSR     _Net_Xport_Close
                LDA     _sockTmpHw
                JSR     _W5_SockFree
                BRA     @st_freeDesc
@st_sentinel    ; AN AF_UNIX DESCRIPTOR STILL OWNS A RING.  Loopback's is freed by
                ; _Loop_CloseTry, which claims only SOCK_HW_LOOP; a bound AF_UNIX
                ; socket carries SOCK_HW_NONE, so nothing had released its receive
                ; ring and the slot leaked for the life of the boot.  NPIPE is 8 and
                ; shared with shell pipes.
                LDY     _sockTmpOff
                JSR     _Unp_CloseTry
@st_freeDesc    LDY     _sockTmpOff
                SEP     #$20
                MX      %10
                LDA     #$00
                STA     [_sockTablePtr],Y       ; SOCK_InUse = 0
                REP     #$20
                MX      %00
                PLP
                RTL

