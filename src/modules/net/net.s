;------------------------------------------------------------------------------
; _So_ArgUio - the send/recv family's common head: resolve the fd (X at the
; trap) into _sockTmpOff and build the task's one-entry uio over the block's
; buffer {+0 offset, +2 length, +6 bank} into _sockUio.
;
; This is sendit/recvit building auio from the msghdr's one iovec
; (uipc_syscalls.c).  The uio is in the U-AREA, which is per task, because a
; TCP wait sleeps between here and the copy.
;
; In:  A = UIO_READ or UIO_WRITE.  MX %00.
; Out: C=1 and _libcTmp2 = the arg block (caller's bank), for the flags and the
;      rest; or C=0 + A = errno (EBADF).
;------------------------------------------------------------------------------
_So_ArgUio      MX      %00
                PHA                             ; rw
                LDA     _Sys_SavedX
                AND     #$00FF
                JSL     SYS_NETKC_SOCKFDTODESC
                BCS     @soau_have
                PLY                             ; drop rw; A = errno
                CLC
                RTS
@soau_have        STY     _sockTmpOff
                JSR     _So_LoadBlk             ; _libcTmp2 = the block
                LDY     #0
                LDA     [_libcTmp2],Y
                STA     _pipeBufOff
                LDY     #2
                LDA     [_libcTmp2],Y
                STA     _pipeReqLen
                LDY     #SOCKARG_BANK
                LDA     [_libcTmp2],Y
                STA     _pipeBufBank
                LDA     _u                      ; the iovec and uio: u.u_ttyiov,
                CLC                             ;   u.u_ttyuio
                ADC     #U_TtyIov
                STA     _kCopyPtr
                LDA     _u
                CLC
                ADC     #U_TtyUio
                STA     _libcTmp2
                STA     _sockUio
                SEP     #$20
                MX      %10
                LDA     _u+2
                STA     _kCopyPtr+2
                STA     _libcTmp2+2
                REP     #$30
                MX      %00
                AND     #$00FF
                STA     _sockUioBank
                PLA                             ; rw
                JSR     _Uio_Fill
                JSR     _So_LoadBlk             ; hand back the block
                SEC
                RTS

_So_LoadBlk     MX      %00
                LDA     _Sys_SavedA
                STA     _libcTmp2
                SEP     #$20
                MX      %10
                LDA     _Sys_CallerBank
                STA     _libcTmp2+2
                REP     #$30
                MX      %00
                RTS

;------------------------------------------------------------------------------
; _So_Bounce - make sure the W5100 bounce buffer exists.
;
; 2.11BSD's sosend uiomoves the caller's bytes into an mbuf and the interface
; driver copies the mbuf to the device; soreceive runs the reverse.  The W5100
; is read and written through ONE auto-incrementing data port, which uiomove
; cannot target, so the same two steps are needed here: the bounce is the mbuf.
; One ring's worth, allocated on first use and kept: the fill or drain and the
; chip copy happen with no sleep between them, so every socket shares it.
;
; Out: C=1 (A = _sockLen), or C=0 + A = ENOBUFS.  MX %00.
;------------------------------------------------------------------------------
_So_Bounce      MX      %00
                LDA     _soBounce+2
                AND     #$00FF
                BNE     @sobc_have
                LDA     #SO_BOUNCE_SZ
                LDX     #M_KERN
                JSR     _NlKC_Kmalloc
                BCC     @sobc_none
                LDA     _kmallocResult
                STA     _soBounce
                LDA     _kmallocResult+2
                AND     #$00FF
                STA     _soBounce+2
@sobc_have        LDA     _sockLen
                SEC
                RTS
@sobc_none        LDA     #ENOBUFS
                CLC
                RTS

;------------------------------------------------------------------------------
