_So_UioBounce   MX      %00
                LDA     _soBounce
                STA     _kCopyPtr
                SEP     #$20
                MX      %10
                LDA     _soBounce+2
                STA     _kCopyPtr+2
                REP     #$30
                MX      %00
                LDA     _sockUio
                STA     _pipeUio
                LDA     _sockUioBank
                STA     _pipeUioBank
                RTS

