                PHP
                PHA
                LDA     _loopHandled
                BEQ     @nol_listen_hw
                PLA
                PLP
                RTL                     ; loopback serviced it
@nol_listen_hw     PLA
                PLP
                LDA     _Sys_SavedA
                AND     #$00FF
                JSL     SYS_NETKC_SOCKFDTODESC
                BCS     @sl_ok
                MX      %00
                CLC
                RTL
@sl_ok          STY     _sockTmpOff
