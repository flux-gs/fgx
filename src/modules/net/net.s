; point _libcTmp2 at it, for _W5_TxStream.  Called by each send core AFTER any
; wait and length cap, immediately before the stream.  MX %00.
; _So_RxDrain - uiomove the _sockCapLen bytes _W5_RxCopy left in the bounce into
; the caller's uio.  Called right after _W5_RxCopy.  MX %00.
