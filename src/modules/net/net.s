                LDA     _Sys_SavedA
                LDX     _Sys_SavedX
                STA     _libcTmp2
                SEP     #$20
                MX      %10
                LDA     _Sys_CallerBank
                STA     _libcTmp2+2
                REP     #$20
                MX      %00
                LDY     #0
                LDA     [_libcTmp2],Y
                STA     _sockOptLevel
                LDY     #2
                LDA     [_libcTmp2],Y
