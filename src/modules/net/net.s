;==============================================================================
; net_op_ifioctl - ioctl(2) SIOCGIF* on a socket: 2.11BSD net/if.c's ifioctl
; and ifconf, and netinet/in.c's in_control for the address getters.  Reached
; from the core's _IoOp_Socket for the 'i' group, by JSL from _Net_Dispatch ->
; RTL.  Args are ioctl's staged cells: _Sys_IoctlCmd, and the ifreq/ifconf
; far pointer in _Sys_IoctlArgLo/_Sys_IoctlArgBank.  Returns A=0 + C=1, or
; A=errno + C=0.  MX %00.
;
; THE INTERFACES ARE THE ifnet TABLE'S CARDS AND lo0.  2.11BSD's ifconf walks
; every ifnet, the loopback among them (net/if_loop.c names it "lo"), so lo0
; is listed after the cards with its fixed address -- 127.0.0.1/8, UP,
; LOOPBACK, RUNNING -- which is what lets ntpd bind a socket to it.
;
; FLAGS ARE BSD's, NOT THE RECORD's.  A card's IF_Flags (LINK_UP, IP_CONF,
; DHCP) is mapped: BROADCAST always (an Ethernet), RUNNING when the link is
; up, UP when it is also configured -- the state ifconfig's address set
; leaves a BSD interface in.  A card with no address is listed with a zero
; sockaddr, as upstream lists an ifnet with an empty address list, and its
; address getters answer EADDRNOTAVAIL (in_control's `ia == 0').
;
; ONE DIVERGENCE: upstream compares `int space' with an unsigned sizeof, so a
; negative ifc_len reads as huge and ifconf writes past the buffer; here a
; negative length is no room.
;==============================================================================
net_op_ifioctl  MX      %00
                LDA     _Sys_IoctlArgLo         ; the ifreq/ifconf far pointer
                STA     _libcTmp2
                SEP     #$20
                MX      %10
                LDA     _Sys_IoctlArgBank
                STA     _libcTmp2+2
                REP     #$20
                MX      %00
                LDA     _Sys_IoctlCmd
                CMP     #SIOCGIFCONF
                BEQ     @ifi_conf
                JMP     @ifi_byname
@ifi_conf       ; ---- ifconf: ifc_len, then the ifc_buf far pointer ----
                LDA     [_libcTmp2]             ; ifc_len
                STA     _ifcTmpW                ; space
                LDY     #2
                LDA     [_libcTmp2],Y
                STA     _kCopyPtr               ; ifc_buf offset
                LDY     #4
                SEP     #$20
                MX      %10
                LDA     [_libcTmp2],Y
                STA     _kCopyPtr+2             ; ifc_buf bank
                REP     #$20
                MX      %00
                STZ     _ifcRecOff              ; the table walk
@ifc_card       LDA     _ifcRecOff
                CMP     #IFNET_BLK_SIZE
                BCS     @ifc_lo
                TAY
                LDA     [_ifTablePtr],Y         ; name word; 0 = empty
                BEQ     @ifc_next
                JSR     _Ifr_Room
                BCC     @ifc_done
                LDX     _ifcRecOff
                JSR     _Ifr_NameRec
                LDX     _ifcRecOff
                JSR     _Ifr_RecFlags           ; A = IF_Flags
                AND     #IFF_IP_CONF
                BEQ     @ifc_noaddr
                LDX     _ifcRecOff
                LDA     #IF_Ip
                JSR     _Ifr_RecAddr
                JSR     _Ifr_Sin
                BRA     @ifc_adv
@ifc_noaddr     JSR     _Ifr_SinZero
@ifc_adv        JSR     _Ifr_Advance
@ifc_next       LDA     _ifcRecOff
                CLC
                ADC     #IF_REC_SIZE
                STA     _ifcRecOff
                BRA     @ifc_card
@ifc_lo         JSR     _Ifr_Room
                BCC     @ifc_done
                JSR     _Ifr_NameLo0
                JSR     _Ifr_Lo0Addr
                JSR     _Ifr_Sin
                JSR     _Ifr_Advance
@ifc_done       LDA     _ifcTmpW                ; ifc_len -= space
                BMI     @ifc_none               ; a negative length took none
                LDA     [_libcTmp2]
                SEC
                SBC     _ifcTmpW
@ifc_len        STA     [_libcTmp2]
                LDA     #0
                SEC
                RTL
@ifc_none       LDA     #0
                BRA     @ifc_len
                ; ---- by name: ifunit, then the getter ----
@ifi_byname     LDA     _libcTmp2               ; the ifreq is the destination
                STA     _kCopyPtr
                SEP     #$20
                MX      %10
                LDA     _libcTmp2+2
                STA     _kCopyPtr+2
                REP     #$20
                MX      %00
                JSR     _Ifr_Lookup             ; C=1: X = record, $FFFF = lo0
                BCS     @ifi_found
                LDA     #ENXIO
                CLC
                RTL
@ifi_found      STX     _ifcRecOff
                LDA     _Sys_IoctlCmd
                CMP     #SIOCGIFFLAGS
                BNE     @ifi_addr
                ; flags: lo0's are fixed, a card's are mapped
                LDA     #BSD_IFF_UP+BSD_IFF_LOOPBACK+BSD_IFF_RUNNING
                CPX     #$FFFF
                BEQ     @ifi_setfl
                JSR     _Ifr_RecFlags
                STA     _ifnIdx
                LDA     #BSD_IFF_BROADCAST
                STA     _ifnCount
                LDA     _ifnIdx
                AND     #IFF_LINK_UP
                BEQ     @ifi_flcard
                LDA     _ifnCount
                ORA     #BSD_IFF_RUNNING
                STA     _ifnCount
                LDA     _ifnIdx
                AND     #IFF_IP_CONF
                BEQ     @ifi_flcard
                LDA     _ifnCount
                ORA     #BSD_IFF_UP
                STA     _ifnCount
@ifi_flcard     LDA     _ifnCount
@ifi_setfl      LDY     #IFR_ADDR
                STA     [_kCopyPtr],Y           ; ifr_flags
                LDA     #0
                SEC
                RTL
@ifi_addr       ; the address getters: in_control's `ia == 0' first
                CPX     #$FFFF
                BEQ     @ifi_lo0
                JSR     _Ifr_RecFlags
                AND     #IFF_IP_CONF
                BNE     @ifi_card
                LDA     #EADDRNOTAVAIL
                CLC
                RTL
@ifi_card       LDA     _Sys_IoctlCmd
                LDX     #IF_Ip
                CMP     #SIOCGIFADDR
                BEQ     @ifi_cget
                LDX     #IF_Broadcast
                CMP     #SIOCGIFBRDADDR
                BEQ     @ifi_cget
                LDX     #IF_Netmask
                CMP     #SIOCGIFNETMASK
                BEQ     @ifi_cmask
                BRA     @ifi_nosup
@ifi_cget       TXA                             ; field offset
                LDX     _ifcRecOff
                JSR     _Ifr_RecAddr
                JSR     _Ifr_Sin
                LDA     #0
                SEC
                RTL
@ifi_cmask      TXA
                LDX     _ifcRecOff
                JSR     _Ifr_RecAddr
                BRA     @ifi_mask
@ifi_lo0        LDA     _Sys_IoctlCmd
                CMP     #SIOCGIFADDR
                BEQ     @ifi_lo0a
                CMP     #SIOCGIFBRDADDR
                BEQ     @ifi_einval             ; lo0 is not IFF_BROADCAST
                CMP     #SIOCGIFNETMASK
                BNE     @ifi_nosup
                LDA     #$00FF                  ; 255.0.0.0, network order
                STA     _ifnIdx
                STZ     _ifnCount
@ifi_mask       ; SIOCGIFNETMASK writes the family and the address only,
                ; as in_control does
                LDY     #IFR_ADDR
                LDA     #AF_INET
                STA     [_kCopyPtr],Y
                LDY     #IFR_ADDR+4
                LDA     _ifnIdx
                STA     [_kCopyPtr],Y
                INY
                INY
                LDA     _ifnCount
                STA     [_kCopyPtr],Y
                LDA     #0
                SEC
                RTL
@ifi_lo0a       JSR     _Ifr_Lo0Addr
                JSR     _Ifr_Sin
                LDA     #0
                SEC
                RTL
@ifi_einval     LDA     #EINVAL
                CLC
                RTL
@ifi_nosup      LDA     #ENOTSUP                ; BSD EOPNOTSUPP: the setters
                CLC
                RTL

;------------------------------------------------------------------------------
; The ifreq builders.  Destination = [_kCopyPtr]; an address travels in
; _ifnIdx (bytes 0-1) and _ifnCount (bytes 2-3), network order.  MX %00.
;------------------------------------------------------------------------------
; _Ifr_Room - C=1 when space exceeds one record (upstream's `space >
; sizeof (ifr)'; a negative space is none).
_Ifr_Room       LDA     _ifcTmpW
                BMI     @ir_no
                CMP     #IFREQ_SIZE+1
                RTS                             ; C = (space >= 33)
@ir_no          CLC
                RTS
; _Ifr_Advance - the next record: _kCopyPtr += 32, space -= 32.
_Ifr_Advance    LDA     _kCopyPtr
                CLC
                ADC     #IFREQ_SIZE
                STA     _kCopyPtr
                LDA     _ifcTmpW
                SEC
                SBC     #IFREQ_SIZE
                STA     _ifcTmpW
                RTS
; _Ifr_NameRec - ifr_name = record X's 8-byte NUL-padded name, then 8 NULs.
_Ifr_NameRec    LDY     #0
@inr_l          PHY
                TXA
                STA     _ifnName                ; (scratch: the record base)
                TYA
                CLC
                ADC     _ifnName
                TAY
                LDA     [_ifTablePtr],Y
                PLY
                STA     [_kCopyPtr],Y
                INY
                INY
                CPY     #8
                BCC     @inr_l
                BRA     _Ifr_NamePad
; _Ifr_NameLo0 - ifr_name = "lo0".
_Ifr_NameLo0    LDA     #$6F6C                  ; 'l','o'
                STA     [_kCopyPtr]
                LDY     #2
                LDA     #$0030                  ; '0', NUL
                STA     [_kCopyPtr],Y
                LDY     #4
                LDA     #0
                STA     [_kCopyPtr],Y
                LDY     #6
                STA     [_kCopyPtr],Y
                LDY     #8
_Ifr_NamePad    LDA     #0                      ; Y = 8: bytes 8..15
@inp_l          STA     [_kCopyPtr],Y
                INY
                INY
                CPY     #IFR_ADDR
                BCC     @inp_l
                RTS
; _Ifr_RecFlags - A = record X's IF_Flags byte.
_Ifr_RecFlags   TXA
                CLC
                ADC     #IF_Flags
                TAY
                LDA     [_ifTablePtr],Y
                AND     #$00FF
                RTS
; _Ifr_RecAddr - the 4 bytes at record X + field A -> _ifnIdx/_ifnCount.
_Ifr_RecAddr    STX     _ifnName
                CLC
                ADC     _ifnName
                TAY
                LDA     [_ifTablePtr],Y
                STA     _ifnIdx
                INY
                INY
                LDA     [_ifTablePtr],Y
                STA     _ifnCount
                RTS
; _Ifr_Lo0Addr - 127.0.0.1, network order.
_Ifr_Lo0Addr    LDA     #$007F
                STA     _ifnIdx
                LDA     #$0100
                STA     _ifnCount
                RTS
; _Ifr_Sin - the union = sockaddr_in {AF_INET, port 0, address, zero[8]}.
_Ifr_Sin        LDY     #IFR_ADDR
                LDA     #AF_INET
                STA     [_kCopyPtr],Y
                LDY     #IFR_ADDR+2
                LDA     #0
                STA     [_kCopyPtr],Y
                LDY     #IFR_ADDR+4
                LDA     _ifnIdx
                STA     [_kCopyPtr],Y
                INY
                INY
                LDA     _ifnCount
                STA     [_kCopyPtr],Y
                LDY     #IFR_ADDR+8
                BRA     _Ifr_ZeroTail
; _Ifr_SinZero - the union zeroed (an ifnet with no address).
_Ifr_SinZero    LDY     #IFR_ADDR
_Ifr_ZeroTail   LDA     #0
@isz_l          STA     [_kCopyPtr],Y
                INY
                INY
                CPY     #IFREQ_SIZE
                BCC     @isz_l
                RTS
; _Ifr_Lookup - ifunit: the caller ifreq's name (NUL-terminated, at most 8
; bytes counted) against lo0 and each record.  C=1 + X = record offset, or
; X = $FFFF for lo0; C=0 when none matches.
_Ifr_Lookup     LDA     [_libcTmp2]
                CMP     #$6F6C                  ; "lo"
                BNE     @il_cards
                LDY     #2
                LDA     [_libcTmp2],Y
                CMP     #$0030                  ; "0", NUL
                BNE     @il_cards
                LDX     #$FFFF
                SEC
                RTS
@il_cards       STZ     _ifcRecOff
@il_rec         LDA     _ifcRecOff
                CMP     #IFNET_BLK_SIZE
                BCS     @il_none
                TAY
                LDA     [_ifTablePtr],Y         ; 0 = empty
                BEQ     @il_next
                LDX     #0                      ; byte index
@il_byte        STX     _ifnIdx
                TXY
                SEP     #$20
                MX      %10
                LDA     [_libcTmp2],Y           ; the caller's byte
                STA     _ifnCount
                REP     #$20
                MX      %00
                LDA     _ifcRecOff
                CLC
                ADC     _ifnIdx
                TAY
                SEP     #$20
                MX      %10
                LDA     [_ifTablePtr],Y         ; the record's byte
                CMP     _ifnCount
                REP     #$20
                MX      %00
                BNE     @il_next
                LDA     _ifnCount
                AND     #$00FF
                BEQ     @il_hit                 ; both ended here
                LDX     _ifnIdx
                INX
                CPX     #8
                BCC     @il_byte
@il_hit         LDX     _ifcRecOff
                SEC
                RTS
@il_next        LDA     _ifcRecOff
                CLC
                ADC     #IF_REC_SIZE
                STA     _ifcRecOff
                BRA     @il_rec
@il_none        CLC
                RTS

;------------------------------------------------------------------------------
; _Ifc_SetIpFields - copy the caller ifreq's IP-layer fields (IF_Ip..IF_Gateway,
; offsets 16..31) into the record (offset X) and set IFF_IP_CONF.  MX %00.
;------------------------------------------------------------------------------
_Ifc_SetIpFields MX     %00
                STX     _ifcRecOff
                LDY     #IF_Ip                  ; 16..30 step 2 (8 words)
@sif_l          LDA     [_libcTmp2],Y           ; ifreq IP word
                STA     _ifcTmpW
                PHY
                TYA
                CLC
                ADC     _ifcRecOff
                TAY                             ; record index
                LDA     _ifcTmpW
                STA     [_ifTablePtr],Y         ; -> record
                PLY
                INY
                INY
                CPY     #IF_REC_SIZE
                BCC     @sif_l
                ; --- flags byte: IFF_IP_CONF always; IFF_DHCP tracks the OP.
                ;     Cleared first so a manual IFC_SET after a lease stops
                ;     claiming dhcp, then re-set only for IFC_SETDHCP.
                LDA     _ifcRecOff
                CLC
                ADC     #IF_Flags
                TAY
                SEP     #$20
                MX      %10
                LDA     [_ifTablePtr],Y
                ORA     #IFF_IP_CONF
                AND     #{$FF-IFF_DHCP}
                STA     [_ifTablePtr],Y
                LDA     _ifcOp                  ; low byte; ops are all < 256
                CMP     #IFC_SETDHCP
                BNE     @sif_notDhcp
                LDA     [_ifTablePtr],Y
                ORA     #IFF_DHCP
                STA     [_ifTablePtr],Y
@sif_notDhcp    REP     #$20
                MX      %00
                RTS

;==============================================================================
; Socket layer (lifted from src/kernel/socket.s, ② net-mod reclaim Phase 2).
; Each net_op_* is JSL'd by _Net_Dispatch -> RTL; the prologue restores the
; syscall args from _Sys_Saved* (the dispatcher clobbers A/Y, preserves X) so
; the lifted body runs verbatim.  Kernel routines are reached via the
; _Net_KCall_* RTL wrappers (net_dispatch.s).  The transport cores +
; _Sock_PollIntr + _AllocSockTable + _Sock_Teardown + the _sock* scratch STAY
; kernel-side (reached DBR-relative via the manifest).
;==============================================================================

;------------------------------------------------------------------------------
; net_op_socket - SYS_SOCKET (#71): socket(domain, type, proto).
;------------------------------------------------------------------------------
net_op_socket   MX      %00
                LDA     _Sys_SavedA             ; domain
                LDX     _Sys_SavedX             ; type
                LDY     _Sys_SavedY             ; proto
                AND     #$00FF
                CMP     #AF_UNIX
                BEQ     @ss_unix
                CMP     #AF_INET
                BNE     @ss_einval
                STY     _sockTmpProto
                TXA
                AND     #$00FF
                CMP     #SOCK_DGRAM
                BNE     @ss_tryStream
                LDA     #XPORT_UDP
                STA     _sockTmpTag
                BRA     @ss_proceed
@ss_tryStream   CMP     #SOCK_STREAM
                BNE     @ss_tryRaw
                LDA     #XPORT_TCP
                STA     _sockTmpTag
                BRA     @ss_proceed
@ss_tryRaw      CMP     #SOCK_RAW
                BNE     @ss_einval
                LDA     _sockTmpProto
                AND     #$00FF
                CMP     #IPPROTO_ICMP
                BNE     @ss_einval
                LDA     #XPORT_ICMP
                STA     _sockTmpTag
                BRA     @ss_proceed
@ss_einval      LDA     #EINVAL
                CLC
                RTL
@ss_emfile      LDA     #EMFILE
                CLC
                RTL
@ss_eprototype  LDA     #EPROTOTYPE
                CLC
                RTL
; No domain claims a W5100 hardware socket here.  An AF_INET descriptor starts
; SOCK_HW_UNCLAIMED and takes one from the verb that first drives the chip
; (_Xport_Claim); an AF_UNIX one never does.
;
; AF_UNIX is SOCK_DGRAM only.  SOCK_STREAM is refused rather than
; accepted-and-unimplemented: upstream's SOCK_STREAM AF_UNIX is what pipe(2) is
; built from, and this kernel has real pipes (DTYPE_PIPE, 2.11BSD's), so there is nothing for it to be.  EPROTOTYPE
; is 2.11BSD's errno for exactly this: "protocol wrong type for socket".
@ss_unix        TXA
                AND     #$00FF
                CMP     #SOCK_DGRAM
                BNE     @ss_eprototype
                LDA     #XPORT_UNIX
                STA     _sockTmpTag
                LDA     #SOCK_HW_NONE
                STA     _sockTmpHw
                BRA     @ss_scan
@ss_proceed     LDA     #SOCK_HW_UNCLAIMED
                STA     _sockTmpHw
@ss_scan        LDY     #0
@ss_findL       SEP     #$20
                MX      %10
                LDA     [_sockTablePtr],Y
                BEQ     @ss_free
                REP     #$20
                MX      %00
                TYA
                CLC
                ADC     #SOCK_REC_SIZE
                TAY
                CPY     #SOCKTBL_BLK_SIZE
                BCC     @ss_findL
                REP     #$20
                MX      %00
                BRA     @ss_emfile
@ss_free        REP     #$20
                MX      %00
                STY     _sockTmpOff
                SEP     #$20
                MX      %10
                LDA     #$01
                STA     [_sockTablePtr],Y
                INY
                LDA     _sockTmpHw
                STA     [_sockTablePtr],Y
                INY
                LDA     #$00
                STA     [_sockTablePtr],Y
                INY
                STA     [_sockTablePtr],Y
                INY
                STA     [_sockTablePtr],Y
                INY
                STA     [_sockTablePtr],Y
                INY
                LDA     _sockTmpTag
                STA     [_sockTablePtr],Y
                INY
                ; SOCK_State (offset 7) -- the ONE byte this positional run used
                ; to step over.  A descriptor is Kmalloc'd once and recycled by
                ; index, so a slot that had been a listener came back from
                ; socket() still reading TCP_LISTEN: _Loop_FindListener matched
                ; it and a connect to that port was answered by a socket nobody
                ; had bound.  It also made every SOCK_State test downstream a
                ; test of the PREVIOUS tenant (apple/fgx#133).
                LDA     #TCP_CLOSED
                STA     [_sockTablePtr],Y
                REP     #$30
                MX      %00
                JSR     _Sock_ClearXportState   ; bytes 8 onward are NOT set above
                JSL     SYS_NETKC_FCBALLOC
                BCC     @ss_fcbFail
                PHA
                LDY     #FCB_Flags
                LDA     #FCB_FL_SOCKET
                STA     [_fcbPtr],Y
                LDY     #FCB_FstIdx
                LDA     #$00
                STA     [_fcbPtr],Y
                LDY     #FCB_SockIdx
                LDA     _sockTmpOff
                STA     [_fcbPtr],Y
                PLA
                REP     #$20
                MX      %00
                AND     #$00FF
                SEC
                RTL
@ss_fcbFail     PHA
                REP     #$30
                MX      %00
                LDY     _sockTmpOff
                SEP     #$20
                MX      %10
                LDA     #$00
                STA     [_sockTablePtr],Y
                PLA
                REP     #$20
                MX      %00
                AND     #$00FF
                CLC
                RTL

;------------------------------------------------------------------------------
; net_op_bind - SYS_BIND (#72): bind(fd, sockaddr_in*, len).
