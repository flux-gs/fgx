;==============================================================================
; net.s - FGXM module: the FGX networking stack (Phase 1: SYS_IFCONFIG).
;
; Lifted out of the kernel (② net-mod reclaim, see
; docs/superpowers/plans/2026-06-09-fgx-net-mod.md).  The kernel keeps the
; W5100 chip bring-up + the shared (bpf.mod-and-scheduler) W5100 ISR + the
; boot iface registration; the socket layer, transport cores and the
; SYS_IFCONFIG read path move here, dispatched from the kernel's syscall
; thunks via _Net_Dispatch (src/kernel/net_dispatch.s) through a VT_NET
; net_op_table — exactly the prodos.mod FOP/_Fst_Dispatch pattern.
;
; Each op is reached by JSL (so it RTLs), runs in THIS module's bank (PB set
; by the JSL) with DBR=kernel-bank (the dispatcher's live bank; $02 = assembly
; ORG) + the kernel direct page active.  So:
;   - DBR-relative reads of the kernel statics assembled at $02 (the ifconfig
;     scratch statics that STAY in ifconfig_sys.s, the _Sys_Saved* /
;     _Sys_CallerBank syscall args) are byte-identical to the in-kernel code;
;   - [_ifTablePtr],Y / [_libcTmp2],Y use the kernel DP soft-globals;
;   - same-bank JSRs into our moved helpers (FindByIndex/Name, _Ifc_*) work;
;   - a cross-bank kernel routine (_W5_WriteIpFromRec) is reached by JSL to
;     its build-resolved bank-$02 address (manifest).
; Ops read their syscall args from _Sys_Saved* (NOT live A/X): _Net_Dispatch
; clobbers A on the way in.
;
; Bank-agnostic, OFFSET-SPECIFIC.  The BANK is still whatever the loader
; puts this module in -- every absolute reference is DBR-relative once
; mod_init runs PHK/PLB.  The OFFSET WITHIN that bank is NOT free: modules
; now SHARE one bank, so this image is ORG'd at MODP_ORG (generated by
; tools/gen_modplace.py from the measured sizes of the modules placed before
; it) and MUST be loaded there.  The FGXM header's load_addr carries that
; offset to Mod_Load.
; mod_init self-patches net_op_table's bank bytes to the live bank.
;==============================================================================

