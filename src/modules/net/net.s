                CLC
                RTL
net_op_loopstatus   MX      %00
                ; RE-STAGE Y, exactly as loopclose below does.  _Loop_StatusTry
                ; takes the DESCRIPTOR RECORD OFFSET in Y, and the kernel stub
                ; that reaches this op destroyed it: _NetThunkExec takes its op
                ; number in Y, so `LDY #NETOP_LoopStatus` overwrote the
                ; descriptor with 72 before the thunk ever ran.
                ;
                ; The migration's own census MISSED this one and said so in
                ; net_loop.s -- "_Loop_CloseTry is the one such site" -- because
                ; it audited the six ops it was moving.  This entry's Y comes
                ; from _Sel_Classify in syscall.s, which is not one of them, and
                ; select() is the only caller.
                ;
                ; _sockTmpOff is the right source and needs no new staging cell:
                ; @cl_sock does `STY _sockTmpOff` on the line BEFORE it calls
                ; _Loop_StatusTry, for its own later use.
                ; AF_UNIX FIRST, then loopback, in net_op_send's order and for
                ; its reason: this test is a single SOCK_Proto compare, where
                ; _Loop_StatusTry resolves more state before it can decide.  Both
                ; write the op's OUT cells, so the kernel reads one place either
                ; way -- _Sel_Classify tests _loopHandled and takes _loopBits.
                LDY     _sockTmpOff             ; descriptor offset the kernel
                JSR     _Unp_StatusTry          ;   saved before the thunk
                LDA     _unpHandled
                BNE     @nls_done
                LDY     _sockTmpOff             ; re-staged: the try above took Y
                JSR     _Loop_StatusTry
@nls_done       RTL
net_op_loopclose    MX      %00
                LDY     _loopThunkSock          ; the socket index fs.s passed in
                JSR     _Loop_CloseTry          ;   Y, staged across the thunk
                RTL
