                RTL
@sb_open        JSR     _Net_Xport_Open
                RTL

;------------------------------------------------------------------------------
; net_op_setsockopt - SYS_SETSOCKOPT (#75): setsockopt(fd, level, optname, ...).
; A = fd, X = level, Y = optname.
;------------------------------------------------------------------------------
; This is 2.11BSD's `sosetopt' (usr/sys/sys/uipc_socket.c:645-700) in this
; tree's shape, and it used to be none of it: the level was ignored, every
; option name but SO_BROADCAST fell through to `return 0', and `optval' and
; `optlen' never left libc at all.  So `setsockopt' ANSWERED SUCCESS FOR
; EVERYTHING -- an option this machine has never heard of, at a level it does
; not implement -- and SO_BROADCAST could be turned on but never off, because
; the value the caller passed to turn it off was discarded before anything read
; it (apple/fgx#439).
;
; Upstream's order is what the arms below follow.  The socket is resolved first
; (`getsock' in the syscall, ahead of `sosetopt'), so a bad fd is EBADF rather
; than a complaint about the option.  A level other than SOL_SOCKET goes to the
; protocol's `pr_ctloutput', and with none here that is `error = ENOPROTOOPT'
; (:654).  An option outside the switch is ENOPROTOOPT too, and one inside it
; with too small a value is EINVAL (`m->m_len < sizeof (int)', :673).
;
; SO_LINGER IS REFUSED WITH THE UNKNOWN NAMES rather than accepted: upstream
; takes a `struct linger' for it and acts on `so_linger' at close time, and
; there is nothing here that would. Half-accepting it -- recording a bit from a
; value of the wrong shape -- is the pattern this fix exists to remove.
;
; Arg block: +0 level  +2 optname  +4 optval offset  +6 optlen  +8 optval bank.
