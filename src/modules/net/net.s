;==============================================================================
; sosend / soreceive -- where every socket's data goes.
;
; 2.11BSD reaches a socket's data through two routines whatever the syscall:
; sorw (read, write), sendit (send, sendto) and recvit (recv, recvfrom) all
; build a uio and call sosend(so, nam, uio, flags) or soreceive(so, aname, uio,
; flags) (sys_generic.c:529, uipc_syscalls.c, uipc_socket.c:299/424).  The
; protocol under the socket is the socket's own business from there.
;
; _So_Send and _So_Recv are that pair.  In: _sockTmpOff = the descriptor;
; _sockUio = the caller's uio; _sockSendFlags / _sockRecvFlags; for a send,
; _soHasDst = 1 when _sockDstIp/_sockDstPort name a destination (sendto); for a
; receive, _sockSrcOff = where to put the source address, 0 for none.
; Out: A = bytes moved + C=1, or A = errno + C=0.  MX %00.
;
; THE TRANSPORT IS CHOSEN HERE ONCE, by the descriptor: AF_UNIX by SOCK_Proto,
; loopback by SOCK_HwIdx = SOCK_HW_LOOP, and the W5100 for the rest.  A
; connected loopback socket given an address (sendto, recvfrom) is sent or
; received on like any connected stream -- sosend asks for an address only on
; an unconnected socket, and TCP's PRU_SEND does not read one -- rather than
; reaching the chip cores with a hardware index no chip socket has.
;==============================================================================
_So_Send        MX      %00
                JSR     _So_Proto               ; A = SOCK_Proto
                CMP     #XPORT_UNIX
                BNE     @sosd_notUnix
                LDA     _soHasDst               ; sendto on AF_UNIX: a temporary
                BEQ     @sosd_unp                 ;   connect is not implemented
                LDA     #EINVAL
                CLC
                RTS
@sosd_unp         JMP     _Unp_Send
@sosd_notUnix     LDA     _sockSendFlags          ; no out-of-band on either of
                AND     #MSG_OOB                ;   the others (sosend's
                BNE     @sosd_oob                 ;   PRU_SENDOOB; EOPNOTSUPP)
                JSR     _So_IsLoop
                BCC     @sosd_chip
                LDA     #0                      ; send
                JMP     _Loop_SoIo
@sosd_chip        LDA     _sockTmpTag             ; (set by _So_Proto)
                CMP     #XPORT_UDP
                BNE     @sosd_dst
                ; A DATAGRAM GOES TO ITS CONNECTED PEER OR TO THE ADDRESS GIVEN,
                ; NEVER BOTH AND NEVER NEITHER.  udp_output: an address on a
                ; connected socket is EISCONN; sosend: no address on an
                ; unconnected one is EDESTADDRREQ.
                JSR     _So_UdpPeer             ; C=1 connected
                LDA     _soHasDst
                BEQ     @sosd_nodst
                BCC     @sosd_bind              ; sendto, unconnected
                LDA     #EISCONN
                CLC
                RTS
@sosd_nodst       BCS     @sosd_peer
                LDA     #EDESTADDRREQ
                CLC
                RTS
@sosd_peer        JSR     _So_UdpPeerLoad         ; bound by connect already
                BRA     @sosd_bcast
@sosd_dst         LDA     _soHasDst
                BEQ     @sosd_hw
@sosd_bind        JSR     _Sock_EnsureBound       ; sendto: implicit bind
                BCS     @sosd_bcast
                RTS                             ; ENOBUFS: no chip socket free
@sosd_bcast       LDA     _sockDstIp              ; broadcast needs SO_BROADCAST:
                AND     #$00FF                  ;   2.11BSD ip_output.c:152-154
                CMP     #$00FF
                BNE     @sosd_hw
                LDY     _sockTmpOff
                TYA
                CLC
                ADC     #SOCK_Flags
                TAY
                SEP     #$20
                MX      %10
                LDA     [_sockTablePtr],Y
                AND     #SO_BROADCAST
                REP     #$30
                MX      %00
                BNE     @sosd_hw
                LDA     #EACCES
                CLC
                RTS
@sosd_hw          JSR     _So_Resid               ; _sockLen = uio_resid
                CMP     #SO_BOUNCE_SZ+1         ; no chip ring holds more
                BCC     @sosd_fits
                LDA     _sockTmpTag             ; (set by _So_Proto)
                CMP     #XPORT_TCP
                BNE     @sosd_emsg                ; a datagram goes whole or not
                LDA     #SO_BOUNCE_SZ           ;   at all; a stream writes short
                STA     _sockLen
@sosd_fits        JSR     _So_Bounce
                BCC     @sosd_out
                JMP     _Net_Xport_Send
@sosd_emsg        LDA     #EMSGSIZE               ; sosend: sosendallatonce and
                CLC                             ;   resid > sb_hiwat
@sosd_out         RTS
@sosd_oob         LDA     #ENOTSUP
                CLC
                RTS

_So_Recv        MX      %00
                JSR     _So_Proto
                CMP     #XPORT_UNIX
                BNE     @sorc_notUnix
                JMP     _Unp_Recv
@sorc_notUnix     LDA     _sockRecvFlags
                AND     #MSG_OOB
                BNE     @sorc_oob
                JSR     _So_IsLoop
                BCC     @sorc_chip
                LDA     #1                      ; receive
                JMP     _Loop_SoIo
@sorc_chip        LDA     _sockSrcOff             ; recvfrom: implicit bind
                BEQ     @sorc_hw
                JSR     _Sock_EnsureBound
@sorc_hw          JSR     _So_Resid               ; _sockLen = uio_resid: the most
                JSR     _So_Bounce              ;   the cores copy
                BCC     @sorc_out
                CMP     #SO_BOUNCE_SZ+1         ; A = _sockLen still; a receive
                BCC     @sorc_fits                ;   of more than one ring is at
                LDA     #SO_BOUNCE_SZ           ;   most one ring
                STA     _sockLen
@sorc_fits        LDA     _soBounce               ; the cores copy into the bounce;
                STA     _sockBufOff             ;   _So_RxDrain moves it into the
                SEP     #$20                    ;   uio
                MX      %10
                LDA     _soBounce+2
                STA     _libcTmp2+2
                REP     #$30
                MX      %00
                JMP     _Net_Xport_Recv
@sorc_oob         LDA     #ENOTSUP
                CLC
@sorc_out         RTS

