;   In: A.lo = index N.  MX %00.  Out: C=1 + X = record offset, or C=0.
; (Same-bank helper, JSR'd by the ops -> RTS.)
;------------------------------------------------------------------------------
_Ifnet_FindByIndex MX   %00
                AND     #$00FF
                STA     _ifnIdx
                STZ     _ifnCount
                LDY     #0
@fbx_l          LDA     [_ifTablePtr],Y         ; Name word; 0 = empty
                BEQ     @fbx_skip
                LDA     _ifnCount
                CMP     _ifnIdx
                BEQ     @fbx_hit
                INC     _ifnCount
@fbx_skip       TYA
                CLC
                ADC     #IF_REC_SIZE
                TAY
                CPY     #IFNET_BLK_SIZE
                BCC     @fbx_l
                CLC
                RTS
@fbx_hit        TYA
                TAX
                SEC
                RTS

