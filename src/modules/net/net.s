_Ifnet_FindByName MX    %00
                LDY     #0
@fbn_l          LDA     [_ifTablePtr],Y         ; Name word; 0 = empty
                BEQ     @fbn_skip
                PHY
                SEP     #$20
                MX      %10
                LDX     #0
@fbn_c          LDA     [_ifTablePtr],Y         ; record name byte (Y = base+i)
                CMP:    _ifnName,X
                BNE     @fbn_ne
                INY
                INX
                CPX     #8
                BCC     @fbn_c
                REP     #$20                    ; all 8 matched
                MX      %00
                PLY
                TYA
                TAX
                SEC
                RTS
@fbn_ne         REP     #$20
                MX      %00
                PLY
@fbn_skip       MX      %00
                TYA
                CLC
                ADC     #IF_REC_SIZE
                TAY
                CPY     #IFNET_BLK_SIZE
                BCC     @fbn_l
                CLC
                RTS

