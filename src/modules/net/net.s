;------------------------------------------------------------------------------
; _W5_PatchSlot (module) - bind THIS module's W5100 U2_* register accesses to the
; detected slot (_u2Slot), mirroring the kernel's uthernet.s _W5_PatchSlot.
;
; net.mod bakes its ~205 fixed-base STAL/LDAL U2_ARH/ARL/DAT sites at slot 1
; ($E0C095..97).  This rewrites each instruction's operand LOW byte to address the
; detected slot's W5100 base = $E0C084 + (_u2Slot<<4) + regoff.  Slot 1 -> the new
; low byte equals the baked $95/$96/$97 -> every store is a NO-OP (slot-1 path
; unchanged).  Slot 0 (no card) -> early-out, nothing patched.
;
; RELOCATION (THE invariant): the module ORGs at MODP_ORG -- a FIXED offset
; inside the shared module bank, not a free choice; see the file header --
; but
; loads at a dynamically-allocated bank at RUNTIME (never $05).  The patch table
; (_w5PatchTbl, GENERATED) holds 16-bit bank-relative OFFSETS only.  The self-mod
; store's bank comes from PHK at load time (the real load bank) -- exactly like
; mod_init's op-table self-patch and the kernel's _W5_PatchSlot.  $05 never
; appears in any runtime store.
;
; Two banks bridged: _u2Slot is a KERNEL static, reachable DBR-relative ONLY while
; DBR = kernel bank.  So this MUST be called as the FIRST thing in mod_init, BEFORE
; mod_init's own PHK/PLB (which switches DBR to the load bank).  It saves the entry
; DBR (kernel bank) with PHB, switches to the load bank (PHK/PLB) for the self-mod
; stores, then restores DBR with PLB -- transparent to mod_init.
;
; Entry: DBR = kernel bank, MX %00.  Preserves DBR (PHB/PLB).  Clobbers A,X,Y.
;------------------------------------------------------------------------------
_W5_PatchSlot   MX      %00
                PHB                             ; save entry DBR (= kernel bank)
                ; --- guard: no W5100 detected -> nothing to bind.  _u2Slot is a
                ;     kernel static, reachable here because DBR = kernel bank. ---
                SEP     #$20
                MX      %10
                LDA     |_u2Slot                ; kernel static (DBR = kernel bank)
                BEQ     @wp_done                ; 0 = no card -> nothing
                ; --- precompute base low byte = $84 + (_u2Slot<<4); regoff added
                ;     per-site in the loop. ---
                ASL
                ASL
                ASL
                ASL                             ; _u2Slot<<4 (slot 1..7 -> $10..$70)
                CLC
                ADC     #$84                    ; base low byte for this slot's W5100
                PHA                             ; stash baseLow (M8: 1 byte) across bank switch
                ; --- DBR = our LOAD bank (PHK = real runtime bank; reloc-correct,
                ;     never $05) so the self-mod stores + _wpBaseLow/_w5PatchTbl
                ;     reads all land in our (relocated) module code. ---
                REP     #$30
                MX      %00
                PHK
                PLB                             ; DBR = load bank
                SEP     #$20
                MX      %10
                PLA
                STA     |_wpBaseLow             ; MODBANK-OK: DBR = load bank (PHK/PLB above)
                REP     #$30
                MX      %00
                LDY     #0
@wp_loop        LDX     _w5PatchTbl,Y           ; X = operand-low-byte offset (M16/X16)
                CPX     #$FFFF
                BEQ     @wp_done                ; sentinel -> done
                INY
                INY                             ; Y -> the DFB regoff byte
                SEP     #$20
                MX      %10
                LDA     _w5PatchTbl,Y           ; A.lo = regoff (0..3)
                CLC
                ADC     |_wpBaseLow             ; MODBANK-OK: still under that PHK/PLB
                                        ;   newlow = $84 + (slot<<4) + regoff
                STA:    $0000,X                 ; self-mod: load_bank:offset <- newlow
                REP     #$30
                MX      %00
                INY                             ; past the DFB byte -> next entry
                BRA     @wp_loop
@wp_done        REP     #$30
                MX      %00
                PLB                             ; restore entry DBR (balances PHB)
                RTS

_wpBaseLow      DS      1                       ; module-local scratch (in load bank)

;------------------------------------------------------------------------------
; mod_init - MX %00 entry; DBR = kernel bank.  Bind our W5100 U2_* sites to the
; detected slot FIRST (while DBR=kernel bank, so _u2Slot is reachable), THEN
; PHK/PLB sets DBR = our bank and self-patch the op table bank bytes, then RTL
; with C=1.  Registration is declarative (the VTDR walk did it).
;------------------------------------------------------------------------------
mod_init        MX      %00
                JSR     _W5_PatchSlot                   ; bind W5100 sites (DBR=kernel bank; restores DBR)
                PHK
                PLB                                     ; DBR = our bank
                SEP     #$30                            ; M8/X8 for the byte patch
                MX      %11
                PHK
                PLA                                     ; A = our bank
                LDX     #2                              ; bank byte of entry 0
@mi_spL         STA:    net_op_table,X
                INX
                INX
                INX
                CPX     #NET_OP_TBL_LEN
                BCC     @mi_spL
                REP     #$30
                MX      %00
                SEC                                     ; success
                RTL

