/* FGX-Origin: original -- FGX code.  It CITES BSD (see below) but contains
 * none of it; registering it would assert the Regents' copyright over work
 * they did not write.
 * vfs_probe.c -- the boot self-test for the buffer cache's WIRING.
 *
 * WHAT NEEDED A PROBE AND WHY THE FIXTURE IS NOT IT.  toolchain/tests/M37/
 * biocache.c exercises the cache against a fake disk in the fcc oracle: lists,
 * hashes, reclaim.  It proves nothing about the kernel wiring, because in that
 * world there is no block layer, no second bank and no device.  Three things
 * landed with no on-target coverage at all -- the block layer's 24-bit buffer
 * address, the per-device cache bypass, and bio_strategy's two-transfer split
 * -- and each of them fails silently: bytes land in the wrong bank, or in two
 * caches, or in the wrong order, and everything still boots.
 *
 * So this is one probe for all three, which is also why it is one probe and
 * not three: they can only be told apart by a test that goes all the way from
 * bread() down to a device block and back up by an INDEPENDENT path.
 *
 * THE ORACLE IS THE LAYER BELOW.  Every assertion here compares what the cache
 * produced against what a RAW kc_blkio call reads or wrote.  Checking the
 * cache's own flags would only ask the code under test whether it thinks it
 * worked.
 *
 * Return 0 = pass; each nonzero value names one failing property, so a failure
 * says which, not merely that.
 *
 *----------------------------------------------------------------------------
 * IT WRITES, AND WHERE IT WRITES IS THE CAREFUL PART.
 *
 * The target is a SCRATCH 2.11BSD VOLUME attached as a second SmartPort drive
 * (disk/ufsscratch.po, built by the ninja `ufsscratch` rule from fgxfs mkfs).
 * Three things make that safe: the ProDOS layer cannot read a UFS volume, so
 * nothing else on the system mounts or touches it; the caller never passes
 * device 0, which is the boot disk; and the image is generated by the build,
 * so a run that corrupts it costs nothing but the next mkfs.
 *
 * A second real spindle is also better evidence than the RAM disk this was
 * first written against: it exercises the actual DEVICE path, including the
 * extended-call parameter list whose buffer bank byte _blkBufBank now sets.
 * The RAM disk only ever exercised an in-kernel copy loop, so it could not
 * have caught a bank bug on the SmartPort side at all.
 *
 * The device is a parameter precisely so this choice stays with the caller.
 *
 *----------------------------------------------------------------------------
 * THE FILESYSTEM CASES LEFT AT 1.10b.  The 2.11BSD superblock (1.10a) and the
 * allocators (1.10b) were here and are now src/kernel/vfs/ufs_probe.c behind
 * kernel.ufsprobe -- a bank split, the third this module has needed, and the
 * same move that separated the earlier probe gates at 1.7b.  They also
 * ask a different question: this file asks whether the buffer cache is WIRED,
 * that one whether the format reader agrees with an independent implementation
 * of the format.  The two gates are ALTERNATIVES; setting both overflows the
 * bank and the ERR guard at the end of vfs.s says so.
 */

#include "fsparam.h"
#include "vnode.h"
#include "specdev.h"
#include "buf.h"
#include "uio.h"

extern int          bdevvp();
extern int          vinvalbuf();
extern int          spec_read();
extern int          spec_write();
extern void         vrele();
extern int          kc_blkio();
extern int          bread();
extern void         brelse();
extern int          bwrite();
extern int          kc_blkreads();

#define DEV_BLKSIZE     512
#define PROBE_READ      1
#define PROBE_WRITE     0

/* One 512-byte scratch, reused for each half rather than two -- the halves are
 * checked one at a time, and a second buffer would be a kilobyte of kernel
 * bank for no extra evidence. */
static char probebuf[DEV_BLKSIZE];

/* One FILESYSTEM block, for the transfer-path cases below.  Static rather than
 * automatic: 1024 bytes is a large stack frame for kernel C, and this probe
 * runs on the boot path where the kernel stack is not the place to find out. */
static char specbuf[FS_BLKSIZE];

/* THE PROBE NO LONGER BRINGS ITS OWN VNODE.  It used to declare a bare struct
 * vnode and set b_dev by hand, because nothing could say which device a buffer
 * belonged to -- the layer missing on purpose at 1.3c.  bdevvp is that layer:
 * it hands back a real device vnode, checkalias puts it on the alias chain,
 * and b_dev follows from v_rdev without anyone naming it.
 *
 * Which also makes this a test of the new path rather than only a user of it.
 * Every read below goes through VOP_STRATEGY on a vnode whose vector came from
 * specfs, so a mis-ordered ops vector, a vector that did not resolve, or a
 * device number that did not survive checkalias fails here -- on the boot
 * path, against a real disk.  That matters more than it sounds: the fcc
 * fixtures cannot reach this context at all (apple/fgx#88). */

/* Raw device access, bypassing the cache entirely: this is the oracle. */
static int
rawio(dev, dblk, isread)
    int     dev;
    daddr_t dblk;
    int     isread;
{
    return (kc_blkio(dev, (int)(dblk >> 16), (int)dblk, probebuf, isread));
}

int
vfs_probe(dev, fsblk)
    int     dev;
    daddr_t fsblk;
{
    struct buf   *bp;
    struct vnode *devvp;
    daddr_t       dblk;
    int           i;
    int           err;
    int           before;

    dblk = fsblk * (daddr_t)2;

    /* ---- IDENTIFY THE VOLUME BEFORE WRITING A SINGLE BYTE ---------------
     *
     * This probe writes, so it must PROVE it is talking to the scratch volume
     * and not to something it would destroy.  A device index is not proof: an
     * uninitialised device table can read as an online disk, and the emulator
     * is free to map an attached image somewhere other than where the device
     * numbering suggests.  Both happened here -- the earlier version wrote to
     * whatever answered at index 1, which read back as neither the pattern it
     * had just written nor the contents of the image on the host.
     *
     * So: read the 2.11BSD superblock, which fgxfs mkfs puts in filesystem
     * block 1 (device block 2), and require its leading fields.  A volume that
     * does not identify is left completely alone and the probe reports that
     * rather than pressing on.
     */
    if (rawio(dev, (daddr_t)2, PROBE_READ) != 0)
        return (60);            /* cannot even read the candidate */
    if (probebuf[0] != (char)0x42 || probebuf[1] != (char)0x00 ||
        probebuf[4] != (char)0x00 || probebuf[5] != (char)0x10)
        return (61);            /* NOT the scratch volume -- nothing written */

    /* ---- 0. Is the seam itself carrying arguments correctly? ------------
     * Device block 0 exists on any live volume, so a read of it must succeed.
     * Split out from the write below so a failure says whether kc_blkio works
     * at all or whether the chosen block is the problem -- the two have very
     * different causes and bisecting them from one code wastes a boot.
     * Returns 20 + errno, so the code names the driver's own complaint. */
    err = rawio(dev, (daddr_t)0, PROBE_READ);
    if (err != 0)
        return (20 + err);

    /* Is the CHOSEN block in range?  A read of it must work before a write
     * to it can, and separating the two says whether a failure is about the
     * block number or about the write path.  Returns 30 + errno. */
    err = rawio(dev, dblk, PROBE_READ);
    if (err != 0)
        return (30 + err);

    /* Does the RAW path move the right BYTES, not merely return success?
     * Write a pattern, poison the buffer, read it back.  This uses only
     * kc_blkio, so a failure here is the block layer or the seam and has
     * nothing to do with the cache -- and without it, a raw write that took
     * its data from the wrong bank would look like a cache bug further down.
     * Returns 50. */
    for (i = 0; i < DEV_BLKSIZE; i++)
        probebuf[i] = (char)(0xA5);
    if (rawio(dev, dblk, PROBE_WRITE) != 0)
        return (51);
    for (i = 0; i < DEV_BLKSIZE; i++)
        probebuf[i] = (char)(0x3C);
    if (rawio(dev, dblk, PROBE_READ) != 0)
        return (52);
    /* On a mismatch, report the BYTE THAT CAME BACK rather than a bare "no":
     * 0x3C means the read never wrote the buffer at all (the poison survived),
     * 0x00 means it landed somewhere else, and anything else is a third story.
     * Guessing between those costs a boot each. */
    for (i = 0; i < DEV_BLKSIZE; i++)
        if (probebuf[i] != (char)(0xA5))
            return (100 + (probebuf[0] & 0x00FF));

    /* ---- 1. Lay down a known pattern through the RAW path ---------------
     * The two device blocks get DIFFERENT patterns, because identical ones
     * would pass even if bio_strategy read the same block twice or swapped
     * the halves -- the two failure modes most likely in a two-transfer
     * split. */
    for (i = 0; i < DEV_BLKSIZE; i++)
        probebuf[i] = (char)(i + 1);
    err = rawio(dev, dblk, PROBE_WRITE);
    if (err != 0)
        return (40 + err);
    for (i = 0; i < DEV_BLKSIZE; i++)
        probebuf[i] = (char)(0 - (i + 1));
    if (rawio(dev, dblk + (daddr_t)1, PROBE_WRITE) != 0)
        return (2);

    /* ---- 2. Read it through the cache ----------------------------------
     *
     * No hand-supplied device any more: bgetvp reads it from the vnode.  That
     * is an assertion rather than a convenience -- a device number that did not
     * survive bdevvp and checkalias reaches bio_strategy as NODEV, which it
     * rejects, and the read below fails.
     *
     * The vnode is released on the SUCCESS path only.  Every failure returns
     * straight out and leaks one of VNODE_POOL, which is the right trade on a
     * boot self-test: a machine whose buffer cache is miswired has a larger
     * problem than a vnode, and an unwind path per return would be more code
     * than the thing it protects. */
    err = bdevvp((dev_t)dev, &devvp);
    if (err != 0)
        return (14);

    /* bread lands in the arena, which is a bank the block layer could not
     * reach until _blkBufBank existed.  If that override is ignored the bytes
     * go to the kernel bank instead and the buffer keeps whatever it held. */
    err = bread(devvp, fsblk, &bp);
    if (err != 0)
        return (3);
    if (bp == 0)
        return (4);

    /* Both halves, in order.  This is the assertion that fails on a wrong
     * fsbtodb, a swapped pair, a lost high word on the second transfer, or a
     * buffer that landed in the wrong bank. */
    for (i = 0; i < DEV_BLKSIZE; i++) {
        if (bp->b_addr[i] != (char)(i + 1)) {
            brelse(bp);
            return (5);
        }
    }
    for (i = 0; i < DEV_BLKSIZE; i++) {
        if (bp->b_addr[DEV_BLKSIZE + i] != (char)(0 - (i + 1))) {
            brelse(bp);
            return (6);
        }
    }

    /* ---- 3. A second bread must not reach the device -------------------
     * kc_blkio is the only way down, and the kernel counts device reads, so
     * "the cache served it" is checkable rather than assumed.  This is also
     * what would catch the legacy cache having quietly taken ownership. */
    brelse(bp);
    before = kc_blkreads();
    err = bread(devvp, fsblk, &bp);
    if (err != 0)
        return (7);
    if (kc_blkreads() != before) {
        brelse(bp);
        return (8);                 /* went to the device on a hit */
    }

    /* ---- 4. Write through the cache, read back RAW ----------------------
     * The independent-oracle assertion, and the one worth keeping if only one
     * could be: it asks the layer BELOW whether the bytes arrived, in the
     * right device blocks, in the right order. */
    for (i = 0; i < DEV_BLKSIZE; i++) {
        bp->b_addr[i] = (char)(0x40 + (i & 15));
        bp->b_addr[DEV_BLKSIZE + i] = (char)(0x50 + (i & 15));
    }
    if (bwrite(bp) != 0)
        return (9);

    if (rawio(dev, dblk, PROBE_READ) != 0)
        return (10);
    for (i = 0; i < DEV_BLKSIZE; i++)
        if (probebuf[i] != (char)(0x40 + (i & 15)))
            return (11);
    if (rawio(dev, dblk + (daddr_t)1, PROBE_READ) != 0)
        return (12);
    for (i = 0; i < DEV_BLKSIZE; i++)
        if (probebuf[i] != (char)(0x50 + (i & 15)))
            return (13);

    /* ---- 5. spec_write and spec_read -- the TRANSFER path (UFS 1.7b) ----
     *
     * Cases 1-4 above prove the buffer cache is wired to the device.  These
     * prove the layer ON TOP of it: a uio in, device blocks out, and back.
     * The oracle is the same one and it is why this belongs here rather than
     * in a probe of its own -- rawio asks the layer BELOW whether the bytes
     * arrived, by a path that shares no code with what put them there.
     *
     * THE TWO ARMS OF spec_write ARE DIFFERENT CODE and only one of them is
     * the interesting one.  A whole-block write calls getblk and never reads
     * the device; a partial write must bread first, because the bytes it does
     * not cover have to survive.  Both are exercised, and the partial case is
     * checked for the PRESERVED remainder rather than for its own bytes --
     * that is the property the split exists for, and a spec_write that always
     * called getblk would pass every other assertion here.
     */
    {
        struct uio   u;
        struct iovec iv;
        off_t        base;

        base = (off_t)fsblk * (off_t)FS_BLKSIZE;

        /* 5a. A WHOLE BLOCK, so spec_write takes the getblk arm. */
        for (i = 0; i < FS_BLKSIZE; i++)
            specbuf[i] = (char)(0x60 + (i & 15));
        iv.iov_base  = specbuf;
        iv.iov_len   = FS_BLKSIZE;
        u.uio_iov    = &iv;
        u.uio_iovcnt = 1;
        u.uio_offset = base;
        u.uio_resid  = FS_BLKSIZE;
        u.uio_segflg = UIO_SYSSPACE;
        u.uio_rw     = UIO_WRITE;
        if (spec_write(devvp, &u, 0, (char *)0) != 0)
            return (20);
        /* THE CURSOR, not just the return code.  spec_read's loop terminates
         * on uio_resid, so a transfer that moved the bytes without consuming
         * the uio would spin the next caller forever. */
        if (u.uio_resid != 0)
            return (21);
        if (u.uio_offset != base + (off_t)FS_BLKSIZE)
            return (22);

        /* bawrite sets B_ASYNC, but VOP_STRATEGY is synchronous here -- biodone
         * runs before it returns -- so the bytes are on the device now and the
         * raw read below is not racing them. */
        if (rawio(dev, dblk, PROBE_READ) != 0)
            return (23);
        for (i = 0; i < DEV_BLKSIZE; i++)
            if (probebuf[i] != (char)(0x60 + (i & 15)))
                return (24);
        if (rawio(dev, dblk + (daddr_t)1, PROBE_READ) != 0)
            return (25);
        for (i = 0; i < DEV_BLKSIZE; i++)
            if (probebuf[i] != (char)(0x60 + ((i + DEV_BLKSIZE) & 15)))
                return (26);

        /* 5b. A PARTIAL write, so spec_write must bread first.  300 bytes at
         * offset 0 of the block: the other 724 are the ones that matter.
         *
         * THE REFERENCE PATTERN IS PUT ON THE DEVICE BY A PATH THAT NEVER
         * TOUCHES A BUFFER, AND WITHOUT THAT THIS CASE IS VACUOUS.  Twice.
         *
         * First attempt: check the remainder against what 5a wrote through the
         * cache.  Useless -- 5a leaves that block cached holding exactly those
         * bytes, so getblk hands back the right contents and a spec_write that
         * never calls bread passes.  Measured, not imagined: the mutation went
         * green.
         *
         * Second attempt: vinvalbuf first, so the next access is cold.  Also
         * useless, and this is the subtler one -- invalidating drops the
         * buffer HEADER, but the buffer's memory still physically holds the
         * old bytes, so the recycled buffer getblk returns still contains the
         * right answer.  The mutation went green again.  "Unspecified
         * contents" is not the same as "wrong contents", and a probe cannot
         * rely on garbage being unhelpful.
         *
         * What works: rawio the reference pattern straight to the device.  No
         * buffer ever holds it, so the only way the remainder can read back
         * correctly is if spec_write actually READ the block first. */
        for (i = 0; i < DEV_BLKSIZE; i++)
            probebuf[i] = (char)(0xA0 + (i & 15));
        if (rawio(dev, dblk, PROBE_WRITE) != 0)
            return (27);
        for (i = 0; i < DEV_BLKSIZE; i++)
            probebuf[i] = (char)(0xB0 + (i & 15));
        if (rawio(dev, dblk + (daddr_t)1, PROBE_WRITE) != 0)
            return (38);
        if (vinvalbuf(devvp, 1) != 0)
            return (39);

        for (i = 0; i < 300; i++)
            specbuf[i] = (char)(0x90 + (i & 15));
        iv.iov_base  = specbuf;
        iv.iov_len   = 300;
        u.uio_iov    = &iv;
        u.uio_iovcnt = 1;
        u.uio_offset = base;
        u.uio_resid  = 300;
        u.uio_segflg = UIO_SYSSPACE;
        u.uio_rw     = UIO_WRITE;
        if (spec_write(devvp, &u, 0, (char *)0) != 0)
            return (37);
        if (u.uio_resid != 0)
            return (28);

        /* 5c. READ THE WHOLE BLOCK BACK, through spec_read.  This checks both
         * halves of the claim at once: the 300 new bytes are there, and the
         * 724 the partial write did not touch still hold what 5a put on the
         * device.  A spec_write that used getblk for the partial case would
         * hand back a buffer of whatever the cache happened to hold and the
         * remainder would be wrong here.
         *
         * It also reads through the DIRTY buffer bdwrite left behind, which is
         * the case the cache's B_DELWRI hit-test exists for -- the bytes are
         * not on the device yet and must still be what a reader sees. */
        for (i = 0; i < FS_BLKSIZE; i++)
            specbuf[i] = (char)0;
        iv.iov_base  = specbuf;
        iv.iov_len   = FS_BLKSIZE;
        u.uio_iov    = &iv;
        u.uio_iovcnt = 1;
        u.uio_offset = base;
        u.uio_resid  = FS_BLKSIZE;
        u.uio_segflg = UIO_SYSSPACE;
        u.uio_rw     = UIO_READ;
        if (spec_read(devvp, &u, 0, (char *)0) != 0)
            return (29);
        if (u.uio_resid != 0)
            return (30);
        if (u.uio_offset != base + (off_t)FS_BLKSIZE)
            return (31);
        for (i = 0; i < 300; i++)
            if (specbuf[i] != (char)(0x90 + (i & 15)))
                return (32);
        /* The remainder is the RAW pattern, which only a bread could have
         * brought back -- no buffer ever contained it. */
        for (i = 300; i < DEV_BLKSIZE; i++)
            if (specbuf[i] != (char)(0xA0 + (i & 15)))
                return (33);
        for (i = DEV_BLKSIZE; i < FS_BLKSIZE; i++)
            if (specbuf[i] != (char)(0xB0 + ((i - DEV_BLKSIZE) & 15)))
                return (33);

        /* 5d. A READ THAT STRADDLES TWO BLOCKS.  Everything above fits in one,
         * so the do/while has never gone round -- a spec_read that handled
         * only the first block would pass all of it.  Starting half a block in
         * and asking for a full block spans fsblk and fsblk+1, which also
         * exercises the non-zero `on` offset within the first. */
        for (i = 0; i < FS_BLKSIZE; i++)
            specbuf[i] = (char)0;
        iv.iov_base  = specbuf;
        iv.iov_len   = FS_BLKSIZE;
        u.uio_iov    = &iv;
        u.uio_iovcnt = 1;
        u.uio_offset = base + (off_t)(FS_BLKSIZE / 2);
        u.uio_resid  = FS_BLKSIZE;
        u.uio_segflg = UIO_SYSSPACE;
        u.uio_rw     = UIO_READ;
        if (spec_read(devvp, &u, 0, (char *)0) != 0)
            return (34);
        if (u.uio_resid != 0)
            return (35);
        /* The first half of what came back is the SECOND half of fsblk -- the
         * 0xB0 device block, which 5b's 300-byte write did not reach. */
        for (i = 0; i < FS_BLKSIZE / 2; i++)
            if (specbuf[i] != (char)(0xB0 + (i & 15)))
                return (36);
    }

    vrele(devvp);
    return (0);
}
