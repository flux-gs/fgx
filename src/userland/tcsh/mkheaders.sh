#!/bin/sh
# mkheaders.sh OUTDIR -- tcsh's three build-generated headers, made from the
# vendored source exactly as its Makefile makes them (Makefile:298-319):
# ed.defns.h from ed.defns.c, sh.err.h from sh.err.c (unifdef -Dpdp11, the
# 2.11BSD SYSDEFINE), tc.const.h from the host preprocessor over tc.const.c.
#
# Each is a pipeline into a file, so a missing tool or a failed preprocess
# would write a valid but EMPTY header and every tcsh TU would then fail with
# "'STRNULL' undeclared" far from the cause.  So the tools are required up
# front and each header's size is checked after.
set -u
# `sort' orders by the locale's collation, so tc.const.h (and through it the
# tcsh binary) came out differently under a Mac's en_US.UTF-8 than under a CI
# runner's C.UTF-8.  The C locale makes it a function of the source alone.
export LC_ALL=C
OUT=$1
TSRC=vendor/2.11BSD/usr/bin/tcsh
SHIM=src/userland/tcsh
for t in egrep sed sort unifdef cc; do
  command -v "$t" >/dev/null \
    || { echo "mkheaders: required tool '$t' not on PATH (Debian: apt-get install unifdef)" >&2; exit 2; }
done
mkdir -p "$OUT"

{ echo '/* Do not edit this file, make creates it. */'
  echo '#ifndef _h_ed_defns'; echo '#define _h_ed_defns'
  egrep '[FV]_' "$TSRC/ed.defns.c" | egrep '^#define'
  echo '#endif /* _h_ed_defns */'; } > "$OUT/ed.defns.h"

{ echo '/* Do not edit this file, make creates it. */'
  echo '#ifndef _h_sh_err'; echo '#define _h_sh_err'
  unifdef -Dpdp11 "$TSRC/sh.err.c" | egrep 'ERR_' | egrep '^#define'
  echo '#endif /* _h_sh_err */'; } > "$OUT/sh.err.h"

{ echo '/* Do not edit this file, make creates it. */'
  cc -E -Dpdp11 -I"$OUT" -I"$SHIM" -I"$TSRC" -Itoolchain/include "$TSRC/tc.const.c" \
    | egrep 'Char STR' | sed -e 's/Char \([a-zA-Z0-9_]*\)\(.*\)/extern Char \1[];/' | sort -u
} > "$OUT/tc.const.h"

check() {   # <file> <min-symbols> <pattern>
  n=$(egrep -c "$3" "$1" 2>/dev/null || echo 0)
  [ "$n" -ge "$2" ] || { echo "mkheaders: $1 has $n symbols (expected >= $2)" >&2; exit 2; }
}
check "$OUT/ed.defns.h" 50 '^#define'
check "$OUT/sh.err.h"   80 '^#define'
check "$OUT/tc.const.h" 100 '^extern Char'
